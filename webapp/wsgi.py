"""Точка входа для боевого сервера (gunicorn), не для локальной разработки.

Зачем отдельный файл, а не запуск webapp/app.py:

  · app.py в блоке __main__ поднимает встроенный сервер Flask на 127.0.0.1.
    Внутри контейнера этот адрес виден только самому контейнеру, и обратный
    прокси до него не достучится. Менять хост в app.py не хочется: локальный
    запуск должен остаться ровно таким же, каким был.

  · прогрев кэшей там же, в __main__. Под gunicorn этот блок не выполняется,
    и без прогрева первые открытия страниц упираются в сборку данных на лету.
    Здесь мы запускаем прогрев сами — тем же фоновым потоком.

Запуск на сервере:
    gunicorn --bind 0.0.0.0:8000 --workers 1 --threads 8 webapp.wsgi:app

Воркер намеренно один: app.py держит разобранные свечи и аналитику в модульных
кэшах, у каждого процесса они были бы свои — память умножилась бы на число
воркеров, а попадания в кэш стали бы реже. Параллельность даём потоками.
"""

import threading

from webapp.app import _warmup, app  # noqa: F401  (app — то, что запускает gunicorn)

threading.Thread(target=_warmup, daemon=True).start()
