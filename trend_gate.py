"""Режим по дневной средней — ОДИН источник для бэктеста, витрины и живого бота.

ЗАЧЕМ. Проверка вперёд показала точную причину провала LTCUSDT/final_wf: рынок
вырос на 22% за 22 дня, а почти чисто шортовый бот потерял 26.8%. В геноме
нет ни одного фильтра длиннее шести дней (EMA 600 баров по 15 минут), так что
«многонедельный рост» бот увидеть не может в принципе. Запрет шорта в росте —
единственная правка за историю проекта, положительная на невиданных 973 днях,
обучении и холдоуте сразу (см. память bbbot-uptrend-gate-hypothesis).

ОПРЕДЕЛЕНИЕ. День d считается днём РОСТА, если закрытие дня d-1 выше простой
средней дневных закрытий за n дней по d-1 включительно; днём ПАДЕНИЯ — если
ниже; 0 — данных меньше n дней (или закрытие равно средней). Любой бар дня d
получает режим дня d, то есть решение принимается только по ЗАВЕРШЁННЫМ
дням: заглядывания в будущее нет по построению.

ГЕЙТ (ген trend_days = n > 0): шорт разрешён только в падении, лонг — только в
росте, при неизвестном режиме не разрешено ничего. trend_days = 0 — выключено.

ПОЧЕМУ ОДИН МОДУЛЬ. У vol_gate определение жило в трёх местах, и четвёртый
потребитель (симуляция на странице бота) его не знал — числа разошлись в 2.7
раза по сделкам. Здесь regime_last (живой бот, по списку закрытий) и
regime_series (бэктест, по бару) — одна и та же арифметика, и тест
test_configs.test_trend_gate_one_definition требует их совпадения.

ДАННЫЕ. Дневные свечи берутся отдельно от 15-минутного окна (evolution.fetch с
интервалом "D"), с запасом EXTRA_DAYS до начала окна — иначе первые n дней
окна были бы «неизвестными» и не торговались бы.
"""
DAY = 86400000
EXTRA_DAYS = 400          # запас дневной истории до начала 15м-окна
OFF = dict(trend_days=0)  # «выключено» — для with_defaults и rand_core


def daily_closes(symbol, days):
    """[(начало_дня_мс, close)] по завершённым дням, по возрастанию."""
    import evolution as ev
    return [(int(r[0]), float(r[4])) for r in ev.fetch(symbol, "D", days)]


def regime_last(closes, n):
    """Режим СЛЕДУЮЩЕГО дня по списку закрытий завершённых дней.

    closes — подряд, последний элемент = вчерашнее закрытие. Это то, что
    считает живой бот: он берёт n+ завершённых дневных свечей с биржи и
    спрашивает, можно ли сегодня входить.
    """
    n = int(n or 0)
    if n <= 0 or len(closes) < n:
        return 0
    sma = sum(closes[-n:]) / n
    c = closes[-1]
    return 1 if c > sma else (-1 if c < sma else 0)


def regime_series(bar_ts, daily, n):
    """Режим на каждый бар. daily — то, что отдаёт daily_closes.

    Для дня k дневного ряда считается режим ДНЯ ПОСЛЕ k (по закрытию k и
    средней по k включительно); бар с меткой t получает режим дня t//DAY,
    то есть значение, посчитанное по дню t//DAY - 1. Если этого дня в ряду
    нет (пропуск на бирже) — 0, торговли нет: неизвестное трактуется как
    запрет, а не как разрешение.
    """
    n = int(n or 0)
    if n <= 0:
        return [0] * len(bar_ts)
    closes = [c for _, c in daily]
    idx = {t // DAY: k for k, (t, _) in enumerate(daily)}
    after = [0] * len(closes)
    s = 0.0
    for k in range(len(closes)):
        s += closes[k]
        if k >= n:
            s -= closes[k - n]
        if k >= n - 1:
            sma = s / n
            after[k] = 1 if closes[k] > sma else (-1 if closes[k] < sma else 0)
    out = []
    for t in bar_ts:
        k = idx.get(int(t) // DAY - 1)
        out.append(after[k] if k is not None else 0)
    return out


def gate(filt, reg):
    """Обернуть фильтр входа режимом: шорт только в падении, лонг — в росте."""
    def f(side, i):
        r = reg[i] if i < len(reg) else 0
        if r == 0:
            return None
        if side == "S" and r > 0:
            return None
        if side == "L" and r < 0:
            return None
        return filt(side, i) if filt else side
    return f
