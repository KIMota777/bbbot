# -*- coding: utf-8 -*-
"""Семейство импульса: если рынок уже пошёл — пойдёт ли он дальше.

ОБЩАЯ ГИПОТЕЗА СЕМЕЙСТВА. Доходность актива не полностью независима от своего
недавнего прошлого: на средних горизонтах (от нескольких дней до нескольких
недель) знак прошлой доходности слабо, но систематически предсказывает знак
будущей. Причина не в графике, а в людях и деньгах: новость всасывается в цену
не мгновенно, крупный участник набирает позицию частями и растягивает движение,
управляющие докупают то, что уже выросло, а к тому, что упало, никто не хочет
подходить. На коротких горизонтах картина обратная — там правит откат, поэтому
слишком быстрый импульс работать не должен и это тоже надо увидеть в числах.

ЧТО ЗДЕСЬ ПРОВЕРЯЕТСЯ, ПО СТРАТЕГИЯМ
  tsmom            — просто знак доходности за n баров; сама классика;
  roc_thresh       — скорость должна не просто быть положительной, а превышать
                     порог: слабое шевеление — это шум, за него платят комиссию;
  multi_mom        — согласие импульса сразу на трёх горизонтах (1, 3 и 6
                     недель), то есть требование, чтобы движение было длинным,
                     а не однодневным всплеском;
  vol_adj_mom      — импульс, делённый на собственную волатильность: 5% за
                     неделю в спокойном рынке и 5% в штормовом — это разные
                     события, и мерить их одной линейкой нельзя;
  accel            — вторая производная: важен не сам импульс, а его РОСТ;
  mom_continuation — пробой уровня, но только по направлению большого импульса.

ЧЕГО ЖДАТЬ ОТ ЧИСЕЛ, ЗАРАНЕЕ И ЧЕСТНО. Круговая сделка стоит около 0.16% от
объёма позиции. Импульс на часовых барах — вещь дешёвая в производстве сигналов
и дорогая в исполнении: чем короче горизонт, тем больше входов, тем вернее
комиссия съест весь перевес. Поэтому в сетках намеренно есть и короткие, и
длинные горизонты — чтобы увидеть, где именно проходит граница, за которой
издержки побеждают. Отрицательный ответ здесь такой же результат, как
положительный.

Всё, что касается размера позиции, плеча и комиссий, живёт в движке. Здесь —
только «куда» и «где стоп».
"""
import numpy as np

import ind
import strat
from engine import Signals


# --- маленькие вспомогательные вещи, которых нет в ind.py -------------------
#
# В ind.py есть roc — арифметическая скорость. Для импульса удобнее логарифм:
# логарифмические доходности складываются по времени и живут в одной шкале с
# сигмой лог-доходностей, поэтому деление импульса на волатильность получается
# осмысленным, а не приблизительным. Ради одной формулы трогать чужой файл
# незачем, поэтому она лежит здесь.


def _log_mom(c, n):
    """Импульс за n баров: логарифм отношения цены к цене n баров назад.

    Значение на баре i опирается на бары i-n и i — оба уже случились.
    """
    out = np.full(len(c), np.nan)
    if n > 0 and len(c) > n:
        out[n:] = np.log(np.maximum(c[n:], 1e-12) / np.maximum(c[:-n], 1e-12))
    return out


def _shift(x, k):
    """Значение k баров назад. Сдвиг только в прошлое — другого не бывает."""
    out = np.full(len(x), np.nan)
    if 0 < k < len(x):
        out[k:] = x[:-k]
    return out


def _rise(cond):
    """Бары, на которых условие ВПЕРВЫЕ стало верным.

    Разница между «условие верно» и «условие только что стало верным» —
    принципиальная. В первом случае стратегия просится в рынок каждый бар и
    после каждого выбитого стопа лезет обратно в то же место. Во втором она
    входит один раз на событие. Обе повадки имеют право на жизнь, но их надо
    различать осознанно, а не случайно.
    """
    out = np.zeros(len(cond), dtype=bool)
    out[1:] = cond[1:] & ~cond[:-1]
    return out


# --- 1. tsmom: знак доходности за n баров ----------------------------------

@strat.register("tsmom", "momentum", {
    "n": [24, 48, 96, 168, 336],          # сутки, двое, четверо, неделя, две
    "stop_atr": [2.0, 3.0, 4.0],
    "trail_atr": [0.0, 4.0],
    "persist": [0, 1],
    "atr_n": [14],
}, "знак доходности за n баров — классика управляемых фьючерсов")
def s_tsmom(bars, p):
    """Самый грубый вопрос, который можно задать рынку: рос ли он последнее время.

    Гипотеза без единого украшения: если за прошедшие n баров цена выше, чем
    была, то и следующий отрезок скорее вверх. На этом с семидесятых годов
    стоят фонды управляемых фьючерсов, и на акциях, облигациях, валютах и
    товарах эффект держится десятилетиями. Крипта моложе и шумнее, зато
    трендов в ней больше — значит, если импульс где-то и жив, то здесь.

    Ключ к пониманию результата — параметр persist. При persist=0 вход только в
    момент СМЕНЫ знака: один вход на одно движение. При persist=1 сигнал стоит,
    пока стоит знак, и после выбитого стопа стратегия возвращается в тот же
    тренд. Второе честнее к исходной идее (в оригинале стопа вовсе нет), но
    дороже: боковик заставляет платить комиссию раз за разом.
    """
    n = len(bars.t)
    m = _log_mom(bars.c, int(p["n"]))
    up, dn = m > 0, m < 0                  # непрогретый участок NaN -> False
    e = np.zeros(n, dtype=np.int8)
    if p["persist"]:
        e[up] = 1
        e[dn] = -1
    else:
        e[_rise(up)] = 1
        e[_rise(dn)] = -1
    return strat.finish(bars, p, Signals(n), e)


# --- 2. roc_thresh: скорость выше порога -----------------------------------

@strat.register("roc_thresh", "momentum", {
    "n": [12, 24, 48, 96],
    "thr": [0.005, 0.01, 0.02, 0.04],     # 0.5% .. 4% за окно
    "stop_atr": [2.0, 3.0],
    "rr": [0.0, 2.0],
    "atr_n": [14],
}, "вход, когда скорость изменения цены вышла за порог; выход — когда вернулась")
def s_roc_thresh(bars, p):
    """Не всякое движение вверх — движение. Мелкое шевеление стоит дороже, чем даёт.

    Гипотеза уточняет предыдущую. Знак доходности меняется постоянно, и почти
    всегда это шум: цена дёрнулась на десятую долю процента и вернулась. Порог
    отсекает мелочь и оставляет только те эпизоды, где за окно набежало
    заметное расстояние — а заметное расстояние обычно означает, что в рынок
    зашли деньги, и они редко заходят одним куском.

    Выход зеркален входу: как только скорость упала обратно внутрь порога,
    повод держать позицию исчерпан. Это выход по угасанию, а не по убытку, и он
    закрывает сделку раньше, чем стоп, — импульсные сделки чаще умирают от
    скуки, чем от разворота.

    Слабое место видно заранее и его надо назвать: порог задан в процентах и
    одинаков для спокойного и штормового рынка. В 2023-м 2% за сутки — событие,
    в марте 2024-го — обычный день. Ровно эту болезнь лечит vol_adj_mom, и
    сравнение двух стратегий как раз и покажет, чего стоит лечение.
    """
    n = len(bars.t)
    r = ind.roc(bars.c, int(p["n"]))
    thr = float(p["thr"])
    e = np.zeros(n, dtype=np.int8)
    e[_rise(r > thr)] = 1
    e[_rise(r < -thr)] = -1
    ex = np.abs(r) < thr                   # скорость вернулась в болото
    return strat.finish(bars, p, Signals(n), e, ex)


# --- 3. multi_mom: согласие нескольких горизонтов ---------------------------

@strat.register("multi_mom", "momentum", {
    "base": [56, 84, 168, 252],            # опорный горизонт в часах
    "need": [2, 3],                        # сколько горизонтов из трёх согласны
    "stop_atr": [2.0, 3.0, 4.0],
    "trail_atr": [0.0, 4.0],
    "atr_n": [14],
}, "импульс на трёх горизонтах (base, 3*base, 6*base) смотрит в одну сторону")
def s_multi_mom(bars, p):
    """Одно окно легко обмануть одним всплеском. Три окна разом — гораздо труднее.

    Гипотеза: настоящее направленное движение оставляет след на всех масштабах
    сразу — и на неделе, и на трёх, и на полутора месяцах. А случайный выброс
    виден только на том окне, в которое он попал. Требование согласия работает
    как фильтр подлинности: мы отказываемся от части входов ради того, чтобы
    оставшиеся были похожи на настоящий тренд, а не на один нервный день.

    Горизонты берутся кратными опорному (1, 3 и 6), примерно как неделя, три
    недели и полтора месяца при base=168 часов. Кратность не подгонялась: она
    взята из литературы по акциям, где классические окна 1, 3, 6 и 12 месяцев,
    и просто пересчитана в часы.

    Параметр need отделяет строгую версию от мягкой: 3 — согласны все, 2 —
    большинство. Строгая даёт мало входов и позднее, мягкая больше и раньше.
    Что важнее — чистота сигнала или его своевременность — это и есть вопрос,
    на который отвечает перебор.

    Выход — по распаду согласия: как только горизонты разошлись, повод исчез.
    Условие симметрично и одинаково верно для длинной и короткой позиции.
    """
    n = len(bars.t)
    b = int(p["base"])
    pos_cnt = np.zeros(n)
    neg_cnt = np.zeros(n)
    ready = np.ones(n, dtype=bool)         # все три окна досчитаны
    for h in (b, 3 * b, 6 * b):
        m = _log_mom(bars.c, h)
        ready &= ~np.isnan(m)
        pos_cnt += (m > 0)
        neg_cnt += (m < 0)
    need = int(p["need"])
    al = ready & (pos_cnt >= need)
    ash = ready & (neg_cnt >= need)
    e = np.zeros(n, dtype=np.int8)
    e[_rise(al)] = 1
    e[_rise(ash)] = -1
    ex = ready & ~al & ~ash
    return strat.finish(bars, p, Signals(n), e, ex)


# --- 4. vol_adj_mom: импульс на свою волатильность --------------------------

@strat.register("vol_adj_mom", "momentum", {
    "n": [48, 96, 168, 336],
    "thr": [0.75, 1.25],                   # в сигмах ожидаемого хода
    "vol_n": [96, 168],
    "stop_atr": [2.5, 3.5],
    "voltarget": [0.0, 0.05],
    "atr_n": [14],
}, "импульс, делённый на собственную волатильность: сравнимость режимов")
def s_vol_adj_mom(bars, p):
    """Один и тот же процент значит разное в тихом и в штормовом рынке.

    Гипотеза та же — доходность цепляется за свой знак, — но измеряется в
    правильных единицах. Если за n баров цена прошла m, а обычный размах за
    столько же баров равен sigma*sqrt(n), то отношение m/(sigma*sqrt(n))
    показывает, во сколько раз движение крупнее привычного. Единица означает
    «ход размером в одно стандартное отклонение»: примерно то, что случается
    само собой. Два — уже событие.

    Зачем это нужно. Порог в процентах приходится подкручивать каждый год,
    потому что волатильность крипты гуляет в разы; порог в сигмах не приходится.
    Тот же приём делает сигнал переносимым между монетами: DOGE шумит втрое
    против BTC, и в процентах их пороги несравнимы, а в сигмах — вполне.

    Дополнительно проверяется нормировка РАЗМЕРА позиции по волатильности
    (voltarget): в спокойном рынке позиция крупнее, в штормовом мельче, риск в
    деньгах ровнее. Это не улучшение сигнала, а выравнивание риска, и сравнение
    voltarget=0 против 0.05 показывает, стоит ли оно того.

    Выход с запасом (порог/2), а не ровно по порогу: у самой границы значение
    дрожит, и без запаса стратегия входила бы и выходила на соседних барах,
    оплачивая каждое такое дрожание комиссией.
    """
    n = len(bars.t)
    nn = int(p["n"])
    m = _log_mom(bars.c, nn)
    rv = ind.realized_vol(bars.c, int(p["vol_n"]))
    scale = rv * np.sqrt(nn)               # ожидаемый размах за n баров
    z = np.where(scale > 0, m / np.where(scale > 0, scale, 1.0), np.nan)
    thr = float(p["thr"])
    e = np.zeros(n, dtype=np.int8)
    e[_rise(z > thr)] = 1
    e[_rise(z < -thr)] = -1
    ex = np.abs(z) < thr * 0.5
    return strat.finish(bars, p, Signals(n), e, ex)


# --- 5. accel: импульс должен расти -----------------------------------------

@strat.register("accel", "momentum", {
    "n": [24, 48, 96, 168],
    "lag": [12, 24, 48],                   # с чем сравниваем импульс
    "need_sign": [0, 1],                   # требовать ли ещё и m > 0
    "stop_atr": [2.0, 3.0],
    "atr_n": [14],
}, "вторая производная: важен не сам импульс, а его рост")
def s_accel(bars, p):
    """Тренд стареет. Ускорение отличает молодое движение от доживающего.

    Гипотеза: положительный импульс — слишком слабое условие, потому что он
    остаётся положительным и тогда, когда движение уже выдохлось и цена
    ползёт вбок на старых заслугах. Нарастающий импульс означает, что приток
    денег продолжается прямо сейчас, а не продолжался неделю назад. Кроме того,
    ускорение опережает знак: оно разворачивается раньше, чем сам импульс
    успевает сменить сторону, и потому даёт более ранний вход.

    Обратная сторона ровно там же. Вторая производная — это разность двух
    зашумлённых величин, и шума в ней вдвое больше. Ускорение мечется, входов
    получается много, комиссия набегает быстро. Отсюда параметр need_sign: при
    единице требуется не только рост импульса, но и его положительность — то
    есть ускорение внутри уже существующего тренда, а не разгон из ниоткуда.
    Сравнение нуля и единицы прямо отвечает на вопрос, нужен ли этому семейству
    страховочный якорь.
    """
    n = len(bars.t)
    m = _log_mom(bars.c, int(p["n"]))
    a = m - _shift(m, int(p["lag"]))
    up, dn = a > 0, a < 0
    if p["need_sign"]:
        up = up & (m > 0)
        dn = dn & (m < 0)
    e = np.zeros(n, dtype=np.int8)
    e[_rise(up)] = 1
    e[_rise(dn)] = -1
    return strat.finish(bars, p, Signals(n), e)


# --- 6. mom_continuation: пробой только по ветру ---------------------------

@strat.register("mom_continuation", "momentum", {
    "n": [24, 48, 96],                     # окно пробиваемого канала
    "mom_n": [96, 168, 336],               # окно подтверждающего импульса
    "exit_n": [12, 24],
    "stop_atr": [2.5, 3.5],
    "trail_atr": [0.0, 4.0],
    "atr_n": [14],
}, "пробой канала, но только по направлению большого импульса")
def s_mom_continuation(bars, p):
    """Половина пробоев ложные. Отличать их предлагается по тому, куда дует ветер.

    Гипотеза складывается из двух. Пробой уровня запускает механику выноса
    стопов и входа опоздавших — это событие, дающее толчок. Импульс на большом
    окне говорит, в какую сторону этот толчок имеет шанс перерасти в движение.
    Пробой вверх посреди месячного падения чаще всего оказывается отскоком, за
    которым продолжается падение; пробой вверх внутри месячного роста — обычным
    продолжением. То есть импульс здесь не источник сигнала, а фильтр
    правдоподобия для чужого сигнала.

    Заведомо больное место: пробой и импульс сильно связаны между собой. Новый
    максимум канала почти всегда сопровождается положительной доходностью за
    последние недели, поэтому фильтр может отсеивать куда меньше, чем кажется,
    и вся конструкция рискует оказаться пробоем в дорогой упаковке. Проверка
    честная только при разнесённых окнах: канал короткий, импульс длинный,
    и mom_n в сетке заметно больше n.

    Выход — по обратному каналу, как у черепах: движение считается законченным,
    когда цена уходит за экстремум коротких exit_n баров ПРОТИВ позиции. Чтобы
    выход был направленным, а не симметричной кашей, стратегия ведёт
    собственный счётчик направления: он меняется только по уже случившимся
    барам и потому не нарушает причинности. Настоящая позиция в движке может
    отличаться (её мог выбить стоп), но лишний приказ «закрыть» безвреден —
    закрывать будет нечего.
    """
    n = len(bars.t)
    hi, lo = ind.donchian(bars.h, bars.l, int(p["n"]))
    xh, xl = ind.donchian(bars.h, bars.l, int(p["exit_n"]))
    m = _log_mom(bars.c, int(p["mom_n"]))
    c = bars.c
    long_in = ((c > hi) & (m > 0)).tolist()
    short_in = ((c < lo) & (m < 0)).tolist()
    cl, xhl, xll = c.tolist(), xh.tolist(), xl.tolist()

    e = np.zeros(n, dtype=np.int8)
    ex = np.zeros(n, dtype=bool)
    st = 0                                  # -1/0/+1 — куда смотрит стратегия
    for i in range(n):
        if st > 0 and cl[i] < xll[i]:       # сравнение с NaN даёт False
            st, ex[i] = 0, True
        elif st < 0 and cl[i] > xhl[i]:
            st, ex[i] = 0, True
        if long_in[i] and st <= 0:
            e[i], st = 1, 1
        elif short_in[i] and st >= 0:
            e[i], st = -1, -1
    return strat.finish(bars, p, Signals(n), e, ex)


