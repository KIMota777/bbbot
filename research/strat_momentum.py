def _sample(combos, k=24, seed=0):
    """Не больше k сочетаний; если их больше — случайные, но воспроизводимо."""
    if len(combos) <= k:
        return combos
    rng = np.random.default_rng(seed)
    idx = sorted(int(i) for i in rng.choice(len(combos), k, replace=False))
    return [combos[i] for i in idx]


def _short(p):
    """Короткая подпись сочетания — в brief на ярлык отведено 22 знака."""
    skip = ("atr_n",)
    return " ".join("%s%g" % (k[:3], v) for k, v in sorted(p.items())
                    if k not in skip and v)


