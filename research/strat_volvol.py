if __name__ == "__main__":
    import random
    import sys

    import engine
    import metrics

    bars, _ = rdata.load_bars("BTCUSDT", "60").slice(*rdata.SPLITS["train"])
    print("Проверка на BTCUSDT 1ч, часть train: %d баров\n" % len(bars.t))

    print("1. Размер сетки (по протоколу 8..72 сочетания)")
    bad_grid = []
    for name in NAMES:
        k = strat.REG[name].n_combos()
        good = 8 <= k <= 72
        if not good:
            bad_grid.append(name)
        print("  %s %-18s %3d сочетаний" % ("+" if good else "!", name, k))

    print("\n2. Причинность: сигналы до среза не меняются от порчи будущего")
    fails = []
    for name in NAMES:
        st = strat.REG[name]
        combos = list(st.combos())
        total = len(combos)
        if total > 24:
            combos = random.Random(0).sample(combos, 24)
        try:
            for p in combos:
                engine.assert_causal(lambda x, s=st, q=p: s.build(x, q), bars)
            print("  + %-18s %2d из %2d сочетаний причинны"
                  % (name, len(combos), total))
        except AssertionError as exc:
            fails.append(name)
            print("  ! %-18s %s" % (name, str(exc)[:100]))

    print("\n3. Показательные прогоны (риск 1% на сделку, комиссия и фандинг"
          " как на бирже)")
    # DSR — вероятность, что настоящий Шарп больше нуля, ПОСЛЕ поправки на
    # число попыток. Считаем поправку по всей сетке стратегии, а не по одному
    # показанному сочетанию: искали-то мы во всей сетке.
    cfg = engine.Cfg()
    for name, tag, p in DEMOS:
        st = strat.REG[name]
        sig = st.build(bars, p)
        res = engine.run(bars, sig, cfg)
        s = metrics.summarize(res, n_trials=st.n_combos(), label=tag)
        print("  %-17s %s | DSR %.2f" % (name, metrics.brief(s), s["dsr"]))

    # --- отдельная диагностика, не результат исследования -----------------
    # Ставки фандинга в файлах funding_*.json записаны В ПРОЦЕНТАХ (0.01 —
    # это 0.01% за расчёт), а rdata.funding_paid умножает их на объём как
    # доли. Выходит стократная переплата: медиана по BTC даёт 736% годовых от
    # объёма позиции вместо примерно 7%. Для сделок на несколько часов это
    # мелочь, для сделок на недели — приговор, и он достаётся не той
    # стратегии, которая его заслужила, а той, которая дольше держит.
    # Чужие файлы я не правлю; ниже — прогон тех же сочетаний с выключенным
    # фандингом, чтобы видеть, где вывод держится на сигнале, а где на этой
    # ошибке. Правильные числа лежат между двумя таблицами, ближе к нижней.
    print("\n4. То же с выключенным фандингом (диагностика ошибки масштаба"
          " ставок, см. комментарий в коде)")
    cfg_nf = engine.Cfg(funding=False)
    for name, tag, p in DEMOS:
        st = strat.REG[name]
        res = engine.run(bars, st.build(bars, p), cfg_nf)
        s = metrics.summarize(res, n_trials=st.n_combos(), label=tag)
        print("  %-17s %s | держ %4.0f б"
              % (name, metrics.brief(s), s["avg_hold"]))

    print("\nИтог: сетки %s, причинность %s"
          % ("в норме" if not bad_grid else "нарушены: " + ", ".join(bad_grid),
             "чиста" if not fails else "провалена: " + ", ".join(fails)))
    sys.exit(1 if (fails or bad_grid) else 0)
