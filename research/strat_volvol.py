@strat.register("vol_regime", "volatility", {
    "regime": [1, -1],
    "q": [0.6, 0.75],
    "rank_n": [200, 400],
    "ma": [50, 100, 200],
    "stop_atr": [2.0, 3.0],
    "atr_n": [14],
}, "трендовое правило, включённое только в выбранном режиме волатильности")
def s_vol_regime(bars, p):
    """Одна и та же трендовая идея, но включённая только в своём климате.

    Гипотеза: рынок не однороден во времени. В тихой фазе цену держат
    маркетмейкеры, движения гасятся, и следование за трендом отдаёт деньги по
    кусочку. В бурной фазе работают потоки ликвидаций и вынужденных покупок,
    и начатое движение доводится до конца. Если это правда, то трендовое
    правило должно зарабатывать в верхнем перцентиле ATR и терять в нижнем —
    и разница между regime=+1 и regime=-1 покажет это без всяких ухищрений.

    Режим меряется перцентилем ATR за rank_n баров, а не его абсолютной
    величиной: «ATR равен 300 долларов» ничего не значит, «ATR выше, чем в 75%
    случаев за последний месяц» значит.

    Выход по потере режима намеренный: если гипотеза про климат верна, то
    досиживать сделку в чужом климате незачем.
    """
    n = len(bars.t)
    a = ind.atr(bars.h, bars.l, bars.c, int(p.get("atr_n", 14)))
    rank = ind.rolling_rank(a, int(p["rank_n"]))
    # ATR на прогреве — NaN, а rolling_rank превращает его в ноль. Ноль в этом
    # ряду читается как «волатильность ниже некуда» и открыл бы поток ложных
    # сделок в самом начале выборки, поэтому непрогретое отсекаем явно.
    fin = np.isfinite(a) & np.isfinite(rank)
    q = float(p["q"])
    ok = (rank >= q) if int(p["regime"]) > 0 else (rank <= 1.0 - q)
    ok = ok & fin

    ma = ind.ema(bars.c, int(p["ma"]))
    up = bars.c > ma
    dn = bars.c < ma

    e = np.zeros(n, dtype=np.int8)
    e[_start(ok & up)] = 1
    e[_start(ok & dn)] = -1
    return strat.finish(bars, p, Signals(n), e, ~ok)


@strat.register("vol_expansion", "volatility", {
    "squeeze_q": [0.25, 0.4],
    "burst_q": [0.6, 0.75],
    "look": [6, 12, 24],
    "rank_n": [200],
    "stop_atr": [2.0, 3.0],
    "rr": [0.0, 2.0],
    "atr_n": [14],
}, "переход из низкой волатильности в высокую, сторона — по телу бара")
def s_vol_expansion(bars, p):
    """Сжатая пружина: узкий рынок долго не бывает узким.

    Гипотеза известна как кластеризация волатильности и держится на механике,
    а не на вере. Пока рынок стоит, стопы и отложенные заявки скапливаются по
    обе стороны узкого коридора. Первый же удар по одной из сторон снимает
    этот запас и порождает движение, которое кормит само себя. Значит вход
    имеет смысл не когда волатильность высокая (там уже поздно), а именно
    в момент ПЕРЕХОДА из низкой в высокую.

    Сторону берём у бара, который расширение и устроил: тело вверх — идём
    вверх. Никакого отдельного трендового фильтра тут нет намеренно, иначе
    непонятно, что проверяем — расширение или тренд.

    Выходим, когда пружина сжалась обратно (перцентиль ATR вернулся в нижний
    коридор). Иначе сделка, открытая по гипотезе про расширение, продолжает
    жить месяцами уже безо всякого расширения — и проверяет что угодно, только
    не заявленную идею.
    """
    n = len(bars.t)
    a = ind.atr(bars.h, bars.l, bars.c, int(p.get("atr_n", 14)))
    rank = ind.rolling_rank(a, int(p["rank_n"]))
    fin = np.isfinite(a) & np.isfinite(rank)
    low = (rank <= float(p["squeeze_q"])) & fin
    high = (rank >= float(p["burst_q"])) & fin

    look = int(p["look"])
    # был ли штиль в предыдущие look баров — смотрим строго назад, поэтому
    # окно максимума сдвинуто на бар
    was_low = _back(ind.rolling_max(low.astype(np.float64), look), 1)
    fire = _start(high) & (was_low > 0.5)

    body = bars.c - bars.o
    e = np.zeros(n, dtype=np.int8)
    e[fire & (body > 0)] = 1
    e[fire & (body < 0)] = -1
    return strat.finish(bars, p, Signals(n), e, low)


@strat.register("vol_target_trend", "volatility", {
    "voltarget": [0.0, 0.03, 0.05, 0.08],
    "fast": [20, 50],
    "slow": [100, 200],
    "vol_n": [48, 96],
    "stop_atr": [3.0],
    "atr_n": [14],
}, "пересечение средних плюс нормировка размера под целевую волатильность")
def s_vol_target_trend(bars, p):
    """Сигнал тот же, а вот риск в долларах — постоянный.

    Гипотеза не про вход, а про размер. Трендовая идея даёт примерно
    одинаковую доходность на единицу принятого риска, но сам риск скачет в
    разы: одна и та же сделка в спокойном июне и в паническом ноябре — это
    два разных вложения. Если держать целевую волатильность позиции ровной
    (уменьшать объём в шторм, увеличивать в штиль), кривая капитала должна
    стать глаже, а просадка мельче при том же наборе сделок.

    Проверяется прямым сравнением: voltarget=0 — нормировка выключена, размер
    считается только от расстояния до стопа; остальные значения включают её.
    Разница между этими ветками и есть ответ. Стоп уже подстроен под ATR,
    поэтому часть работы сделана и без нормировки — тем интереснее, остаётся
    ли сверх этого хоть что-нибудь.
    """
    n = len(bars.t)
    if int(p["fast"]) >= int(p["slow"]):
        return Signals(n)
    f = ind.ema(bars.c, int(p["fast"]))
    s = ind.ema(bars.c, int(p["slow"]))
    fin = np.isfinite(f) & np.isfinite(s)
    up = f > s
    ch = np.zeros(n, dtype=bool)
    ch[1:] = up[1:] != up[:-1]
    # смена состояния засчитывается, только если обе средние были посчитаны и
    # на этом баре, и на прошлом: иначе первый же прогретый бар выглядит как
    # пересечение
    ok = ch & fin & _prev(fin)
    e = np.zeros(n, dtype=np.int8)
    e[ok & up] = 1
    e[ok & ~up] = -1
    return strat.finish(bars, p, Signals(n), e)


