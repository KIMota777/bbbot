"""Волатильность, объём и VWAP — три соседних способа задать рынку один вопрос.

Все три семейства спрашивают не «куда пойдёт цена», а «стоит ли вообще сейчас
торговать и чья это цена». Волатильность отвечает про состояние рынка: в штиле
и в шторме одна и та же трендовая идея живёт по-разному. Объём отвечает про то,
подкреплено ли движение деньгами или это инерция тонкого стакана. VWAP отвечает
про уровень, вокруг которого крутится реальная торговля: это средняя цена входа
тех, кто сейчас в позиции, и потому естественный магнит и естественный рубеж.

ПРО ОБЪЁМ ОТДЕЛЬНО. У всех четырёх объёмных стратегий есть выключатель
use_volume. Он нужен не для красоты: объём почти всегда «улучшает» результат
на истории просто потому, что добавляет ещё одно сито и режет число сделок,
а меньше сделок — меньше комиссии. Единственный способ отличить это от
настоящего вклада — прогнать ту же самую стратегию без объёма и сравнить.
Поэтому у каждой объёмной стратегии выключенный объём оставляет осмысленный
ценовой скелет: у rvol_break — чистый пробой, у vol_spike — просто большая
свеча, у obv_trend — тот же OBV, но с единичным объёмом (то есть накопленный
знак движения цены), у vol_divergence — вход против экстремума без оглядки
на объём.
Сетка перебирает use_volume вместе с остальным, поэтому пары «с объёмом /
без объёма» получаются автоматически.

Из-за произведения по сетке часть сочетаний с use_volume=0 повторяет друг
друга (порог объёма при выключенном объёме ни на что не влияет). Это
сознательно: так контрольная ветка получает столько же попыток, сколько
основная, и сравнение не смещено в её сторону.

Причинность. Всё считается только по барам 0..i: перцентили — скользящим
окном (ind.rolling_rank), дневной VWAP — нарастающим итогом внутри суток
(ind.vwap_anchored), «а что было раньше» — явными сдвигами назад. Ни одно
значение не нормируется по всей выборке. Проверяется механически в конце файла.
"""
import numpy as np

import ind
import rdata
import strat
from engine import Signals


# --- мелочь, которой нет в ind.py -----------------------------------------

def rel_volume(v, n):
    """Объём бара к своей средней за n баров. Безразмерная величина.

    Абсолютный объём несравним ни между монетами, ни между эпохами одной
    монеты: в 2023-м у BTC на часовом баре торговали одни деньги, в 2026-м
    другие. Отношение к собственной недавней норме сравнимо всегда.
    """
    m = ind.sma(v, n)
    out = np.full(len(v), np.nan)
    ok = np.isfinite(m) & (m > 0)
    out[ok] = v[ok] / m[ok]
    return out


def _prev(mask):
    """Значение маски на предыдущем баре. Первый бар — False."""
    out = np.zeros(len(mask), dtype=bool)
    out[1:] = mask[:-1]
    return out


def _start(mask):
    """Первый бар каждой серии, где условие стало истинным.

    Разница между «условие выполняется» и «условие только что появилось»
    решает судьбу стратегии на издержках. Постоянный сигнал заставляет движок
    открываться заново на следующем же баре после каждого выбитого стопа —
    в один и тот же тренд можно зайти десять раз и десять раз заплатить.
    """
    out = np.zeros(len(mask), dtype=bool)
    out[0] = bool(mask[0])
    out[1:] = mask[1:] & ~mask[:-1]
    return out


def _back(x, k):
    """Ряд, сдвинутый на k баров назад: «что было k баров назад»."""
    out = np.full(len(x), np.nan)
    if k < len(x):
        out[k:] = x[:len(x) - k]
    return out


def _ones(n):
    return np.ones(n, dtype=bool)


