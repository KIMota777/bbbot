@strat.register("vwap_rev", "vwap", {
    "n": [24, 48, 96],
    "k": [1.0, 1.5, 2.0],
    "stop_atr": [2.0, 3.0],
    "rr": [0.0, 1.0],
    "atr_n": [14],
}, "возврат к скользящему VWAP при отклонении больше k*ATR")
def s_vwap_rev(bars, p):
    """Резинка: далеко от средней цены сделок цена не живёт.

    Скользящий VWAP — это средняя цена, по которой реально прошёл оборот
    последних n баров, то есть примерно средняя цена входа всех, кто сейчас в
    позиции. Гипотеза: уход далеко от неё создаёт встречный интерес сразу с
    трёх сторон. Тем, кто в минусе, хочется выйти в ноль; тем, кто исполняет
    крупную заявку, положено брать не хуже VWAP; маркетмейкер, набравший
    перекос, откупает его обратно. Всё это тянет цену к средней.

    Порог меряем в ATR, а не в процентах: одно и то же отклонение в тихую ночь
    — событие, а в день отчёта по инфляции — норма.

    Выход не по тейку, а по касанию VWAP: гипотеза утверждает возврат к
    средней, вот его и берём. Дальше цена уже ничего нам не должна.
    """
    n = len(bars.t)
    vw = ind.vwap_rolling(bars.turnover, bars.v, int(p["n"]))
    a = ind.atr(bars.h, bars.l, bars.c, int(p.get("atr_n", 14)))
    dev = bars.c - vw
    band = float(p["k"]) * a
    fin = np.isfinite(dev) & np.isfinite(band)

    e = np.zeros(n, dtype=np.int8)
    e[_start((dev > band) & fin)] = -1
    e[_start((dev < -band) & fin)] = 1
    sgn = np.sign(np.where(fin, dev, np.nan))
    ex = (sgn * _back(sgn, 1)) < 0        # цена пересекла VWAP — дошла
    return strat.finish(bars, p, Signals(n), e, ex)


@strat.register("vwap_reclaim", "vwap", {
    "hold": [2, 3, 4],
    "look": [6, 12],
    "stop_atr": [2.0, 3.0],
    "rr": [0.0, 1.5, 2.0],
    "atr_n": [14],
}, "возврат за дневной VWAP (сутки UTC) и закрепление на hold баров")
def s_vwap_reclaim(bars, p):
    """Не касание, а закрепление: кто контролирует день, тот его и закончит.

    Дневной VWAP от начала суток UTC — общий ориентир для всех, кто торгует
    внутри дня: пока цена под ним, средний покупатель дня в минусе. Гипотеза:
    сам по себе прокол этой линии ничего не значит, их за день бывает много.
    Значение имеет возврат ПОСЛЕ пребывания на другой стороне и удержание
    hold баров подряд — тогда сторона, которая контролировала день, сдалась,
    и остаток дня чаще идёт против неё.

    Отсюда два условия: закрепление (hold баров подряд по нужную сторону) и
    память (в предыдущие look баров цена была по другую сторону). Без второго
    сигнал вырождается в «цена выше VWAP», а это уже другая стратегия — она
    ниже и называется vwap_trend.

    Оговорка про край выборки: у первого неполного дня VWAP считается от того
    бара, с которого начался кусок данных, а не от полуночи. Это несколько
    десятков баров из тысяч и на выводы не влияет, но знать надо.
    """
    n = len(bars.t)
    vw = ind.vwap_anchored(bars.t, bars.turnover, bars.v, rdata.DAY_MS)
    fin = np.isfinite(vw)
    above = (bars.c > vw) & fin
    below = (bars.c < vw) & fin

    hold = int(p["hold"])
    look = int(p["look"])
    up_hold = ind.rolling_sum(above.astype(np.float64), hold) >= hold - 1e-9
    dn_hold = ind.rolling_sum(below.astype(np.float64), hold) >= hold - 1e-9
    # что было ДО начала закрепления: окно памяти заканчивается там, где
    # серия началась, поэтому сдвиг ровно на hold баров
    was_below = _back(ind.rolling_max(below.astype(np.float64), look), hold)
    was_above = _back(ind.rolling_max(above.astype(np.float64), look), hold)

    e = np.zeros(n, dtype=np.int8)
    e[_start(up_hold) & (was_below > 0.5)] = 1
    e[_start(dn_hold) & (was_above > 0.5)] = -1
    return strat.finish(bars, p, Signals(n), e)


@strat.register("vwap_trend", "vwap", {
    "band": [0.0, 0.5, 1.0],
    "ma_n": [0, 100, 200],
    "stop_atr": [2.0, 3.0],
    "trail_atr": [0.0, 4.0],
    "atr_n": [14],
}, "сторона дневного VWAP как направление, с полосой нечувствительности")
def s_vwap_trend(bars, p):
    """Простейшее применение VWAP: он делит день на бычий и медвежий.

    Гипотеза скромная и потому проверяемая: положение цены относительно
    дневного VWAP — это взвешенный по деньгам ответ на вопрос, кто сегодня в
    плюсе. Внутридневные участники смотрят на ту же линию и подталкивают цену
    в ту же сторону, поэтому сторона VWAP работает как направление.

    Полоса band в мерах ATR нужна против дёрганья: у самой линии цена
    пересекает её десяток раз за день, и торговать каждый переход — значит
    платить комиссию за шум. band=0 оставлен в сетке нарочно, чтобы увидеть,
    сколько именно стоит эта защита.

    Необязательное подтверждение средней (ma_n=0 — выключено) отвечает на
    отдельный вопрос: VWAP несёт что-то своё или всего лишь повторяет обычный
    тренд, который дешевле поймать скользящей средней.
    """
    n = len(bars.t)
    vw = ind.vwap_anchored(bars.t, bars.turnover, bars.v, rdata.DAY_MS)
    a = ind.atr(bars.h, bars.l, bars.c, int(p.get("atr_n", 14)))
    fin = np.isfinite(vw) & np.isfinite(a)
    edge = float(p["band"]) * a
    up = (bars.c - vw > edge) & fin
    dn = (vw - bars.c > edge) & fin

    ma_n = int(p["ma_n"])
    if ma_n > 0:
        ma = ind.ema(bars.c, ma_n)
        up = up & (bars.c > ma)
        dn = dn & (bars.c < ma)

    e = np.zeros(n, dtype=np.int8)
    e[_start(up)] = 1
    e[_start(dn)] = -1
    return strat.finish(bars, p, Signals(n), e, ~(up | dn))


