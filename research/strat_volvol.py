@strat.register("rvol_break", "volume", {
    "n": [20, 40, 80],
    "exit_n": [10, 20],
    "rvol_k": [1.5, 2.5],
    "use_volume": [0, 1],
    "stop_atr": [2.0, 3.0],
    "vol_n": [96],
    "atr_n": [14],
}, "пробой канала, подтверждённый относительным объёмом (объём отключаем)")
def s_rvol_break(bars, p):
    """Пробой на пустом стакане и пробой на потоке — разные события.

    Гипотеза: уровень пробивают либо деньги, либо тонкость. Ночью в неликвиде
    цену выносит за верх канала пара заявок, и она возвращается, как только
    приходит нормальный поток. Настоящий пробой сопровождается всплеском
    оборота, потому что через уровень проходят и стопы, и вход опоздавших,
    и закрытие тех, кто стоял против.

    Объём требуется ИМЕННО в момент пробоя, а не когда-нибудь потом: смысл в
    том, что уровень пробили деньгами, а не в том, что через три бара кто-то
    проснулся. Если use_volume=0, остаётся голый Дончиан — с ним и сравниваем.
    """
    n = len(bars.t)
    hi, lo = ind.donchian(bars.h, bars.l, int(p["n"]))
    xh, xl = ind.donchian(bars.h, bars.l, int(p["exit_n"]))
    if int(p["use_volume"]):
        rv = rel_volume(bars.v, int(p.get("vol_n", 96)))
        conf = rv >= float(p["rvol_k"])
    else:
        conf = _ones(n)

    e = np.zeros(n, dtype=np.int8)
    e[_start(bars.c > hi) & conf] = 1
    e[_start(bars.c < lo) & conf] = -1
    # Выход раздельный по сторонам: длинную закрывает уход НИЖЕ нижней
    # границы выходного канала, короткую — ВЫШЕ верхней. Одним условием на обе
    # стороны это правило закрывало длинную и при движении цены вверх, то есть
    # на прибыльной стороне пробоя, и превращало черепаший выход в его
    # противоположность.
    return strat.finish(bars, p, Signals(n), e, None,
                        exit_long=(bars.c < xl), exit_short=(bars.c > xh))


@strat.register("vol_spike", "volume", {
    "mode": [1, -1],
    "spike_k": [2.0, 3.0, 4.0],
    "body_atr": [0.5, 1.0],
    "use_volume": [0, 1],
    "stop_atr": [2.0, 3.0],
    "vol_n": [96],
    "atr_n": [14],
}, "всплеск объёма: продолжение (mode=1) или разворот (mode=-1)")
def s_vol_spike(bars, p):
    """Всплеск объёма означает две противоположные вещи, и обе надо проверить.

    В момент, когда на баре проходит втрое больше обычного, в рынок вошёл
    крупный поток. Дальше есть ровно два объяснения, и они несовместимы:
      * продолжение — поток только начался, за ним идут остальные, движение
        разгоняется (mode=+1);
      * разворот — это кульминация, продавец наконец нашёл всех покупателей,
        поток исчерпан, и цену возвращают (mode=-1).
    Рынок не обязан вести себя одинаково, поэтому направление вынесено в
    параметр, а не выбрано заранее по вкусу.

    Обязательное условие в обеих ветках — крупное тело свечи в мерах ATR:
    объём без движения означает лишь смену рук по той же цене и стороны не
    задаёт. При use_volume=0 остаётся только это условие, и сравнение
    отвечает на вопрос, добавляет ли объём хоть что-то к «большой свече».
    """
    n = len(bars.t)
    a = ind.atr(bars.h, bars.l, bars.c, int(p.get("atr_n", 14)))
    body = np.abs(bars.c - bars.o)
    with np.errstate(divide="ignore", invalid="ignore"):
        big = np.where(np.isfinite(a) & (a > 0),
                       body / np.where(a > 0, a, 1.0), np.nan)
    cond = big >= float(p["body_atr"])
    if int(p["use_volume"]):
        rv = rel_volume(bars.v, int(p.get("vol_n", 96)))
        cond = cond & (rv >= float(p["spike_k"]))

    fire = _start(cond)
    m = int(p["mode"])
    e = np.zeros(n, dtype=np.int8)
    e[fire & (bars.c > bars.o)] = m
    e[fire & (bars.c < bars.o)] = -m
    return strat.finish(bars, p, Signals(n), e)


@strat.register("obv_trend", "volume", {
    "obv_n": [24, 72, 168],
    "ma_n": [50, 100],
    "use_volume": [0, 1],
    "stop_atr": [2.0, 3.0],
    "trail_atr": [0.0, 3.0],
    "atr_n": [14],
}, "согласие направления OBV с направлением цены (объём отключаем)")
def s_obv_trend(bars, p):
    """Идём туда, куда идут и цена, и накопленный поток.

    OBV складывает объём со знаком движения цены: растёт — прибавили, падает —
    отняли. Гипотеза в том, что он показывает не то же самое, что цена. Цена
    может ползти вверх на пустом объёме, пока крупный участник разгружается в
    этот рост, — тогда OBV стоит или падает, и рост обречён. И наоборот:
    накопление под ценой видно в OBV раньше, чем в самой цене.

    Проверка вклада объёма здесь особенно чистая. При use_volume=0 OBV
    считается с единичным объёмом, то есть превращается в накопленный знак
    движения цены — та же конструкция, тот же сдвиг, тот же фильтр, разница
    ровно в одном множителе. Если результат при этом не портится, значит объём
    в OBV не нёс ничего, кроме шума.
    """
    n = len(bars.t)
    vol = bars.v if int(p["use_volume"]) else np.ones(n)
    ob = ind.obv(bars.c, vol)
    oe = ind.ema(ob, int(p["obv_n"]))
    ma = ind.ema(bars.c, int(p["ma_n"]))
    flow_up = ob > oe
    price_up = bars.c > ma
    price_dn = bars.c < ma
    fin = np.isfinite(oe) & np.isfinite(ma)

    long_c = flow_up & price_up & fin
    short_c = (~flow_up) & price_dn & fin
    e = np.zeros(n, dtype=np.int8)
    e[_start(long_c)] = 1
    e[_start(short_c)] = -1
    # поток и цена разошлись — повода сидеть в позиции больше нет
    return strat.finish(bars, p, Signals(n), e, ~(long_c | short_c))


@strat.register("vol_divergence", "volume", {
    "n": [20, 40, 80],
    "rvol_thr": [0.8, 1.0],
    "use_volume": [0, 1],
    "rr": [0.0, 1.5],
    "stop_atr": [2.0, 3.0],
    "vol_n": [96],
    "atr_n": [14],
}, "новый экстремум цены без подтверждения объёмом — вход против него")
def s_vol_divergence(bars, p):
    """Максимум, который никому не был нужен, обычно не держится.

    Гипотеза: чтобы обновить максимум месяца, требуется покупатель. Если новый
    максимум поставлен на объёме НИЖЕ обычного, покупателя не было — цену
    дотолкали по инерции в тонком стакане, и возвращать её будет некому. Такой
    экстремум чаще откатывает, чем продолжается, поэтому входим против него.

    Это самая рискованная гипотеза семейства: вход против свежего экстремума —
    ставка против движения в момент его силы, и ошибка тут стоит дорого. Зато
    проверка честная: при use_volume=0 остаётся вход против любого нового
    экстремума без разбора, и если разницы с объёмной веткой нет, вся идея
    расхождения цены и объёма — красивые слова.
    """
    n = len(bars.t)
    hi, lo = ind.donchian(bars.h, bars.l, int(p["n"]))
    if int(p["use_volume"]):
        rv = rel_volume(bars.v, int(p.get("vol_n", 96)))
        weak = rv <= float(p["rvol_thr"])
    else:
        weak = _ones(n)

    e = np.zeros(n, dtype=np.int8)
    e[_start(bars.h > hi) & weak] = -1
    e[_start(bars.l < lo) & weak] = 1
    return strat.finish(bars, p, Signals(n), e)


