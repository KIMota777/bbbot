# -*- coding: utf-8 -*-
"""Критерии приёмки. Объявлены ДО экзамена и после него не меняются.

Смысл этого файла в том, что он написан раньше, чем прочитаны данные экзамена.
Если сформулировать требования после просмотра результата, они неизбежно
подстроятся под победителя — это самый незаметный и самый разрушительный вид
подгонки, потому что выглядит как здравый смысл.

ПОРОГИ И ПОЧЕМУ ОНИ ТАКИЕ

  ПОРТФЕЛЬ, А НЕ ЛУЧШАЯ МОНЕТА. Стратегия торгуется на всех пяти сразу равной
  долей риска. Выбор монеты — это тоже подбор параметра, причём с пятью
  попытками.

  ПРОСАДКА <= 20%. Прямо из задания. Причём и историческая, и по Монте-Карло:
  если история дала 15%, а бутстрэп говорит, что четверть путей уходит глубже
  20%, значит нам просто повезло с порядком сделок.

  ПРИБЫЛЬ НЕ ИЗ НЕСКОЛЬКИХ СДЕЛОК. Убираем лучшие 5% сделок; остаток обязан
  остаться положительным. Пропустить пять сделок из ста в жизни проще
  простого — не хватило маржи, был перерыв, отвалился интернет. Стратегия,
  которая без них убыточна, зарабатывает не правилом, а везением.

  ЗДЕСЬ БЫЛ ИСПРАВЛЕН СОБСТВЕННЫЙ ПОРОГ, и об этом надо сказать прямо.
  Сначала стояло условие «доля лучших 5% сделок в чистой прибыли не выше
  60%». Его провалили ВСЕ кандидаты без исключения, и это был повод не
  расстроиться, а проверить сам порог. Проверка (research/calibrate_conc.py):
  берём заведомо здоровую выдуманную стратегию — сделки независимы, одинаково
  распределены, небольшой положительный перевес — с теми же средним и
  разбросом, что у кандидатов (+0.28% на сделку при разбросе 1.36%). У неё
  доля лучших 5% выходит 54-63%. То есть порог 60% отвергал любую стратегию с
  умеренным перевесом просто по арифметике, а не по существу.

  Различает не доля, а ОСТАТОК. У той же здоровой стратегии после удаления
  лучших 5% остаётся +0.34, у стратегии без перевеса вовсе — минус 0.42.
  Поэтому в жёстких условиях остался остаток (как и просит задание), а доля
  переведена в предупреждение: она сообщается, но не отвергает.

  Порог смягчён ДО экзамена и по доказательству, а не после просмотра
  результатов экзамена. Разница принципиальная: первое — исправление ошибки
  измерения, второе было бы подгонкой правил под желаемый ответ.

  ЖИВЁТ ПРИ ДОРОГОМ ИСПОЛНЕНИИ. Издержки в полтора раза выше — доходность
  обязана остаться положительной. Реальная биржа всегда дороже бэктеста.

  ДОСТАТОЧНО СДЕЛОК. Меньше сотни — статистики нет, и любой вывод держится на
  нескольких случайностях.

  БОЛЬШЕ ПОЛОВИНЫ МЕСЯЦЕВ В ПЛЮСЕ. Не про доходность, а про то, можно ли этим
  пользоваться: стратегия, зарабатывающая раз в квартал, требует терпения,
  которого у человека с реальными деньгами обычно нет.
"""
import numpy as np

MIN_TRADES = 100
MAX_DD = 0.20
MAX_MC_DD95 = 0.25
MAX_P_DD20 = 0.25
MIN_MO_MED = 0.02
MIN_MONTHS_POS = 0.55
DROP_TOP = 0.05


def concentration(trades_by_symbol, drop=DROP_TOP):
    """Что останется от прибыли, если убрать лучшие сделки."""
    r = np.array([t["ret"] for trs in trades_by_symbol.values() for t in trs])
    if len(r) < 20:
        return None
    srt = np.sort(r)[::-1]
    total = float(srt.sum())
    out = {"всего": total}
    for q in (0.01, 0.05, 0.10):
        k = max(1, int(round(len(srt) * q)))
        out["без топ-%d%%" % (100 * q)] = float(srt[k:].sum())
    k5 = max(1, int(round(len(srt) * drop)))
    out["доля топ-5%"] = (float(srt[:k5].sum()) / total) if total > 0 else 0.0
    out["выжила"] = bool(out["без топ-5%"] > 0)
    return out


def check(name, port, mc, monthly, conc, stress15):
    """Проверить кандидата по всем критериям. Возвращает (прошёл, список)."""
    rows = []
    warn = []

    def add(label, ok, got, need):
        rows.append((label, bool(ok), got, need))

    mv = np.array([m[1] for m in monthly]) if monthly else np.array([])
    add("сделок хватает", port["trades"] >= MIN_TRADES,
        "%d" % port["trades"], ">= %d" % MIN_TRADES)
    add("просадка по истории", port["maxdd"] <= MAX_DD,
        "%.1f%%" % (100 * port["maxdd"]), "<= %.0f%%" % (100 * MAX_DD))
    if mc:
        add("просадка Монте-Карло 95%", mc["dd_p95"] <= MAX_MC_DD95,
            "%.1f%%" % (100 * mc["dd_p95"]), "<= %.0f%%" % (100 * MAX_MC_DD95))
        add("вероятность просадки >20%", mc["p_dd20"] <= MAX_P_DD20,
            "%.0f%%" % (100 * mc["p_dd20"]), "<= %.0f%%" % (100 * MAX_P_DD20))
        add("риск потери счёта", mc["p_ruin"] <= 0.01,
            "%.1f%%" % (100 * mc["p_ruin"]), "<= 1%")
    if len(mv):
        add("медиана месяца", float(np.median(mv)) >= MIN_MO_MED,
            "%+.2f%%" % (100 * np.median(mv)), ">= %.0f%%" % (100 * MIN_MO_MED))
        add("плюсовых месяцев", float((mv > 0).mean()) >= MIN_MONTHS_POS,
            "%.0f%%" % (100 * (mv > 0).mean()),
            ">= %.0f%%" % (100 * MIN_MONTHS_POS))
    if conc:
        add("прибыль без лучших 5%", conc["выжила"],
            "%+.2f" % conc["без топ-5%"], "> 0")
        # Ниже — предупреждения, а не отказы. Почему именно так, разобрано
        # в шапке модуля: доля лучших сделок высока у любой стратегии с
        # умеренным перевесом, а остаток после их удаления различает
        # настоящий перевес и его отсутствие.
        warn.append(("прибыль без лучших 10%", conc["без топ-10%"] > 0,
                     "%+.2f" % conc["без топ-10%"], "> 0 (желательно)"))
        warn.append(("доля лучших 5% в прибыли", conc["доля топ-5%"] <= 0.60,
                     "%.0f%%" % (100 * conc["доля топ-5%"]),
                     "у здоровой 54-63%"))
    if stress15 is not None:
        add("жива при дорогих издержках", stress15 > 0,
            "%+.1f%%" % (100 * stress15), "> 0")
    passed = all(ok for _, ok, _, _ in rows)
    return passed, rows, warn


def report(name, passed, rows):
    print("\n%s — %s" % (name, "ПРОШЁЛ" if passed else "НЕ ПРОШЁЛ"))
    for label, ok, got, need in rows:
        print("   %s %-28s %10s   нужно %s"
              % ("+" if ok else "!", label, got, need))
