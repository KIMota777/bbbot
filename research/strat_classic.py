# --- самопроверка ----------------------------------------------------------

if __name__ == "__main__":
    import random
    import sys

    import engine
    import metrics
    import rdata

    bars, start = rdata.load_bars("BTCUSDT", "60").slice(*rdata.SPLITS["train"])
    print("Проверка на BTCUSDT 1ч, часть train: %d баров\n" % len(bars))

    print("1. Причинность: сигнал не смотрит в будущее")
    total = 0
    failed = []
    for name in NAMES:
        st = strat.REG[name]
        combos = list(st.combos())
        n_all = len(combos)
        if n_all > 24:
            combos = random.Random(0).sample(combos, 24)
        bad = 0
        for prm in combos:
            try:
                engine.assert_causal(
                    lambda b, st=st, prm=prm: st.build(b, prm), bars)
            except AssertionError as exc:
                bad += 1
                failed.append((name, prm, str(exc)[:90]))
        total += len(combos)
        print("   %-12s сочетаний %2d, проверено %2d, чисто %2d %s"
              % (name, n_all, len(combos), len(combos) - bad,
                 "OK" if not bad else "ПРОВАЛ"))
    print("   итого проверено сочетаний: %d\n" % total)
    for name, prm, msg in failed:
        print("   провал %s %s: %s" % (name, prm, msg))

    print("2. Показательные прогоны (издержки и фандинг включены)")
    demo = [
        ("c_rsi", dict(n=14, thr=30, mode=REVERT, stop_atr=2.0, atr_n=14)),
        ("c_rsi", dict(n=14, thr=30, mode=FOLLOW, stop_atr=2.0, atr_n=14)),
        ("c_bb", dict(n=20, k=2.0, mode=REVERT, stop_atr=2.0, atr_n=14)),
        ("c_sma_cross", dict(fast=20, mult=6, mode=FOLLOW, stop_atr=3.0,
                             atr_n=14)),
    ]
    # число попыток для дефлированного Шарпа — весь перебор этого модуля,
    # а не одна показанная точка: иначе поправка врёт в свою пользу
    n_trials = sum(strat.REG[x].n_combos() for x in NAMES)
    for name, prm in demo:
        res = engine.run(bars, strat.REG[name].build(bars, prm),
                         engine.Cfg(), start_i=start)
        lab = "%s m%d" % (name, prm["mode"])
        s = metrics.summarize(res, n_trials=n_trials, label=lab)
        print("   " + metrics.brief(s))
        print("      комиссии %.0f + фандинг %.0f при капитале %.0f, "
              "дефл. Шарп %.3f (попыток %d)"
              % (s["fees"], s["funding"], res.start_equity, s["dsr"],
                 n_trials))

    print("\nИтог: %s" % ("всё зелено" if not failed else "ЕСТЬ ПРОВАЛЫ"))
    sys.exit(1 if failed else 0)
