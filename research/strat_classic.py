# -*- coding: utf-8 -*-
"""Опорная линия исследования: классические индикаторы поодиночке.

ЗАЧЕМ ЭТО НУЖНО. Любая сложная конструкция — фильтр по режиму рынка, связка из
трёх индикаторов, обучаемая модель — обязана доказать, что она лучше самой
простой вещи, которую умеет кто угодно: одного индикатора с порогом. Пока
такого доказательства нет, сложность оплачена зря, а её преимущество на
истории объясняется числом попыток. Поэтому здесь замеряется не «хорошая
стратегия», а высота планки, ниже которой всё остальное не имеет смысла.

КАК УСТРОЕНО СРАВНЕНИЕ. У каждого индикатора есть ровно два прочтения, и
спорят они уже сто лет:

  режим 0, возврат к средней — крайнее значение означает перегиб. Толпа
  выбила цену за край, продавцы кончились, цена вернётся к своей середине;

  режим 1, продолжение — крайнее значение означает силу. За край цену вынес
  тот, кто крупнее рынка, и он ещё не закончил; отклонение будет расти.

Спусковой крючок у обоих режимов ОДИН И ТОТ ЖЕ — пересечение порога, — и
направление входа противоположно. Так и задумано: мы измеряем не два разных
сигнала, а два ответа на один вопрос «край — это конец движения или его
начало». Зеркальными по деньгам режимы всё равно не выйдут: стоп и выход
несимметричны, а издержки берутся с обеих сторон.

ВЫХОД ОДИНАКОВЫЙ У ОБОИХ РЕЖИМОВ — возврат осциллятора к своей середине
(RSI к 50, CCI к нулю, цена к средней полосе). Для возврата к средней это
«отскок состоялся», для продолжения — «импульс выдохся». Разные выходы для
разных режимов сделали бы сравнение бессмысленным: мы бы читали разницу в
выходах, а не разницу в гипотезах.

ЧЕГО ЗДЕСЬ СОЗНАТЕЛЬНО НЕТ. Ни фильтров по тренду, ни выбора часов суток, ни
подгонки порога под монету. Порог 30 по RSI взят потому, что его сто лет
рисуют в учебниках, а не потому, что он лучший на BTC. Если на разных монетах
работают разные пороги — это и есть результат, который надо увидеть, а не
спрятать за общим оптимумом.

ЧЕГО ЖДАТЬ ОТ ЧИСЕЛ. Круговая сделка стоит около 0.16% объёма позиции. На
часовых барах любой осциллятор с частым порогом даёт сотни сделок, и почти
всё, что он зарабатывает, остаётся у биржи. Убыточная опорная линия — это
нормальный результат: она честно показывает, сколько должна отыграть
сложность, чтобы вообще окупиться.
"""
import numpy as np

import ind
import strat
from engine import Signals

# Два прочтения одного и того же события.
REVERT = 0      # край — перегиб, входим против движения
FOLLOW = 1      # край — сила, входим по движению

MODES = [REVERT, FOLLOW]
# Ширина стопа в ATR. Две точки, а не одна: узкий стоп чаще выбивается шумом,
# широкий делает сделку крупнее по расстоянию и реже её закрывает. Если
# гипотеза жива, она переживёт обе. Если только одну — это подгонка, и она
# видна сразу, без отдельного исследования.
STOPS = [2.0, 3.0]
ATR_N = [14]


# --- общая механика порогов ------------------------------------------------

def _prev(x):
    """Значение предыдущего бара. У первого бара прошлого нет — там NaN."""
    return np.concatenate([[np.nan], x[:-1]])


def _shift_bool(m):
    out = np.zeros(len(m), dtype=bool)
    out[1:] = m[:-1]
    return out


def _zone(x, ok, lo, hi, mid, mode):
    """Разбор осциллятора на события. Общая деталь всех семи пороговых семей.

    Вход — только в момент ПЕРЕСЕЧЕНИЯ порога, а не всё время, пока значение
    находится за ним. Разница принципиальная: RSI умеет висеть ниже 30 по
    сорок баров подряд, и вход «пока перепродано» означает покупку на каждом
    баре обвала. Событие же случается один раз, и именно про него говорит
    учебник.

    Оба соседних бара обязаны быть посчитаны. Иначе первый бар после прогрева
    засчитывался бы как пересечение: значение до него было не «по другую
    сторону порога», а неизвестно. Разница между «неизвестно» и «ноль» — это
    ровно то место, где в бэктест заползает сигнал из ниоткуда.

    Возвращает (входы -1/0/+1, выходы). Выход — возврат к середине: сделка
    жила ради отклонения, отклонения больше нет.
    """
    p = _prev(x)
    live = ok & _shift_bool(ok)
    into_lo = live & (x < lo) & (p >= lo)      # провалились под нижний порог
    into_hi = live & (x > hi) & (p <= hi)      # выбрались над верхним
    e = np.zeros(len(x), dtype=np.int8)
    s = 1 if mode == REVERT else -1
    e[into_lo] = s                             # низ: возврат покупает,
    e[into_hi] = -s                            # продолжение — продаёт
    ex = live & ((x > mid) != (p > mid))
    return e, ex


def _mfi_ok(m, n):
    """Где MFI посчитан на самом деле.

    В ind.mfi непрогретый участок получается не NaN, а ровно 100: сумма
    оттоков там NaN, проверка `neg > 0` даёт False, отношение уходит в
    бесконечность. Стратегия приняла бы это за предельную перекупленность на
    старте выборки и открыла бы шорт на пустом месте. Отсекаем по длине окна —
    больше тут ничего не нужно.
    """
    return np.isfinite(m) & (np.arange(len(m)) >= n)


def _stoch_ok(k, d):
    """Где %D посчитан по настоящим %K, а не по подставленным 50.

    ind.stoch сглаживает %K, заменив перед этим NaN на 50. В середине выборки
    это ни на что не влияет, а на прогреве превращает пустоту в «нейтральное
    значение», пересечение которого с порогом выглядит как сигнал. Считаем,
    сколько непосчитанных %K попало в окно сглаживания, и требуем ноль.
    """
    bad = ind.rolling_sum((~np.isfinite(k)).astype(np.float64), d)
    return np.isfinite(bad) & (bad == 0)


# --- 1. RSI ----------------------------------------------------------------

@strat.register("c_rsi", "classic", {
    "n": [7, 14, 21],
    "thr": [20, 30],
    "mode": MODES,
    "stop_atr": STOPS,
    "atr_n": ATR_N,
}, "RSI за порогом: перегиб (режим 0) против силы (режим 1)")
def c_rsi(bars, p):
    """RSI — доля силы роста в общем ходе цены за последние n баров.

    Гипотеза возврата. Часовая перепроданность в крипте почти никогда не
    означает переоценку стоимости: за час фундаментальные причины не меняются.
    Она означает каскад — выбило стопы, за ними сработали ликвидации плечевых
    позиций, и продавали не потому, что хотели, а потому, что заставили. Такое
    падение отдаёт обратно, как только принудительные продажи кончились.

    Гипотеза продолжения. Ровно те же ликвидации — это топливо тренда, а не
    его конец: за первым каскадом идёт второй, потому что уровни маржин-колла
    стоят лесенкой. Тогда пробой порога RSI вниз — приглашение в шорт, а не в
    лонг.

    Обе версии не могут быть верны одновременно, и здесь они меряются одной
    линейкой.
    """
    n = len(bars.t)
    r = ind.rsi(bars.c, int(p["n"]))
    thr = float(p["thr"])
    e, ex = _zone(r, np.isfinite(r), thr, 100.0 - thr, 50.0, int(p["mode"]))
    return strat.finish(bars, p, Signals(n), e, ex)


# --- 2. Стохастик ----------------------------------------------------------

@strat.register("c_stoch", "classic", {
    "n": [9, 14, 21],
    "thr": [10, 20],
    "mode": MODES,
    "stop_atr": STOPS,
    "atr_n": ATR_N,
}, "%D стохастика за порогом: перегиб против силы")
def c_stoch(bars, p):
    """Стохастик — где закрытие внутри диапазона последних n баров.

    Гипотеза возврата. Закрытие у самого дна диапазона означает, что день
    отдали продавцам целиком. Такие бары редко идут подряд длинными сериями:
    покупателю выгоднее забирать у отчаявшегося, и следующий бар обычно
    закрывается выше.

    Гипотеза продолжения. Закрытие у дна — признак того, что покупателя в
    диапазоне вообще нет, и цене некуда идти, кроме как ниже.

    Берём сглаженную линию %D, а не сырой %K: %K на часе дёргается на каждом
    длинном фитиле, и половина пересечений порога — это не состояние рынка, а
    одна свеча с плохой ликвидностью.
    """
    n = len(bars.t)
    d_len = 3
    k, d = ind.stoch(bars.h, bars.l, bars.c, int(p["n"]), d_len)
    thr = float(p["thr"])
    e, ex = _zone(d, _stoch_ok(k, d_len), thr, 100.0 - thr, 50.0,
                  int(p["mode"]))
    return strat.finish(bars, p, Signals(n), e, ex)


# --- 3. CCI ----------------------------------------------------------------

@strat.register("c_cci", "classic", {
    "n": [14, 20, 30],
    "thr": [100, 200],
    "mode": MODES,
    "stop_atr": STOPS,
    "atr_n": ATR_N,
}, "CCI за ±порог: перегиб против силы")
def c_cci(bars, p):
    """CCI — насколько типичная цена ушла от своей средней, в единицах
    собственного среднего отклонения.

    От RSI отличается тем, что мерит РАЗМАХ, а не соотношение движений вверх и
    вниз. Медленный сползающий рынок держит RSI низким неделями, но CCI туда
    не загонит: отклонение от средней там маленькое. Поэтому CCI ловит рывок,
    а не усталость.

    Гипотеза возврата: рывок на две-три собственных нормы — это заявка,
    которую исполняли в тонком стакане, и цена вернётся туда, где стакан
    плотный. Гипотеза продолжения: такой рывок означает, что кто-то набирает
    позицию и будет набирать дальше.

    Порог 100 — из учебника Ламберта, где он покрывал примерно четверть
    случаев. У часовой крипты хвосты толще, и то же число означает совсем
    другую редкость события. Это часть измерения, а не оплошность.
    """
    n = len(bars.t)
    x = ind.cci(bars.h, bars.l, bars.c, int(p["n"]))
    thr = float(p["thr"])
    e, ex = _zone(x, np.isfinite(x), -thr, thr, 0.0, int(p["mode"]))
    return strat.finish(bars, p, Signals(n), e, ex)


# --- 4. Williams %R --------------------------------------------------------

@strat.register("c_willr", "classic", {
    "n": [14, 24, 48],
    "thr": [10, 20],
    "mode": MODES,
    "stop_atr": STOPS,
    "atr_n": ATR_N,
}, "%R за порогом: перегиб против силы; несглаженный близнец стохастика")
def c_willr(bars, p):
    """%R Уильямса — то же положение закрытия в диапазоне, но без сглаживания.

    Стоит сказать вслух: %R и %K стохастика — одна и та же величина, сдвинутая
    на 100. %R = 100*(c-hh)/rng, %K = 100*(c-ll)/rng, а hh-ll и есть rng, так
    что %R + 100 = %K тождественно. Значит, эта строчка опорной линии
    отличается от предыдущей ровно двумя вещами: отсутствием сглаживания и
    более длинными окнами.

    Именно поэтому её и надо мерить отдельно. Если c_stoch и c_willr на
    одинаковых окнах дадут разный результат, вся разница — в сглаживании
    трёх баров, и это интереснее любого из двух чисел по отдельности: значит,
    сигнал живёт в шуме, а не в состоянии рынка.
    """
    n = len(bars.t)
    w = ind.willr(bars.h, bars.l, bars.c, int(p["n"]))
    thr = float(p["thr"])
    # %R живёт на отрезке -100..0, поэтому нижний порог -(100-thr): -80 при
    # thr=20 — это классические «перепродано» из книг Уильямса.
    e, ex = _zone(w, np.isfinite(w), -(100.0 - thr), -thr, -50.0,
                  int(p["mode"]))
    return strat.finish(bars, p, Signals(n), e, ex)


# --- 5. MFI ----------------------------------------------------------------

@strat.register("c_mfi", "classic", {
    "n": [10, 14, 21],
    "thr": [20, 30],
    "mode": MODES,
    "stop_atr": STOPS,
    "atr_n": ATR_N,
}, "MFI за порогом: перегиб против силы; RSI, взвешенный оборотом")
def c_mfi(bars, p):
    """MFI — тот же RSI, но каждое движение взвешено оборотом в деньгах.

    Гипотеза, ради которой он вообще нужен: важно не то, что цена упала, а то,
    на какие деньги она упала. Падение на пустом рынке ночью и падение на
    трёхкратном обороте — разные события, а RSI их не различает. Если MFI
    систематически лучше RSI, значит объём несёт сведения о том, кто именно
    двигал цену, и его стоит тащить в более сложные конструкции. Если хуже —
    объём на бирже деривативов просто шум, и дальше о нём можно не вспоминать.

    Оговорка: объём фьючерса — это не приток денег, а оборот, где каждая
    сделка считается дважды и половина её — закрытие чужой позиции. Так что
    «денежный поток» в названии — метафора, и ждать от неё многого не стоит.
    """
    n = len(bars.t)
    per = int(p["n"])
    m = ind.mfi(bars.h, bars.l, bars.c, bars.v, per)
    thr = float(p["thr"])
    e, ex = _zone(m, _mfi_ok(m, per), thr, 100.0 - thr, 50.0, int(p["mode"]))
    return strat.finish(bars, p, Signals(n), e, ex)


# --- 6. ROC ----------------------------------------------------------------

@strat.register("c_roc", "classic", {
    "n": [6, 12, 24],
    "thr": [0.015, 0.03],
    "mode": MODES,
    "stop_atr": STOPS,
    "atr_n": ATR_N,
}, "ход цены за n баров больше порога: импульс против отката")
def c_roc(bars, p):
    """Скорость изменения — импульс без всякой обработки: сколько процентов
    цена прошла за n баров.

    Самый прямой способ спросить у рынка главное: продолжается ли начатое
    движение. Все остальные индикаторы этого раздела — та же мысль, обёрнутая
    в нормировку. Если голый импульс работает не хуже них, обёртки не нужны.

    Порог задан в процентах и НЕ подстраивается ни под окно, ни под монету —
    сознательно. Три процента за шесть часов и три процента за сутки — разные
    по редкости события, а для DOGE и для BTC они отличаются ещё вдвое. Сетка
    покажет, во что превращается один и тот же учебничный порог при переносе,
    и это ровно тот перенос, на котором обычно и рассыпаются готовые системы.
    """
    n = len(bars.t)
    r = ind.roc(bars.c, int(p["n"]))
    thr = float(p["thr"])
    e, ex = _zone(r, np.isfinite(r), -thr, thr, 0.0, int(p["mode"]))
    return strat.finish(bars, p, Signals(n), e, ex)


# --- 7. Полосы Боллинджера -------------------------------------------------

@strat.register("c_bb", "classic", {
    "n": [20, 40],
    "k": [2.0, 2.5, 3.0],
    "mode": MODES,
    "stop_atr": STOPS,
    "atr_n": ATR_N,
}, "выход цены за край полосы: отбой (режим 0) против пробоя (режим 1)")
def c_bb(bars, p):
    """Край полосы Боллинджера — отклонение цены на k сигм от своей средней.

    Отличие от осцилляторов в том, что порог здесь дышит вместе с рынком: в
    штиль полосы сжимаются, и до края достаточно небольшого хода, в шторм
    расходятся. Один и тот же «край» означает одинаковую РЕДКОСТЬ события в
    любом режиме — по крайней мере, если доходности нормальны, чего у крипты
    и близко нет: три сигмы там случаются в разы чаще, чем обещает формула.
    Поэтому k=3 здесь не «раз в год», а вполне рабочий порог, и сетка это
    покажет.

    Гипотеза отбоя: цена привязана резинкой к своей средней. Гипотеза пробоя
    (у Боллинджера она называется расширением полос): выход за край на
    растущей волатильности — начало движения, а не его край.

    Считаем положение цены в долях полуширины полосы, чтобы событие «вышли за
    край» описывалось теми же двумя порогами ±1, что и у осцилляторов, а
    середина совпадала со средней линией.
    """
    n = len(bars.t)
    m, up, dn, _w = ind.bbands(bars.c, int(p["n"]), float(p["k"]))
    half = up - m
    x = np.where(half > 0, (bars.c - m) / np.where(half > 0, half, 1.0),
                 np.nan)
    e, ex = _zone(x, np.isfinite(x), -1.0, 1.0, 0.0, int(p["mode"]))
    return strat.finish(bars, p, Signals(n), e, ex)


# --- 8-9. Пересечения скользящих -------------------------------------------

def _ma_cross(bars, p, ma):
    """Общая часть обоих пересечений: состояние «быстрая выше медленной».

    Вход — на СМЕНЕ состояния. Пока состояние держится, новых сигналов нет:
    иначе один и тот же тренд переоткрывался бы после каждого выбитого стопа,
    и стратегия платила бы комиссию за право сидеть в уже проигранной сделке.

    Явного выхода нет — позиция живёт до стопа или до обратного пересечения,
    которое движок исполнит как разворот. Это классический «стоп и переворот»:
    система всегда в рынке. Для режима продолжения такой выход естественен,
    для режима возврата он груб — отскок ждать до обратного креста незачем.
    Но выход у режимов обязан быть один, иначе сравниваются выходы, а не
    гипотезы.
    """
    n = len(bars.t)
    fast = int(p["fast"])
    slow = fast * int(p["mult"])
    f = ma(bars.c, fast)
    s = ma(bars.c, slow)
    ok = np.isfinite(f) & np.isfinite(s)
    up = f > s
    ch = np.zeros(n, dtype=bool)
    ch[1:] = up[1:] != up[:-1]
    # оба бара посчитаны — иначе «смена состояния» на выходе из прогрева
    live = ch & ok & _shift_bool(ok)
    e = np.zeros(n, dtype=np.int8)
    sgn = 1 if int(p["mode"]) == FOLLOW else -1
    e[live & up] = sgn
    e[live & ~up] = -sgn
    return strat.finish(bars, p, Signals(n), e)


@strat.register("c_sma_cross", "classic", {
    "fast": [10, 20, 50],
    "mult": [3, 6],
    "mode": MODES,
    "stop_atr": STOPS,
    "atr_n": ATR_N,
}, "простые средние: по тренду (режим 1) против отката к нему (режим 0)")
def c_sma_cross(bars, p):
    """Пересечение простых средних — самая старая механическая система вообще.

    Гипотеза продолжения (режим 1): цена не блуждает случайно, у неё есть
    инерция, и смена знака разности двух средних отмечает начало отрезка, где
    инерция направлена в одну сторону. Плата за это — множество ложных
    пересечений в боковике, и весь вопрос в том, окупает ли редкий длинный
    ход частые мелкие потери.

    Гипотеза возврата (режим 0): пересечение случается, когда цена уже далеко
    ушла от своей средней, то есть на излёте хода. Тогда крест — не начало, а
    место, где надо становиться против.

    Медленная средняя задана множителем к быстрой, а не отдельным числом:
    работает не абсолютная длина, а отношение окон, и плато параметров надо
    искать по нему. Заодно из сетки исчезают вырожденные пары вроде 50/50.
    """
    return _ma_cross(bars, p, ind.sma)


@strat.register("c_wma_cross", "classic", {
    "fast": [10, 20, 50],
    "mult": [3, 6],
    "mode": MODES,
    "stop_atr": STOPS,
    "atr_n": ATR_N,
}, "взвешенные средние: то же, но с меньшим запаздыванием")
def c_wma_cross(bars, p):
    """То же пересечение, но средние взвешены по свежести бара.

    Здесь проверяется одна узкая мысль: цена запаздывания. Простая средняя
    отвечает на разворот с задержкой примерно в половину окна, взвешенная —
    примерно в треть. Если запаздывание и есть главная беда пересечений, у
    взвешенных те же сетки должны идти заметно лучше. Если разница в пределах
    шума, значит беда не в задержке, а в том, что пересечений в боковике
    просто слишком много, и лечить надо не средние, а отбор момента.
    """
    return _ma_cross(bars, p, ind.wma)


