# -*- coding: utf-8 -*-
u"""Сколько нужно, чтобы поверить, и сколько нужно, чтобы это имело смысл.

Два вопроса, которые надо задать ЛЮБОЙ найденной прибавке, и оба — до споров
о том, настоящая она или нет.

  А. МОЖНО ЛИ ЕЁ ВООБЩЕ ИЗМЕРИТЬ. Доходность сделки — величина с тяжёлыми
     хвостами: разброс в десятки раз больше среднего. Отсюда прямой счёт:
     какая прибавка на вход была бы различима на имеющемся числе сделок, и
     сколько сделок нужно, чтобы различить ту, что найдена. Если для
     подтверждения находки нужно больше сделок, чем даёт вся история пяти
     монет за три года, — находка не подтверждена и подтверждена быть не может.

  Б. МЕНЯЕТ ЛИ ОНА ХОТЬ ЧТО-НИБУДЬ. Отдельно от статистики: какой прибавки на
     вход хватило бы, чтобы вытащить систему из минуса. Сравнение с ней и
     решает, стоит ли вообще спорить о значимости.

Ничего не подбирается и не выбирается: считаются только следствия из чисел,
уже полученных в ml_r2_pool.
"""
import os
import sys

import numpy as np

DIR = os.path.dirname(os.path.abspath(__file__))
if DIR not in sys.path:
    sys.path.insert(0, DIR)

import ml_lib      # noqa: E402
import ml_r2_lib as L  # noqa: E402
import ml_r2_pool as P  # noqa: E402
import rdata       # noqa: E402


def main():
    d = L.pooled(P.RULES4)
    folds = P.purged_folds(d["t_in"], d["t_out"])
    te = np.concatenate([f["test"] for f in folds])
    ret = d["ret"][te]
    n = len(ret)
    sd = float(ret.std(ddof=1))
    days = (float(d["t_out"][te].max()) - float(d["t_in"][te].min())) \
        / rdata.DAY_MS

    print(u"А. МОЖНО ЛИ ИЗМЕРИТЬ ТАКУЮ ПРИБАВКУ")
    print(u"   сделок вне обучения: %d за %.0f дней (%.1f сделки в день)"
          % (n, days, n / days))
    print(u"   доходность одного входа: среднее %+.4f%%, разброс %.3f%%, "
          u"эксцесс %.1f" % (100 * ret.mean(), 100 * sd,
                            float(((ret - ret.mean()) ** 4).mean() / sd ** 4)))
    se_half = sd * np.sqrt(1.0 / (n / 2) + 1.0 / n - 2.0 / n)
    # прибавка = среднее оставленных минус среднее всех; при отборе половины
    # разброс разности примерно sd*sqrt(1/k - 1/n), k = n/2
    se_half = sd * np.sqrt(1.0 / (n / 2.0) - 1.0 / n)
    se_top = sd * np.sqrt(1.0 / (0.3 * n) - 1.0 / n)
    print(u"   разброс самой прибавки при отсутствии умения:")
    print(u"      порог «медиана» (оставлено %d): ±%.4f%% на вход"
          % (n // 2, 100 * se_half))
    print(u"      порог «верх 30%%» (оставлено %d): ±%.4f%% на вход"
          % (int(0.3 * n), 100 * se_top))
    for eff in (0.00012, 0.00025):
        need = (3.0 * sd / eff) ** 2 * (1.0 / (1.0 / 0.3 - 1.0))
        print(u"   чтобы отличить прибавку %+.3f%% от нуля на трёх сигмах, "
              u"нужно %.0f сделок" % (100 * eff, need))
        print(u"      это %.1f лет при нынешней частоте (%.1f сделки в день)"
              % (need / (n / days) / 365.0, n / days))

    print(u"\nБ. ХВАТИЛО БЫ ЛИ ЕЁ, ЕСЛИ БЫ ОНА БЫЛА НАСТОЯЩЕЙ")
    print(u"   Опорная точка — то, что реально торговалось по FINAL_SPEC:")
    print(u"   четыре правила на 4ч, пять монет, доля риска 0.43%.")
    # 4ч-срез той же объединённой выборки
    m4 = np.array([c.endswith("|240") for c in d["cfg"][te]])
    r4 = ret[m4]
    ti4, to4 = d["t_in"][te][m4], d["t_out"][te][m4]
    mo4 = ml_lib.monthly_rate(r4, ti4, to4)
    per_month = len(r4) / (days / 30.0)
    print(u"   на 4ч-срезе: %d сделок, %.1f сделки в месяц на все рукава,"
          % (len(r4), per_month))
    print(u"   средняя доходность входа %+.4f%%, месяц %+.2f%% (риск 1%%)"
          % (100 * r4.mean(), 100 * mo4))
    for gap_mo in (0.0336, 0.0288):
        need_per_trade = gap_mo / per_month
        print(u"   чтобы закрыть разрыв в %.2f%% в месяц, нужна прибавка "
              u"%+.4f%% на вход" % (100 * gap_mo, 100 * need_per_trade))
    print(u"   (%.2f%% в месяц — провал на экзамене; %.2f%% — то, что "
          u"показывали обучение и проверка)" % (3.36, 2.88))

    print(u"\n   ПЕРЕСЧЁТ НА ДОЛЮ РИСКА 0.43%: все доходности здесь считаны")
    print(u"   при риске 1% на рукав, то есть в 2.3 раза крупнее боевых. В")
    print(u"   боевом масштабе найденная прибавка +0.025% на вход")
    print(u"   превращается в +0.011% — при издержках круга около 0.11%")
    print(u"   оборота. Прибавка меньше одной десятой стоимости входа.")
    print(u"\n   ВЫВОД РАЗДЕЛА. Найденная в ml_r2_pool прибавка — %.4f%% при"
          % (100 * 0.00012))
    print(u"   пороге «медиана» и %.4f%% при «верх 30%%»; это %.1f и %.1f"
          % (100 * 0.00025, 0.00012 / se_half, 0.00025 / se_top))
    print(u"   собственного разброса. Чтобы что-то изменить в системе, нужна")
    print(u"   прибавка %.4f%% — больше найденной." % (100 * 0.0359 / 93.7))


if __name__ == "__main__":
    main()
