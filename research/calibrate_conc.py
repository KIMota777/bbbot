# -*- coding: utf-8 -*-
"""Калибровка порога концентрации прибыли.

Порог отбора — такой же объект проверки, как и стратегия. Если он отвергает
всех подряд, у этого две возможные причины: либо все кандидаты плохи, либо
негоден сам порог. Различить их можно только одним способом: применить порог
к тому, чей ответ известен заранее.

Здесь берётся заведомо здоровая выдуманная стратегия: сделки независимы,
одинаково распределены, никакой лотереи в них нет по построению. Среднее и
разброс — как у настоящих кандидатов. Если показатель и на ней даёт тревожное
значение, значит он меряет не пригодность стратегии, а величину перевеса.

Запуск: python calibrate_conc.py
"""
import numpy as np

CASES = [
    ("как у кандидатов: 264 сд., +0.28% / 1.36%", 264, 0.0028, 0.0136),
    ("как у кандидатов: 323 сд., +0.25% / 1.41%", 323, 0.0025, 0.0141),
    ("сильный перевес: 300 сд., +0.8% / 1.4%", 300, 0.0080, 0.0140),
    ("очень сильный: 300 сд., +2.0% / 1.4%", 300, 0.0200, 0.0140),
    ("перевеса нет вовсе: 300 сд., 0% / 1.36%", 300, 0.0000, 0.0136),
    ("перевес отрицательный: 300 сд., -0.3%", 300, -0.0030, 0.0136),
]


def run(n_sims=2000, seed=0):
    rng = np.random.default_rng(seed)
    print("%-42s %8s %10s %11s" % ("эталон", "топ-5%", "без топ-5%",
                                   "без топ-10%"))
    out = []
    for label, n, mu, sd in CASES:
        shares, rest5, rest10 = [], [], []
        for _ in range(n_sims):
            r = rng.normal(mu, sd, n)
            s = np.sort(r)[::-1]
            tot = float(s.sum())
            k5 = max(1, int(round(n * 0.05)))
            k10 = max(1, int(round(n * 0.10)))
            if tot > 0:
                shares.append(float(s[:k5].sum()) / tot)
            rest5.append(float(s[k5:].sum()))
            rest10.append(float(s[k10:].sum()))
        row = (label,
               float(np.median(shares)) if shares else float("nan"),
               float(np.median(rest5)), float(np.median(rest10)))
        out.append(row)
        print("%-42s %7.0f%% %+10.3f %+11.3f"
              % (row[0], 100 * row[1], row[2], row[3]))
    return out


if __name__ == "__main__":
    rows = run()
    print("""
ВЫВОД

Доля лучших 5%% сделок в чистой прибыли у ЗДОРОВОЙ стратегии с перевесом
+0.28%% на сделку составляет 54-63%%. Это арифметика небольшого перевеса при
обычном разбросе, а не признак лотереи: чистая прибыль мала по сравнению с
разбросом, поэтому любые несколько лучших сделок дают в ней большую долю.
Порог «не выше 60%%» отвергал бы такую стратегию по построению.

Различает не доля, а ОСТАТОК после удаления лучших сделок:
  здоровая (+0.28%%)     без лучших 5%%  ->  остаётся в плюсе;
  без перевеса (0%%)     без лучших 5%%  ->  уходит в заметный минус.

Поэтому в жёсткие условия приёмки берётся остаток, а доля переведена в
предупреждение. Порог исправлен по этому расчёту и ДО экзамена.""")
