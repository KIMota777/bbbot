# -*- coding: utf-8 -*-
"""Семейство ПРОБОЕВ: семь способов задать рынку один и тот же вопрос.

Общая идея всех пробоев проста и стара. Пока цена ходит внутри границ, обе
стороны согласны, где справедливая цена. Выход за границу означает, что
согласие сломалось: кому-то срочно нужен объём, его стопы стоят за уровнем,
и там же стоят входы тех, кто ждал подтверждения. Если этих отложенных
приказов много, первое движение порождает второе — цена продолжает идти.

Но у той же ситуации есть зеркальный ответ, и он не менее правдоподобен.
За уровнем скапливаются стопы, а значит там ЛИКВИДНОСТЬ. Крупному участнику
выгодно сходить туда именно затем, чтобы собрать её и уйти обратно. Тогда
пробой — не начало движения, а его конец, и правильный вход — против него.

Оба объяснения складные, и спорить о них словами бессмысленно. Поэтому в
модуле стоят рядом две крайние стратегии:
    bb_break / range_break — «пробой продолжается»,
    false_break            — «пробой ложный, входим против».
Они смотрят на одни и те же события и торгуют их в противоположные стороны.
Что бы ни вышло по деньгам, разница между ними — это прямое измерение того,
кого на часовом биткойне больше: продолжений или ловушек. Такой ответ
самоценен, даже если обе стратегии убыточны после издержек.

О ЧЁМ ЗДЕСЬ ПРИХОДИТСЯ ПОМНИТЬ ОТДЕЛЬНО

Круговая сделка стоит около 0.16% объёма (комиссия обеих ног плюс
проскальзывание). Пробойные правила по своей природе частые: чем короче окно
уровня, тем чаще цена его пересекает. Поэтому короткие окна в сетках
присутствуют не как надежда, а как измерение — чтобы увидеть, на каком месте
частота съедает всё. Прятать этот эффект подбором длинных окон нечестно.

Второе: у пробоя нет естественного выхода. Вход задан событием, а выход —
нет, и почти всё, что называют «оптимизацией пробоя», на деле есть подбор
выхода. Поэтому выход здесь всюду простой и однотипный: стоп от ATR (общий
strat.finish), иногда трейл или тейк, кратный R, и лишь там, где выход
следует из самой гипотезы (сутки кончились, волатильность снова сжалась),
он задан явно.

Третье: правило причинности соблюдено конструктивно. Все уровни берутся из
ind.donchian (канал сдвинут на бар — иначе пробой ловит сам себя), пороги
глубины считаются по ATR ПРЕДЫДУЩЕГО бара (ATR текущего раздут ровно тем
движением, которое мы измеряем), диапазон суток берётся только после того,
как его часы закрылись.
"""
import numpy as np

import ind
import rdata
import strat
from engine import Signals

FAMILY = "breakout"

# Окно, в котором ширина диапазона сравнивается сама с собой (10 суток на 1ч).
# Абсолютной «узости» не существует: диапазон в 1% узок для DOGE и широк для
# BTC, поэтому меряем перцентилем, а не процентом.
W_RANK_N = 240

# Насколько цена должна уйти обратно за уровень, чтобы считать сетап пробоя
# погибшим. Полпроцента — не подобранное число, а грубая граница «вернулась
# внутрь по-настоящему, а не колебанием у самой линии».
FAIL_BAND = 0.005

# Сколько баров даётся цене на возврат в режиме ложного пробоя по закрытию.
# Ловушка — событие быстрое: если за четыре часа обратно не вернулись, это
# уже не ловушка, а нормальный пробой.
FB_WAIT = 4


# --- мелкие помощники, которых нет в ind.py ---------------------------------

def _cross_up(x, y):
    """Пересечение снизу вверх: на прошлом баре не выше, на этом — выше.

    Событие, а не состояние. Разница существенная: «цена выше уровня» держится
    десятками баров и после каждого выбитого стопа заводит позицию заново,
    а «цена пересекла уровень» случается один раз на пробой.
    """
    out = np.zeros(len(x), dtype=bool)
    out[1:] = (x[1:] > y[1:]) & (x[:-1] <= y[:-1])
    return out


def _cross_dn(x, y):
    out = np.zeros(len(x), dtype=bool)
    out[1:] = (x[1:] < y[1:]) & (x[:-1] >= y[:-1])
    return out


def _prev(x):
    """Значение предыдущего бара; на первом баре — NaN (сравнения дадут False)."""
    out = np.full(len(x), np.nan)
    out[1:] = x[:-1]
    return out


def _warm_after(x, n):
    """Маска «окно длины n уже целиком заполнено настоящими значениями».

    ind.rolling_rank сравнивает окно с текущим значением, а сравнение с NaN
    всегда даёт False. Значит на прогреве ранг занижен: окно наполовину
    пустое, и фильтр «ширина в нижнем перцентиле» там срабатывает даром.
    Участок надо отрезать явно, иначе первые недели выборки живут по другим
    правилам, чем остальные, и незаметно портят статистику.
    """
    out = np.zeros(len(x), dtype=bool)
    f = np.flatnonzero(np.isfinite(x))
    if len(f):
        j = int(f[0]) + int(n) - 1
        if j < len(x):
            out[j:] = True
    return out


# --- 1. Пробой границы устоявшегося диапазона -------------------------------

@strat.register("range_break", FAMILY, {
    "n": [24, 48, 96],
    "buf_atr": [0.0, 0.5],
    "w_rank": [0.5, 1.0],
    "trail_atr": [0.0, 3.0],
    "stop_atr": [2.0, 3.0],
    "atr_n": [14],
}, "пробой границы диапазона, сложившегося за n баров")
def s_range_break(bars, p):
    """Гипотеза: чем дольше и теснее рынок стоял, тем сильнее выход из стойки.

    Отличие от обычного канального пробоя — требование, чтобы уровень был
    границей именно ДИАПАЗОНА, а не случайным краем тренда. В тренде верх
    канала обновляется каждый второй бар, и «пробой» там не событие, а способ
    описать движение задним числом. Поэтому канал сначала проверяется на
    узость относительно собственной десятидневной истории: пробивать имеет
    смысл только то, что до этого держало.

    Буфер в долях ATR отвечает на второе возражение: цена задевает круглый
    уровень постоянно, и заход на один тик — не пробой, а шум. Буфер отделяет
    касание от выхода, но платит за это опозданием, и сетка честно содержит
    оба варианта — с буфером и без.

    Выход не задан отдельно: работают стоп от ATR, необязательный трейл и
    разворот на пробое в другую сторону. Так и задумано — измеряется вход,
    а не искусство выхода.
    """
    n = len(bars.t)
    if n < 3:
        return Signals(n)
    hi, lo = ind.donchian(bars.h, bars.l, int(p["n"]))
    a = ind.atr(bars.h, bars.l, bars.c, int(p.get("atr_n", 14)))
    buf = float(p["buf_atr"]) * _prev(a)          # ATR прошлого бара — см. шапку
    up_lvl = hi + buf
    dn_lvl = lo - buf

    # ширина канала в долях цены и её место среди собственных значений
    width = np.where(np.isfinite(hi) & np.isfinite(lo),
                     (hi - lo) / np.maximum(bars.c, 1e-12), np.nan)
    thr = float(p["w_rank"])
    if thr >= 1.0:
        narrow = np.ones(n, dtype=bool)           # фильтр выключен
    else:
        r = ind.rolling_rank(np.where(np.isfinite(width), width, np.inf),
                             W_RANK_N)
        narrow = _warm_after(width, W_RANK_N) & (r <= thr)

    e = np.zeros(n, dtype=np.int8)
    e[_cross_up(bars.c, up_lvl) & narrow] = 1
    e[_cross_dn(bars.c, dn_lvl) & narrow] = -1
    return strat.finish(bars, p, Signals(n), e)


# --- 2. Сжатие волатильности сменяется расширением --------------------------

@strat.register("squeeze_break", FAMILY, {
    "bb_n": [20, 40],
    "look": [96, 240],
    "q": [0.15, 0.25, 0.35],
    "stop_atr": [2.0, 3.0],
    "atr_n": [14],
}, "полосы сжались, затем разошлись — идём по направлению выхода")
def s_squeeze_break(bars, p):
    """Гипотеза: волатильность возвращается к средней, а направление — нет.

    Про волатильность известно то, чего не известно про цену: она липнет к
    своим значениям и возвращается к норме. Долгое сжатие поэтому предсказуемо
    сменяется расширением — но куда именно двинет цена, сжатие не говорит.
    Значит спрашивать надо не заранее, а в момент выхода: тишина кончилась,
    и первый выход за полосу показывает, чья взяла.

    Считаем сжатие не в процентах, а перцентилем ширины полос за look баров:
    у одного и того же рынка «тихо» в 2023-м и в 2025-м — разные числа.
    Требуем, чтобы сжатие было на ПРОШЛОМ баре, а на текущем ширина уже
    росла: это и есть смена режима, а не просто узкие полосы.

    Выход — обратное событие: ширина снова упала в зону сжатия, значит топливо
    кончилось. Выход по возврату к средней здесь не годится: массив выходов у
    движка один на обе стороны, и условие «цена ниже средней» закрыло бы шорт
    ровно там, где он работает.
    """
    n = len(bars.t)
    if n < 3:
        return Signals(n)
    mid, up, dn, w = ind.bbands(bars.c, int(p["bb_n"]), 2.0)
    look = int(p["look"])
    r = ind.rolling_rank(np.where(np.isfinite(w), w, np.inf), look)
    sq = _warm_after(w, look) & (r <= float(p["q"]))

    sq_prev = np.zeros(n, dtype=bool)
    sq_prev[1:] = sq[:-1]
    expand = np.zeros(n, dtype=bool)
    expand[1:] = w[1:] > w[:-1]                   # полосы пошли врозь

    # За полосу ПРОШЛОГО бара: полоса текущего уже раздута тем самым баром,
    # которым цена и вышла, и условие «закрылся выше своей же полосы»
    # проверяет бар сам о себя.
    up_prev, dn_prev = _prev(up), _prev(dn)
    go = sq_prev & expand
    e = np.zeros(n, dtype=np.int8)
    e[go & (bars.c > up_prev)] = 1
    e[go & (bars.c < dn_prev)] = -1
    return strat.finish(bars, p, Signals(n), e, sq)


# --- 3. Бар-шок: уход от прошлого закрытия больше чем на k*ATR ---------------

@strat.register("atr_break", FAMILY, {
    "k": [1.0, 1.5, 2.0, 3.0],
    "atr_n": [14, 24],
    "rr": [0.0, 2.0],
    "stop_atr": [1.5, 2.5, 3.5],
}, "бар ушёл от прошлого закрытия дальше чем на k ATR")
def s_atr_break(bars, p):
    """Гипотеза: резкий бар — это не шум, а вход крупного участника.

    Обычное блуждание не выдаёт часовых движений в две-три нормальные
    амплитуды. Такой бар почти всегда чем-то вызван: новостью, каскадом
    ликвидаций, срабатыванием чужих стопов. Если причина не исчерпана одним
    баром, поток приказов продолжится в ту же сторону — на этом и строится
    вход по направлению шока.

    Порог считается по ATR ПРЕДЫДУЩЕГО бара, и это принципиально: ATR
    текущего включает размах того самого бара, которым мы измеряем шок, —
    получилось бы измерение линейкой, растянутой ровно на измеряемую длину.

    Здесь нет уровня и нет диапазона: пробивается не линия на графике, а
    привычная амплитуда. Поэтому и выход в сетке предлагается двоякий — либо
    только стоп (держим, пока не вынесет), либо тейк в две ширины стопа
    (импульс краток, забираем сразу).
    """
    n = len(bars.t)
    if n < 3:
        return Signals(n)
    a = ind.atr(bars.h, bars.l, bars.c, int(p.get("atr_n", 14)))
    thr = float(p["k"]) * _prev(a)
    d = bars.c - _prev(bars.c)
    e = np.zeros(n, dtype=np.int8)
    e[d > thr] = 1
    e[d < -thr] = -1
    return strat.finish(bars, p, Signals(n), e)


# --- 4. Выход за полосу Боллинджера как ПРОДОЛЖЕНИЕ --------------------------

@strat.register("bb_break", FAMILY, {
    "bb_n": [20, 30, 50],
    "bb_k": [1.5, 2.0, 2.5],
    "exit_m": [0, 3],
    "stop_atr": [2.0, 3.0],
    "atr_n": [14],
}, "выход за полосу — сигнал продолжения, а не возврата")
def s_bb_break(bars, p):
    """Полосы читаются наоборот привычному: за полосой покупают, а не продают.

    Обычное толкование — «цена ушла на два сигма, вернётся». Оно опирается на
    предположение о нормальности, которого у доходностей нет и близко: хвосты
    толстые, и уход на два сигма случается не раз в двадцать баров, а куда
    чаще, причём кучно. Кучность и есть содержательная часть: сильные ходы
    идут сериями, и цена подолгу «едет по полосе», ни разу не вернувшись к
    середине.

    Проверяется именно это прочтение. Оно же — прямой антипод стратегии
    rsi_mr из strat.py, стоящей на возврате к средней. Разница результатов
    двух правил на одних барах говорит о рынке больше, чем каждое по
    отдельности.

    Вход — на пересечении полосы, а не на состоянии «за полосой»: иначе после
    каждого выбитого стопа позиция открывается заново тем же затянувшимся
    условием. Выход при exit_m > 0 — когда цена m баров подряд просидела
    внутри полос: езда кончилась. Это условие не зависит от стороны позиции,
    поэтому годится для общего массива выходов.
    """
    n = len(bars.t)
    if n < 3:
        return Signals(n)
    mid, up, dn, w = ind.bbands(bars.c, int(p["bb_n"]), float(p["bb_k"]))
    e = np.zeros(n, dtype=np.int8)
    e[_cross_up(bars.c, up)] = 1
    e[_cross_dn(bars.c, dn)] = -1

    m = int(p["exit_m"])
    ex = None
    if m > 0:
        inside = ((bars.c < up) & (bars.c > dn)).astype(np.float64)
        ex = ind.rolling_sum(inside, m) >= m - 1e-9
    return strat.finish(bars, p, Signals(n), e, ex)


# --- 5. Пробой диапазона первых часов суток ---------------------------------

@strat.register("opening_range", FAMILY, {
    "orn": [2, 3, 4, 6],
    "buf_atr": [0.0, 0.3],
    "eod": [0, 1],
    "stop_atr": [1.5, 2.5],
    "atr_n": [14],
}, "пробой диапазона первых orn часов суток UTC")
def s_opening_range(bars, p):
    """Гипотеза: у круглосуточного рынка всё же есть точка отсчёта суток.

    Возражение очевидно: крипта торгуется без перерыва, «открытия» нет, а
    полночь UTC — условность. Но условность общая: по ней биржа режет дневные
    свечи, по ней считают дневную доходность, рядом с ней (00:00, 08:00,
    16:00 UTC) платится фандинг. Если участники смотрят на одни и те же
    границы, границы становятся настоящими. Диапазон первых часов — это цена,
    которую рынок счёл справедливой на сегодня; выход за него означает, что
    день пошёл в одну сторону.

    Диапазон замораживается ровно тогда, когда его часы закрылись, и до этого
    момента ни один сигнал не выдаётся — заглянуть в собственный диапазон
    невозможно. При eod=1 позиция закрывается с концом суток: гипотеза
    внутридневная, и переносить сделку через полночь значило бы проверять уже
    другое утверждение.
    """
    n = len(bars.t)
    if n < 3:
        return Signals(n)
    bar_ms = bars.bar_ms()
    orn = int(p["orn"])
    day = (bars.t // rdata.DAY_MS).astype(np.int64)
    slot = ((bars.t % rdata.DAY_MS) // bar_ms).astype(np.int64)
    new = np.concatenate([[True], day[1:] != day[:-1]])
    starts = np.flatnonzero(new)
    grp = np.cumsum(new) - 1

    in_or = slot < orn
    # Максимум/минимум по суткам, где часы вне утреннего окна вычеркнуты
    # (-inf/+inf в максимуме и минимуме не участвуют). Значение получается
    # только из баров начала суток, а пользуемся им лишь после их закрытия.
    orh = np.maximum.reduceat(np.where(in_or, bars.h, -np.inf), starts)[grp]
    orl = np.minimum.reduceat(np.where(in_or, bars.l, np.inf), starts)[grp]
    ready = (slot >= orn) & np.isfinite(orh) & np.isfinite(orl)

    a = ind.atr(bars.h, bars.l, bars.c, int(p.get("atr_n", 14)))
    buf = float(p["buf_atr"]) * _prev(a)
    e = np.zeros(n, dtype=np.int8)
    e[_cross_up(bars.c, orh + buf) & ready] = 1
    e[_cross_dn(bars.c, orl - buf) & ready] = -1

    ex = None
    if int(p["eod"]):
        ex = np.zeros(n, dtype=bool)
        ex[:-1] = new[1:]          # последний бар суток; движок закроет на
        ex[-1] = True              # открытии первого бара следующих
    return strat.finish(bars, p, Signals(n), e, ex)


# --- 6. Пробой, возврат к уровню, отскок ------------------------------------

@strat.register("break_retest", FAMILY, {
    "n": [24, 48, 96],
    "wait": [6, 12, 24],
    "tol": [0.0, 0.002],
    "stop_atr": [1.5, 2.5],
    "atr_n": [14],
}, "пробой, возврат к уровню и отскок от него; вход на подтверждении")
def s_break_retest(bars, p):
    """Гипотеза: пробитое сопротивление становится поддержкой — и это проверяемо.

    Ходовое объяснение — про «смену ролей уровня» — звучит как заклинание, но
    за ним стоит механика: те, кто продавал у границы, теперь в убытке и хотят
    выйти в ноль на возврате; те, кто прозевал пробой, ждут второго шанса.
    Оба потока приказов сидят у одной и той же цены. Если поток покупателей
    там сильнее, возврат заканчивается отскоком.

    Вход не на самом возврате, а на ПОДТВЕРЖДЕНИИ: нужен отдельный бар,
    закрывшийся выше уровня и выше своего открытия. Разница не косметическая
    — вход на касании неотличим от ловли падающего ножа, потому что в момент
    касания ещё неизвестно, отскок это или продолжение вниз.

    Сетап живёт wait баров и умирает, если цена ушла обратно за уровень
    глубже полупроцента: тогда это был не пробой, а вылазка.

    Заведомое ограничение: сделок будет мало. Три условия подряд (пробой,
    возврат, подтверждение) отсеивают почти всё, и малое число сделок само по
    себе делает любую оценку доходности шаткой. Это следствие гипотезы, а не
    недосмотр.
    """
    n = len(bars.t)
    if n < 3:
        return Signals(n)
    hi, lo = ind.donchian(bars.h, bars.l, int(p["n"]))
    wait = int(p["wait"])
    tol = float(p["tol"])

    # Списки вместо массивов: обход поштучный (состояние сетапа зависит от
    # собственного прошлого), а обращение к элементу списка в разы дешевле,
    # чем к элементу numpy. Сравнения с NaN дают False — этим и пользуемся
    # вместо явных проверок на прогрев.
    c = bars.c.tolist()
    o = bars.o.tolist()
    h = bars.h.tolist()
    l = bars.l.tolist()
    hh = hi.tolist()
    ll = lo.tolist()

    e = np.zeros(n, dtype=np.int8)
    side = 0          # сторона активного сетапа
    phase = 0         # 1 — ждём возврата к уровню, 2 — ждём подтверждения
    lvl = 0.0
    dead = -1

    for i in range(1, n):
        if side > 0:
            if i > dead or c[i] < lvl * (1 - FAIL_BAND):
                side = 0
            elif phase == 1:
                if l[i] <= lvl * (1 + tol):
                    phase = 2
            elif c[i] > lvl and c[i] > o[i]:
                e[i] = 1
                side = 0
        elif side < 0:
            if i > dead or c[i] > lvl * (1 + FAIL_BAND):
                side = 0
            elif phase == 1:
                if h[i] >= lvl * (1 - tol):
                    phase = 2
            elif c[i] < lvl and c[i] < o[i]:
                e[i] = -1
                side = 0
        if side == 0:
            if c[i] > hh[i] and not (c[i - 1] > hh[i - 1]):
                side, phase, lvl, dead = 1, 1, hh[i], i + wait
            elif c[i] < ll[i] and not (c[i - 1] < ll[i - 1]):
                side, phase, lvl, dead = -1, 1, ll[i], i + wait
    return strat.finish(bars, p, Signals(n), e)


# --- 7. Ложный пробой: вход ПРОТИВ ------------------------------------------

@strat.register("false_break", FAMILY, {
    "n": [24, 48, 96],
    "pen": [0.0, 0.3],
    "mode": ["wick", "close"],
    "rr": [0.0, 2.0],
    "stop_atr": [1.5, 2.5],
    "atr_n": [14],
}, "цена вышла за уровень и вернулась — входим против пробоя")
def s_false_break(bars, p):
    """Гипотеза, противоположная всему остальному модулю: за уровнем ловушка.

    Стопы стоят там, где их видно всем, — сразу за границей диапазона. Это
    единственное место, где заведомо есть встречный объём. Кому нужно набрать
    крупную позицию, тому выгодно сходить туда, забрать эту ликвидность и
    вернуться. Со стороны выглядит как пробой, который «не пошёл»; по сути
    это набор позиции в обратную сторону.

    Два прочтения одного события, и оба в сетке:
      wick  — бар пробил уровень тенью, но закрылся обратно внутри. Отказ
              случился в тот же час, и он виден сразу;
      close — бар ЗАКРЫЛСЯ за уровнем (то есть выглядел как настоящий
              пробой), а в ближайшие FB_WAIT баров цена вернулась внутрь.
              Ловушка более дорогая для попавшихся и потому более значимая.

    Глубина захода pen меряется в ATR прошлого бара: заход на пару тиков —
    это не сбор стопов, а обычное касание.

    Цель здесь — противоположная сторона диапазона, поэтому в сетке есть тейк
    в две ширины стопа: возврат к середине диапазона — событие быстрое, и
    держать позицию «до упора» противоречит самой гипотезе.

    Именно сравнение этой стратегии с range_break и bb_break на одних и тех
    же барах и есть главный результат модуля. Прибыльность вторична: важно,
    какая сторона систематически права.
    """
    n = len(bars.t)
    if n < 3:
        return Signals(n)
    hi, lo = ind.donchian(bars.h, bars.l, int(p["n"]))
    ap = _prev(ind.atr(bars.h, bars.l, bars.c, int(p.get("atr_n", 14))))
    pen = float(p["pen"]) * ap
    e = np.zeros(n, dtype=np.int8)

    if p["mode"] == "wick":
        # Тень вышла за уровень, закрытие вернулось внутрь.
        sell = (bars.h > hi + pen) & (bars.c < hi)
        buy = (bars.l < lo - pen) & (bars.c > lo)
        both = sell & buy            # бар смёл обе границы — сторону не выбрать
        e[buy & ~both] = 1
        e[sell & ~both] = -1
        return strat.finish(bars, p, Signals(n), e)

    # Режим «пробой закрытием, затем возврат» — состояние живёт между барами.
    c = bars.c.tolist()
    up_l = (hi + pen).tolist()
    dn_l = (lo - pen).tolist()
    hh = hi.tolist()
    ll = lo.tolist()
    lvl_up = lvl_dn = 0.0
    exp_up = exp_dn = -1

    for i in range(1, n):
        s = 0
        if exp_up >= 0:                       # ждём возврата после пробоя вверх
            if i > exp_up:
                exp_up = -1
            elif c[i] < lvl_up:
                s -= 1
                exp_up = -1
        if exp_dn >= 0:
            if i > exp_dn:
                exp_dn = -1
            elif c[i] > lvl_dn:
                s += 1
                exp_dn = -1
        # Новые пробои отмечаем ПОСЛЕ проверки возврата: иначе один и тот же
        # бар успел бы и пробить, и вернуться.
        if exp_up < 0 and c[i] > up_l[i]:
            lvl_up, exp_up = hh[i], i + FB_WAIT
        if exp_dn < 0 and c[i] < dn_l[i]:
            lvl_dn, exp_dn = ll[i], i + FB_WAIT
        if s:
            e[i] = s                          # s == 0, если сработали обе стороны
    return strat.finish(bars, p, Signals(n), e)


