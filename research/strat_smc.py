# Короткие имена для строки отчёта: metrics.brief режет подпись на 22 знака,
# и обрезаться должно наименее важное — размер стопа, а не режим стратегии.
_SHORT = {"fvg": "fvg", "order_block": "ob", "displacement": "disp",
          "imbalance": "imb", "premium_discount": "prem", "pdh_pdl": "pdh",
          "session_levels": "week"}
_KEY = {"min_gap_atr": "g", "life": "L", "imp_atr": "i", "imp_n": "m",
        "k": "k", "body": "b", "hold": "h", "n": "n", "thr": "t",
        "buf": "b", "rr": "R", "stop_atr": "s"}
_ORDER = ["mode", "min_gap_atr", "imp_atr", "imp_n", "k", "n", "buf", "thr",
          "body", "life", "hold", "rr", "stop_atr"]


def _label(name, p):
    parts = [_SHORT.get(name, name)]
    for k in _ORDER:
        if k not in p:
            continue
        if k == "mode":
            parts.append("brk" if p[k] == "break" else str(p[k]))
        else:
            parts.append("%s%s" % (_KEY[k], p[k]))
    return " ".join(parts)[:22]


