# -*- coding: utf-8 -*-
"""Прайс-экшен и «умные деньги»: семь утверждений, разобранных поодиночке.

У этого языка есть особенность: он описывает КАРТИНКУ, а не правило. «Цена
вернулась в зону дисбаланса и продолжила движение» — это пересказ уже
случившегося графика, и на любой истории такие места находятся. Поэтому здесь
не проверяется «работает ли SMC». Проверяется другое: даёт ли КАЖДЫЙ отдельный
элемент этого языка сдвиг вероятности сам по себе, без остальных шести.

Почему по одному, а не набором. Набор из шести условий на часовом BTC
срабатывает десяток раз за два года, и любой его результат — это разброс
десяти сделок, а не свойство рынка. Разделив элементы, мы получаем по
несколько сотен наблюдений на каждый и можем отличить сдвиг от шума. Если
элемент не даёт сдвига в одиночку, то утверждение «он работает в сочетании»
требует отдельного доказательства, а не выдаётся авансом.

Никакой мистики в определениях нет, и намеренно:
  * разрыв справедливой цены (FVG) — это просто промежуток между тенью бара
    и тенью бара через один, через который цена прошла не торгуясь;
  * ордер-блок — это просто последний бар противоположного цвета перед
    сильным движением;
  * дисбаланс — серия баров, идущих в одну сторону, не отдавая назад;
  * премиум/дисконт — цена в верхней или нижней половине недавнего размаха;
  * уровни суток и недели — максимум и минимум предыдущего календарного
    периода по меткам времени UTC.

ЧТО ВЫЯСНИЛОСЬ ПРО «БЕЗ ПЕРЕКРЫТИЯ» (важно для честности определения).
На непрерывном рынке открытие бара в точности равно закрытию предыдущего —
проверено на этих же данных, расхождение ровно нулевое на всех 17 673 барах.
Значит диапазоны СОСЕДНИХ баров всегда касаются, и «серия баров без
перекрытия» в буквальном смысле не встречается никогда. Это не редкое
явление, это невозможное. Поэтому непересечение измеряется через бар — так,
как оно единственно и может существовать на непрерывных данных.

Общее для всех семи: направление входа задаёт стратегия, размер считает
движок от риска и расстояния до стопа, стоп — из ATR через strat.finish.
Ни одна из семи не знает про капитал, плечо и комиссии.

ПОЧЕМУ В САМОПРОВЕРКЕ ФАНДИНГ ВЫКЛЮЧЕН (найдено при разборе этих же чисел).
В файлах funding_*.json ставка записана В ПРОЦЕНТАХ: первые строки BTCUSDT —
ровно 0.01, медиана за всю историю 0.0067. А rdata.funding_paid умножает
объём позиции на это число КАК НА ДОЛЮ. Разница в сто раз: 0.0067% за восемь
часов — это 7.3% годовых, обычная для BTC величина, а 0.0067 долей — это 733%
годовых, чего не бывает ни на одном вечном контракте. Сам движок в своём
описании исходит из долей: «при ставке 0.01% на 8 часов набегает ~11%
годовых» — это и есть 0.0001, а не 0.01.

Последствие не косметическое: с таким фандингом любой шорт получает почти
семикратную годовую доплату к объёму позиции, а любой лонг её платит. На этой
самой сетке «покупай в дисконте, продавай в премиуме» в прогоне только
шортами (allow_long=False) показывала +2260% и Шарп 4.6 — и вся эта прибыль
до копейки была доплатой фандинга: итог 225 997 при фандинге 254 641, то есть
сам сигнал в минусе. С выключенным фандингом та же стратегия становится худшей
из семи. Поэтому здесь и в отчётах по этому модулю фандинг отключён: с ним
меряется ошибка в единицах, а не поведение рынка.

Чинить чужой файл — не работа этого модуля, но пользоваться сломанным числом
и делать вид, что меряешь рынок, нельзя. Правильное место для починки — либо
единицы в funding_*.json, либо деление на 100 в rdata.funding_paid.
"""
import numpy as np

import engine
import ind
import rdata
import strat
from engine import Signals

DAY_MS = rdata.DAY_MS
WEEK_MS = 7 * DAY_MS
# Эпоха начинается в четверг, поэтому чтобы неделя шла с понедельника, время
# сдвигается на три дня вперёд перед делением.
WEEK_OFFSET_MS = 3 * DAY_MS

FAMILY = "smc"


# --- мелкие вспомогательные вещи, которых нет в ind.py ---------------------

def _shift(x, k=1):
    """Значение k баров назад. Ничего не знает о будущем по построению."""
    out = np.full(len(x), np.nan)
    if k < len(x):
        out[k:] = x[:len(x) - k]
    return out


def _first(cond):
    """Первый бар, на котором условие стало верным (а не каждый бар подряд).

    Без этого стратегия переоткрывает одну и ту же мысль на каждом баре, пока
    условие держится, и число сделок начинает измерять длительность состояния,
    а не количество поводов.
    """
    prev = np.zeros(len(cond), dtype=bool)
    prev[1:] = cond[:-1]
    return cond & ~prev


def _hold_exit(entry, hold):
    """Выход по времени: закрыться через hold баров после сигнала на вход.

    Считается от ПОСЛЕДНЕГО входного сигнала, известного к текущему бару, —
    никакого знания о том, когда движок реально откроет позицию, здесь нет и
    быть не может. Позиция открывается на баре сигнал+1, выход срабатывает на
    баре сигнал+hold+1, то есть держим примерно hold часов.
    """
    n = len(entry)
    idx = np.where(entry != 0, np.arange(n), -1)
    np.maximum.accumulate(idx, out=idx)
    out = np.zeros(n, dtype=bool)
    ok = idx >= 0
    out[ok] = (np.arange(n)[ok] - idx[ok]) >= hold
    return out


def _prev_period_hl(t, h, l, period_ms, offset_ms=0):
    """Максимум и минимум ПРЕДЫДУЩЕГО завершённого периода для каждого бара.

    Период нарезается по меткам времени UTC — так же, как их отдаёт биржа.
    Текущий, ещё не закрытый период не используется никогда: бару из суток D
    достаются только числа суток D-1, а они окончательны уже к полуночи.
    Именно поэтому уровень и можно торговать: он известен заранее и виден всем
    одинаково, чем и объясняется скопление заявок вокруг него.

    Самый первый период выборки выбрасывается: выборка почти всегда начинается
    посреди суток, и его максимум — это максимум огрызка, а не дня. Иначе
    сигналы первых дней зависели бы от того, где мы нарезали окно.
    """
    n = len(t)
    g = ((t + offset_ms) // period_ms).astype(np.int64)
    new = np.empty(n, dtype=bool)
    new[0] = True
    new[1:] = g[1:] != g[:-1]
    starts = np.flatnonzero(new)
    gh = np.maximum.reduceat(h, starts)
    gl = np.minimum.reduceat(l, starts)
    gi = np.cumsum(new) - 1                 # номер периода для каждого бара
    ph = np.full(n, np.nan)
    pl = np.full(n, np.nan)
    ok = gi > 1                             # предыдущий период должен быть полным
    ph[ok] = gh[gi[ok] - 1]
    pl[ok] = gl[gi[ok] - 1]
    return ph, pl


def _with(p, **defaults):
    """Копия параметров с дефолтами для strat.finish, не раздувая сетку.

    Тейк и трейл — часть обвязки выхода, а не гипотезы. Держать их в сетке
    ради одного значения значит умножать число проверок на единицу и потом
    расплачиваться поправкой на множественность.
    """
    q = dict(p)
    for k, v in defaults.items():
        q.setdefault(k, v)
    return q


# --- 1. Разрыв справедливой цены (FVG) -------------------------------------

@strat.register("fvg", FAMILY, {
    "min_gap_atr": [0.15, 0.3, 0.5],
    "life": [12, 24, 48],
    "stop_atr": [1.5, 2.5],
    "rr": [1.5, 3.0],
}, "вход на возврате в незакрытый трёхбарный разрыв, по направлению разрыва")
def s_fvg(bars, p):
    """Гипотеза: место, где цена прошла не торгуясь, притягивает её обратно.

    Если между тенью бара i-2 и тенью бара i остался промежуток, значит внутри
    него сделок почти не было: цена проскочила его одним движением. Тот, кто не
    успел, ждёт возврата в этот промежуток, а тот, кто вошёл на самом рывке,
    готов добирать там же. Утверждение SMC состоит в двух частях: цена в этот
    промежуток вернётся (это почти всегда правда и потому бесполезно) и,
    вернувшись, ПРОДОЛЖИТ движение в сторону разрыва (вот это и проверяем).

    Промежуток живёт life баров. Если цена закрылась по другую его сторону,
    он считается отработанным и снимается: возврат внутрь после этого — уже
    не возврат, а обычное блуждание.

    Проверять размер разрыва приходится в долях ATR, а не в процентах цены:
    полпроцента в спокойный месяц и полпроцента в шторм — разные события.
    """
    n = len(bars.t)
    h, l, c = bars.h, bars.l, bars.c
    a = ind.atr(h, l, c, int(p.get("atr_n", 14)))
    life = int(p["life"])
    mn = float(p["min_gap_atr"])
    e = np.zeros(n, dtype=np.int8)
    up = None                    # (низ, верх, бар рождения) разрыв вверх
    dn = None                    # то же для разрыва вниз

    for i in range(2, n):
        # Сначала работа с уже известными промежутками: они образовались
        # раньше, и текущий бар лишь проверяет, вернулась ли к ним цена.
        if up is not None:
            lo_z, hi_z, born = up
            if i - born > life or c[i] < lo_z:
                up = None                       # протух или пробит насквозь
            elif l[i] <= hi_z:
                e[i] = 1                        # цена зашла в промежуток
                up = None
        if dn is not None:
            lo_z, hi_z, born = dn
            if i - born > life or c[i] > hi_z:
                dn = None
            elif h[i] >= lo_z:
                # если на этом же баре сработал и разрыв вверх, промежуток всё
                # равно считается отработанным — иначе он выстрелит следующим
                # баром и развернёт только что открытую позицию
                if e[i] == 0:
                    e[i] = -1
                dn = None
        # Затем — не образовался ли новый промежуток на текущем баре.
        ai = a[i]
        if not np.isnan(ai) and ai > 0:
            g_up = l[i] - h[i - 2]
            if g_up >= mn * ai:
                up = (h[i - 2], l[i], i)
            g_dn = l[i - 2] - h[i]
            if g_dn >= mn * ai:
                dn = (h[i], l[i - 2], i)
    return strat.finish(bars, _with(p), Signals(n), e)


# --- 2. Ордер-блок ----------------------------------------------------------

@strat.register("order_block", FAMILY, {
    "imp_atr": [1.0, 1.5, 2.0],
    "imp_n": [3, 5],
    "life": [12, 24, 48],
    "stop_atr": [1.5, 2.5],
}, "последний бар против сильного движения, вход на возврате к его диапазону")
def s_order_block(bars, p):
    """Гипотеза: крупный покупатель набирал позицию там, откуда цена ушла.

    Рассказывают это так: перед резким движением вверх кто-то большой набирал
    объём, а видно его по последнему падающему бару перед рывком — там он
    исполнялся против продавцов. Если он набрал не всё, то при возврате цены к
    этому бару он доберёт, и рынок оттуда снова пойдёт вверх.

    Проверяемая часть: цена, вернувшись к диапазону последнего бара против
    движения, чаще продолжает в сторону движения, чем разворачивается.
    Ненаблюдаемая часть (кто там набирал и набрал ли) нам и не нужна — она
    ничего не добавляет к правилу.

    Сила движения меряется ATR, взятым ДО движения. ATR на текущем баре уже
    впитал сам рывок и занижает его необычность — порог тогда сам себе мешает
    сработать.
    """
    n = len(bars.t)
    o, h, l, c = bars.o, bars.h, bars.l, bars.c
    a = ind.atr(h, l, c, int(p.get("atr_n", 14)))
    m = int(p["imp_n"])
    k = float(p["imp_atr"])
    life = int(p["life"])
    e = np.zeros(n, dtype=np.int8)
    up = None                    # (низ, верх, бар рождения) бычий ордер-блок
    dn = None

    for i in range(m + 1, n):
        if up is not None:
            lo_z, hi_z, born = up
            if i - born > life or c[i] < lo_z:
                up = None                       # цена прошла блок насквозь
            elif l[i] <= hi_z:
                e[i] = 1
                up = None
        if dn is not None:
            lo_z, hi_z, born = dn
            if i - born > life or c[i] > hi_z:
                dn = None
            elif h[i] >= lo_z:
                if e[i] == 0:               # см. пояснение в s_fvg
                    e[i] = -1
                dn = None

        base = a[i - m]
        if np.isnan(base) or base <= 0:
            continue
        move = c[i] - c[i - m]
        if move >= k * base:
            b = -1
            for j in range(i - 1, i - m - 1, -1):
                if c[j] < o[j]:                 # последний падающий бар
                    b = j
                    break
            if b >= 0:
                up = (l[b], h[b], i)
        elif -move >= k * base:
            b = -1
            for j in range(i - 1, i - m - 1, -1):
                if c[j] > o[j]:                 # последний растущий бар
                    b = j
                    break
            if b >= 0:
                dn = (l[b], h[b], i)
    return strat.finish(bars, _with(p, rr=2.0), Signals(n), e)


# --- 3. Бар необычного размаха ---------------------------------------------

@strat.register("displacement", FAMILY, {
    "k": [1.5, 2.0, 2.5, 3.0],
    "body": [0.3, 0.6],
    "hold": [6, 12, 24],
    "stop_atr": [1.5, 2.5],
}, "бар размахом в k ATR как заявка на направление, удержание hold баров")
def s_displacement(bars, p):
    """Гипотеза: резкий бар — это не шум, а след потока, который ещё не иссяк.

    За баром втрое шире обычного почти всегда стоит либо новость, либо каскад
    ликвидаций. И в том, и в другом случае участник, который двигал цену, редко
    заканчивает ровно на закрытии часа: остаток заявки доносится в следующие
    часы. Отсюда и правило — входить в сторону бара и держать несколько часов.

    Против гипотезы работает встречное соображение, и оно не слабее: каскад
    ликвидаций выносит цену дальше, чем оправдано, и после него нормален
    возврат. Так что честный исход здесь — не «прибыль», а знание, какая из
    двух сил на часовом BTC перевешивает.

    Размах сравнивается с ATR ПРЕДЫДУЩЕГО бара. Если брать ATR текущего, бар
    сравнивается с самим собой: он же входит в среднее и тянет порог за собой.
    Требование к телу отсеивает бары-качели, где размах есть, а итога нет.
    """
    n = len(bars.t)
    o, h, l, c = bars.o, bars.h, bars.l, bars.c
    a_prev = _shift(ind.atr(h, l, c, int(p.get("atr_n", 14))), 1)
    rng = h - l
    with np.errstate(divide="ignore", invalid="ignore"):
        wide = rng >= float(p["k"]) * a_prev
        body_ok = np.abs(c - o) >= float(p["body"]) * np.maximum(rng, 1e-12)
    ok = wide & body_ok & np.isfinite(a_prev) & (a_prev > 0)
    e = np.zeros(n, dtype=np.int8)
    e[ok & (c > o)] = 1
    e[ok & (c < o)] = -1
    ex = _hold_exit(e, int(p["hold"]))
    return strat.finish(bars, _with(p, rr=2.0), Signals(n), e, ex)


# --- 4. Дисбаланс: серия баров в одну сторону ------------------------------

@strat.register("imbalance", FAMILY, {
    "k": [2, 3],
    "mode": ["gap", "push"],
    "hold": [8, 24],
    "stop_atr": [1.5, 2.5],
    "rr": [1.5, 3.0],
}, "k подряд баров, уходящих в одну сторону без отката; вход по направлению")
def s_imbalance(bars, p):
    """Гипотеза: односторонний ход означает, что одна сторона выбита из книги.

    Когда несколько часов подряд цена уходит, не возвращаясь к прошлым
    уровням, это значит, что встречных заявок на пути нет: их сняли или увели.
    Пока книга не восстановилась, продолжать движение дешевле, чем развернуть,
    и ход обычно длится дольше одного бара.

    Как здесь меряется «без перекрытия» и почему именно так. Открытие бара на
    непрерывном рынке равно закрытию предыдущего — на этих данных ровно, до
    последнего знака. Значит соседние бары СЛИПЛИСЬ по определению, и
    буквальная серия «без перекрытия соседей» не существует в природе. Остаются
    два осмысленных прочтения, оба и проверяем:
      gap  — каждый бар серии не перекрывается с баром ЧЕРЕЗ ОДИН (цепочка
             тех самых незакрытых промежутков, идущих подряд);
      push — каждый бар серии закрывается за пределами всего диапазона
             предыдущего: откат внутрь прошлого часа не состоялся ни разу.
    Первое строже и встречается в несколько раз реже второго.

    Отличие от стратегии fvg принципиальное: там вход на ВОЗВРАТЕ в промежуток,
    здесь — по направлению серии сразу. Это две противоположные ставки на одно
    и то же явление, и полезно знать, какая из них хотя бы не хуже.
    """
    n = len(bars.t)
    h, l, c = bars.h, bars.l, bars.c
    k = int(p["k"])
    up_step = np.zeros(n, dtype=bool)
    dn_step = np.zeros(n, dtype=bool)
    if p["mode"] == "gap":
        up_step[2:] = l[2:] > h[:-2]
        dn_step[2:] = h[2:] < l[:-2]
    else:
        up_step[1:] = c[1:] > h[:-1]
        dn_step[1:] = c[1:] < l[:-1]
    up_run = ind.rolling_sum(up_step.astype(np.float64), k) == k
    dn_run = ind.rolling_sum(dn_step.astype(np.float64), k) == k
    e = np.zeros(n, dtype=np.int8)
    # только на ЗАВЕРШЕНИИ серии: пока она тянется, повод один и тот же
    # (непрогретые бары дают NaN, а NaN == k — это False, лишнего сигнала нет)
    e[_first(up_run)] = 1
    e[_first(dn_run) & (e == 0)] = -1
    ex = _hold_exit(e, int(p["hold"]))
    return strat.finish(bars, _with(p), Signals(n), e, ex)


# --- 5. Премиум и дисконт --------------------------------------------------

@strat.register("premium_discount", FAMILY, {
    "n": [48, 96, 192],
    "thr": [0.2, 0.3],
    "rr": [1.0, 2.0],
    "stop_atr": [1.5, 2.5],
}, "покупка в нижней части последнего размаха, продажа в верхней")
def s_premium_discount(bars, p):
    """Гипотеза: внутри размаха цена дороже или дешевле своей середины.

    Идея простая и старая: разметить последний размах, назвать нижнюю половину
    дисконтом, верхнюю премиумом и покупать только в дисконте. По сути это
    возврат к середине диапазона, переназванный в другие слова, и проверяется
    он ровно как возврат к средней: работает, пока рынок стоит в диапазоне, и
    режет счёт, как только диапазон становится трендом. Ровно там, где цена
    «слишком дешёвая», начинается вынос вниз.

    Размах берётся каналом Дончиана СО СДВИГОМ на бар (так он сделан в ind):
    считать положение цены внутри размаха, который сам же текущий бар и
    образовал, — значит вечно получать 0 или 1.

    Вход — на ПЕРЕСЕЧЕНИИ порога, а не на каждом баре ниже него: иначе в
    затяжном падении набирается десяток входов подряд в одну сторону, и
    результат меряет длину падения, а не качество идеи.
    """
    n = len(bars.t)
    hi, lo = ind.donchian(bars.h, bars.l, int(p["n"]))
    rng = hi - lo
    with np.errstate(divide="ignore", invalid="ignore"):
        pos = np.where(rng > 0, (bars.c - lo) / rng, np.nan)
    prev = _shift(pos, 1)
    thr = float(p["thr"])
    e = np.zeros(n, dtype=np.int8)
    e[(pos < thr) & (prev >= thr)] = 1                  # ушли в дисконт
    e[(pos > 1 - thr) & (prev <= 1 - thr) & (e == 0)] = -1   # ушли в премиум
    return strat.finish(bars, _with(p), Signals(n), e)


# --- 6 и 7. Уровни предыдущих суток и предыдущей недели --------------------

def _level_build(bars, p, period_ms, offset_ms):
    """Общий расчёт для суточных и недельных уровней: пробой или отбой.

    Два прочтения одного уровня, взаимоисключающие, и потому измеряются
    отдельными сочетаниями сетки:
      break — закрытие за уровнем считается пробоем, входим по направлению;
      fade  — заход за уровень тенью с возвратом обратно считается отбоем,
              входим против.
    Буфер в долях ATR отодвигает уровень от цены: без него любое дрожание в
    полтика объявляется пробоем.
    """
    n = len(bars.t)
    h, l, c = bars.h, bars.l, bars.c
    a = ind.atr(h, l, c, int(p.get("atr_n", 14)))
    ph, pl = _prev_period_hl(bars.t, h, l, period_ms, offset_ms)
    buf = float(p["buf"]) * a
    e = np.zeros(n, dtype=np.int8)
    if p["mode"] == "break":
        up = _first(c > ph + buf)
        dn = _first(c < pl - buf)
    else:
        up = _first((h > ph + buf) & (c < ph))     # сходили выше и вернулись
        dn = _first((l < pl - buf) & (c > pl))
    if p["mode"] == "break":
        e[up] = 1
        e[dn & (e == 0)] = -1
    else:
        e[up] = -1                                  # отбой вниз от верха
        e[dn & (e == 0)] = 1
    ex = _hold_exit(e, int(p["hold"]))
    return strat.finish(bars, _with(p), Signals(n), e, ex)


@strat.register("pdh_pdl", FAMILY, {
    "mode": ["break", "fade"],
    "buf": [0.0, 0.25, 0.5],
    "hold": [12, 24],
    "stop_atr": [1.5, 2.5],
    "rr": [1.5, 3.0],
}, "максимум и минимум предыдущих суток UTC: пробой либо отбой")
def s_pdh_pdl(bars, p):
    """Гипотеза: за вчерашним экстремумом стоит скопление стоп-заявок.

    Вчерашний максимум видят все и одинаково, поэтому под ним лежат стопы
    шортов и заявки пробойщиков. Отсюда два несовместимых утверждения, и оба
    ходят в обиходе: «уровень пробивают, чтобы забрать стопы и пойти дальше» и
    «уровень пробивают, чтобы забрать стопы и развернуться». Второе на жаргоне
    называют выносом ликвидности. Раз утверждения противоположны, вместе они
    непроверяемы — их и разводим по режимам сетки.

    Сутки нарезаются по UTC. Это не произвол: биржевые сводки, расчёт фандинга
    и большинство графиков считают день так же, и именно эту разметку видят
    все участники сразу.
    """
    return _level_build(bars, p, DAY_MS, 0)


@strat.register("session_levels", FAMILY, {
    "mode": ["break", "fade"],
    "buf": [0.0, 0.5],
    "hold": [24, 72],
    "stop_atr": [2.0, 3.0],
    "rr": [2.0, 3.0],
}, "максимум и минимум предыдущей недели (с понедельника UTC): пробой/отбой")
def s_session_levels(bars, p):
    """То же самое, но уровень недельный — и потому куда более людный.

    Если сдвиг вероятности у суточного уровня есть, у недельного он обязан
    быть заметнее: за неделю к нему привыкает больше народу, заявок вокруг
    копится больше. Если же у недельного эффекта нет, а у суточного нашёлся,
    это скорее говорит о случайности находки, чем о свойстве рынка. Пара
    стратегий тут работает взаимной проверкой.

    Неделя считается с понедельника UTC, поэтому перед делением время
    сдвигается на три дня: отсчёт эпохи начинается с четверга. Удержание
    длиннее суточного варианта — недельный уровень отрабатывается дольше, и
    двенадцати часов на него мало.
    """
    return _level_build(bars, p, WEEK_MS, WEEK_OFFSET_MS)


