def _causal_all(bars, max_combos=24, seed=0):
    """Прогнать проверку причинности по всей сетке (или по 24 её точкам).

    Проверяется каждое сочетание, а не одно «типовое»: утечка в это семейство
    попадает не из общей части, а из редкой ветки — например, из окна, которое
    при большом n перестаёт помещаться в выборку. Одна точка сетки такое
    пропустит.
    """
    rng = np.random.default_rng(seed)
    bad = 0
    for name in NAMES:
        st = strat.REG[name]
        combos = list(st.combos())
        if len(combos) > max_combos:
            idx = sorted(rng.choice(len(combos), max_combos, replace=False))
            take = [combos[i] for i in idx]
        else:
            take = combos
        fails = []
        for pp in take:
            try:
                engine.assert_causal(
                    lambda b, _p=pp, _s=st: _s.build(b, _p), bars)
            except AssertionError as exc:
                fails.append((pp, str(exc)[:110]))
        bad += len(fails)
        print("  %-12s сочетаний %3d, проверено %2d -> %s"
              % (name, len(combos), len(take),
                 "причинна" if not fails else "УТЕЧКА БУДУЩЕГО"))
        for pp, msg in fails[:3]:
            print("      %s\n      %s" % (pp, msg))
    return bad


