# -*- coding: utf-8 -*-
"""Возврат к средней: шесть способов задать рынку один и тот же вопрос.

ОБЩАЯ ГИПОТЕЗА СЕМЕЙСТВА

Цена дёргается сильнее, чем меняется представление участников о том, сколько
монета стоит. Крупная заявка, каскад ликвидаций, паника в выходные — всё это
уводит цену в сторону быстрее, чем подтягиваются те, кто готов торговать
против. Если сдвиг вызван не новостью, а нехваткой встречной ликвидности, то
через несколько часов маркетмейкеры и охотники за отклонением возвращают цену
к недавнему среднему. Значит, крайнее отклонение — это не сигнал «началось», а
сигнал «перебор, сейчас откатит».

Ровно поэтому семейство обязано ломаться на тренде. Когда цена уходит потому,
что рынок ПЕРЕОЦЕНИЛСЯ, никакого возврата не будет: отклонение от средней — это
и есть новая правда, а средняя просто отстала. Отличить одно от другого заранее
нельзя, но можно измерить силу направленного движения. Этим занят общий для
всех шести стратегий переключатель use_regime: при сильном тренде (ADX выше
порога) вход ПРОТИВ его направления запрещается. Вход по направлению тренда
остаётся разрешён — запрещаем не торговлю, а спор с рынком.

Главный опыт модуля: у каждой стратегии одна и та же сетка прогоняется дважды,
с фильтром и без. Разница между этими половинами и есть ответ на вопрос,
починил ли фильтр возврат к средней — или заодно вырезал те редкие резкие
откаты, на которых семейство только и зарабатывает.

ЧТО ЕЩЁ СРАВНИВАЕТСЯ ВНУТРИ СЕМЕЙСТВА

Стратегии разделены не только по индикатору, но и по МОМЕНТУ входа:
  * bb_mr и keltner_mr ждут ВОЗВРАТА — цена сначала закрылась за полосой, потом
    вернулась внутрь. Вход позже и дороже, зато после того, как падение
    выдохлось;
  * zscore_mr, ema_dist, st_reversal и rsi_regime входят НА КАСАНИИ порога, то
    есть ловят падающий нож: раньше и по лучшей цене, но против ещё живого
    движения.
Это два разных утверждения о рынке, и сравнить их на одних данных полезнее,
чем прогнать шесть вариаций одной мысли.

Выход у всех один и следует прямо из гипотезы: цель достигнута, когда цена
вернулась к своей середине. Поэтому exit — пересечение средней линии, а не
произвольное число баров удержания. Стоп и тейк добавляет общий хвост
strat.finish: стоп из ATR, тейк кратный риску (rr).

Нормировка размера под волатильность (voltarget) в сетки намеренно не
включена: она относится к управлению капиталом, а не к гипотезе, и удвоила бы
перебор. Размер позиции и без неё считает движок — от риска и до стопа.

О ЧИСЛЕ ПОПЫТОК. Шесть сеток дают 276 сочетаний. Это уже немало для поправки
на множественную проверку, поэтому пороги внутри стратегий взяты круглые и
редкие (2.0 / 2.5 / 3.0), а не мелким шагом: плато из трёх соседних значений
доказательнее, чем пик, найденный шагом 0.1.

Запуск самопроверки:
    cd research && python strat_meanrev.py
"""
import numpy as np

import engine
import ind
import strat
from engine import Signals

# Порог, выше которого рынок считается трендовым. 25 у Уайлдера — значение из
# первоисточника, а не подобранное здесь. Перебирается только у rsi_regime, где
# сила фильтра и есть предмет изучения.
ADX_TREND = 25.0
ADX_N = 14
# Средняя для краткосрочного разворота: восемь часов — примерно треть суток.
# Зафиксирована, чтобы не раздувать перебор.
ST_MEAN_N = 8

FAMILY = "meanrev"
NAMES = ["bb_mr", "zscore_mr", "ema_dist", "keltner_mr", "st_reversal",
         "rsi_regime"]


# --- общие мелкие детали ----------------------------------------------------

def _prev(x):
    """Значение того же ряда на предыдущем баре. Первый бар — NaN.

    Нужно везде, где важен не уровень, а момент его пересечения: «RSI ниже 30»
    держится десяток баров подряд, а «RSI только что опустился ниже 30» —
    событие, и сигналом является именно оно.
    """
    out = np.full(len(x), np.nan)
    out[1:] = x[:-1]
    return out


def _crossed(x):
    """Бары, где ряд сменил знак, то есть пересёк свою нулевую линию.

    Через это выражается выход всего семейства: если взять (цена - средняя), то
    смена знака и означает «цена вернулась к средней». Сторона перехода не
    важна, и это не небрежность: лонг открывался НИЖЕ средней, шорт — выше,
    поэтому первое же пересечение случается в нашу сторону.
    """
    p = _prev(x)
    ok = np.isfinite(x) & np.isfinite(p)
    return ok & (x * p <= 0)


def _down_cross(x, level):
    """Ряд опустился ниже уровня именно на этом баре."""
    p = _prev(x)
    return np.isfinite(x) & np.isfinite(p) & (x < level) & (p >= level)


def _up_cross(x, level):
    """Ряд поднялся выше уровня именно на этом баре."""
    p = _prev(x)
    return np.isfinite(x) & np.isfinite(p) & (x > level) & (p <= level)


def _in_atr(bars, x, n):
    """Величину в деньгах — в доли ATR, чтобы порог не зависел от монеты и года.

    Отклонение «на 900 долларов» само по себе не значит ничего: для биткоина по
    двадцать тысяч это много, по сто тысяч — ход одного спокойного бара. В долях
    ATR порог сравним и между монетами, и между эпохами.
    """
    a = ind.atr(bars.h, bars.l, bars.c, int(n))
    with np.errstate(divide="ignore", invalid="ignore"):
        d = x / a
    return np.where(np.isfinite(d), d, np.nan)


def _regime_veto(bars, p):
    """Где нельзя идти против тренда. Отдаёт (запрет лонга, запрет шорта).

    ADX меряет не направление, а СИЛУ направленного хода; +DI и -DI дают
    сторону. Если ход сильный и он вниз, покупка отскока — спор с рынком, а не
    сбор отклонения: на таких участках возврат к средней и теряет деньги
    пачками. Продавать в таком рынке никто не мешает.

    Пока ADX не досчитан (первые бары), фильтра просто нет. Это честнее, чем
    принять неизвестность за ноль и разрешить всё разом.
    """
    n = len(bars.t)
    off = np.zeros(n, dtype=bool)
    if not int(p.get("use_regime", 0)):
        return off, off
    a, pdi, ndi = ind.adx(bars.h, bars.l, bars.c, int(p.get("adx_n", ADX_N)))
    strong = np.isfinite(a) & (a > float(p.get("adx_max", ADX_TREND)))
    veto_long = strong & (ndi > pdi)      # сильный ход вниз — не покупаем
    veto_short = strong & (pdi > ndi)     # сильный ход вверх — не продаём
    return veto_long, veto_short


def _entries(bars, p, long_ok, short_ok):
    """Собрать направления, вырезав входы против сильного тренда."""
    e = np.zeros(len(bars.t), dtype=np.int8)
    vl, vs = _regime_veto(bars, p)
    e[long_ok & ~vl] = 1
    e[short_ok & ~vs] = -1
    return e


# --- 1. Край полосы Боллинджера --------------------------------------------

@strat.register("bb_mr", FAMILY, {
    "n": [20, 40],
    "k": [2.0, 2.5, 3.0],
    "rr": [1.0, 2.0],
    "stop_atr": [1.5, 2.5],
    "use_regime": [0, 1],
    "atr_n": [14],
}, "закрытие за полосой Боллинджера и возврат внутрь, выход на средней")
def s_bb_mr(bars, p):
    """Покупаем не сам провал за полосу, а его окончание.

    Полоса Боллинджера — это среднее плюс-минус k собственных отклонений цены
    за n баров, то есть порог «редко» в единицах самого рынка, а не в процентах.
    Закрытие за нижней полосой означает, что бар оказался в хвосте недавнего
    распределения: продавцы продавили цену дальше, чем она обычно ходит.

    Но пока цена сидит за полосой, продавец ещё сильнее покупателя, и ловить
    там нож дорого. Поэтому вход — на первом закрытии ОБРАТНО внутрь полосы:
    выброс кончился, а средняя ещё далеко. Цель — сама средняя, и на её
    пересечении позиция закрывается.

    Слабое место гипотезы известно заранее: в затяжном падении цена «едет по
    полосе», выходя и заходя обратно десяток раз подряд. Каждый такой заход
    даст сигнал на покупку. Это и должен отсекать use_regime.
    """
    n = len(bars.t)
    mid, up, dn, _w = ind.bbands(bars.c, int(p["n"]), float(p["k"]))
    c, pc = bars.c, _prev(bars.c)
    p_up, p_dn = _prev(up), _prev(dn)
    # «был снаружи, стал внутри» — сравниваем каждый бар со своей же полосой
    long_ok = np.isfinite(p_dn) & (pc < p_dn) & (c > dn)
    short_ok = np.isfinite(p_up) & (pc > p_up) & (c < up)
    e = _entries(bars, p, long_ok, short_ok)
    ex = _crossed(c - mid)                    # средняя достигнута — выходим
    return strat.finish(bars, p, Signals(n), e, ex)


# --- 2. Отклонение в собственных сигмах ------------------------------------

@strat.register("zscore_mr", FAMILY, {
    "n": [50, 100, 200],
    "z": [1.5, 2.0, 2.5],
    "rr": [1.5],
    "stop_atr": [2.0, 3.0],
    "use_regime": [0, 1],
    "atr_n": [14],
}, "цена ушла от средней на z своих отклонений, вход навстречу")
def s_zscore_mr(bars, p):
    """Тот же Боллинджер, но с длинной памятью и входом на касании.

    Смысл z-оценки: насколько текущая цена далека от средней за n баров, если
    мерить расстояние разбросом самой цены за те же n баров. Порог 2 означает
    «так далеко бывает примерно в одном случае из двадцати».

    Отличий от bb_mr два, и оба содержательные. Окно длиннее (50-200 часов
    против 20-40): проверяем не выброс одного дня, а уход от недельной нормы.
    И вход происходит в момент ПЕРВОГО пересечения порога, без ожидания
    возврата — то есть раньше и по лучшей цене, но против ещё живого движения.
    Сравнение bb_mr и zscore_mr на одних данных отвечает, что дороже: терпение
    или ранний вход.

    Выход — пересечение нуля z, то есть возвращение цены ровно к средней.
    """
    n = len(bars.t)
    z = ind.zscore(bars.c, int(p["n"]))
    zt = float(p["z"])
    long_ok = _down_cross(z, -zt)
    short_ok = _up_cross(z, zt)
    e = _entries(bars, p, long_ok, short_ok)
    ex = _crossed(z)
    return strat.finish(bars, p, Signals(n), e, ex)


# --- 3. Расстояние до EMA в единицах ATR -----------------------------------

@strat.register("ema_dist", FAMILY, {
    "ema_n": [20, 50, 100],
    "dist": [2.0, 3.0],
    "rr": [1.0, 2.0],
    "stop_atr": [2.0, 3.0],
    "use_regime": [0, 1],
    "atr_n": [14],
}, "цена оторвалась от EMA больше чем на dist ATR — вход навстречу")
def s_ema_dist(bars, p):
    """Резинка: чем дальше цена от средней, тем сильнее её тянет назад.

    Здесь расстояние меряется не разбросом цены, как у Боллинджера, а ATR —
    средним размахом бара. Разница не косметическая. Разброс закрытий не видит
    ни разрывов, ни длинных теней: рынок, который весь день мотает от края к
    краю и закрывается там же, по стандартному отклонению выглядит спокойным.
    ATR его спокойным не считает. Поэтому «три ATR от средней» — это «столько,
    сколько рынок обычно проходит за три бара», мера пути, а не мера разброса.

    Вход — на первом баре, где отрыв превысил порог. Цель — сама EMA: позиция
    закрывается, когда цена её пересекла, независимо от того, дошёл ли тейк.

    Чем длиннее EMA, тем реже событие и тем больше в нём тренда, а не шума. На
    ema_n=100 отрыв в три ATR — это уже, скорее всего, настоящее движение, и
    фильтру режима там будет что резать.
    """
    n = len(bars.t)
    e_line = ind.ema(bars.c, int(p["ema_n"]))
    d = _in_atr(bars, bars.c - e_line, int(p.get("atr_n", 14)))
    dt = float(p["dist"])
    long_ok = _down_cross(d, -dt)
    short_ok = _up_cross(d, dt)
    e = _entries(bars, p, long_ok, short_ok)
    ex = _crossed(d)                          # цена вернулась к EMA
    return strat.finish(bars, p, Signals(n), e, ex)


# --- 4. Канал Кельтнера ----------------------------------------------------

@strat.register("keltner_mr", FAMILY, {
    "n": [20, 50],
    "k": [1.5, 2.0, 2.5],
    "rr": [1.0, 2.0],
    "stop_atr": [2.0, 3.0],
    "use_regime": [0, 1],
    "atr_n": [14],
}, "выход за канал Кельтнера и возврат внутрь, выход на средней")
def s_keltner_mr(bars, p):
    """То же ожидание отката, но канал построен на размахе, а не на разбросе.

    Пара к bb_mr, поставленная ради одного различия. Полоса Боллинджера
    раздувается сама от себя: сильный бар входит в расчёт отклонения и тут же
    расширяет полосу, из-за чего в шторм цена «легально» уходит далеко и сигнала
    нет. Канал Кельтнера строится на ATR, который растёт медленнее и ровнее,
    поэтому в шторм он даёт сигналы там, где Боллинджер молчит — а в затишье,
    наоборот, молчит там, где Боллинджер уже кричит.

    Если у семейства есть настоящая жизнь, оба варианта должны быть похожи по
    знаку результата. Если один прибылен, а второй нет — прибыль сидит не в
    гипотезе, а в форме полосы, то есть в случайности.

    Вход, как у bb_mr, только на возврате внутрь канала. Выход — пересечение
    центральной EMA.
    """
    n = len(bars.t)
    mid, up, dn = ind.keltner(bars.h, bars.l, bars.c, int(p["n"]),
                              float(p["k"]))
    c, pc = bars.c, _prev(bars.c)
    p_up, p_dn = _prev(up), _prev(dn)
    long_ok = np.isfinite(p_dn) & (pc < p_dn) & (c > dn)
    short_ok = np.isfinite(p_up) & (pc > p_up) & (c < up)
    e = _entries(bars, p, long_ok, short_ok)
    ex = _crossed(c - mid)
    return strat.finish(bars, p, Signals(n), e, ex)


# --- 5. Краткосрочный разворот ---------------------------------------------

@strat.register("st_reversal", FAMILY, {
    "nb": [1, 2, 3],
    "move": [1.0, 2.0],
    "rr": [1.0, 2.0],
    "stop_atr": [1.5, 2.5],
    "use_regime": [0, 1],
    "atr_n": [14],
}, "nb баров подряд в одну сторону на move ATR — вход против")
def s_st_reversal(bars, p):
    """Самая грубая форма гипотезы: рынок редко идёт в одну сторону долго.

    Никаких полос и средних — только последние один-три бара. Условие двойное:
    все nb баров закрылись в одну сторону И суммарный ход составил не меньше
    move размахов ATR. Второе важнее первого: три вялых красных бара не значат
    ничего, а один падающий на полтора ATR — это уже вынос, у которого обычно
    есть отдача.

    Почему такое вообще может работать: резкий бар на часовом графике чаще
    вызван срабатыванием стопов и ликвидаций, чем приходом информации. Стопы
    заканчиваются, а цена остаётся смещённой — и её подбирают.

    Почему это, скорее всего, не переживёт издержек: событие частое, откат
    мелкий, а круговая сделка стоит около 0.16% оборота. Здесь мы, по сути,
    меряем, есть ли отдача ВООБЩЕ и хватает ли её на комиссию, — а не ищем
    готовую торговлю. Отрицательный ответ тут ожидаем и полезен.

    Выход — пересечение восьмибарной EMA, ближайшего аналога «середины» на
    таком коротком горизонте.
    """
    n = len(bars.t)
    nb = int(p["nb"])
    c = bars.c
    back = np.full(n, np.nan)
    back[nb:] = c[:-nb]
    mv = _in_atr(bars, c - back, int(p.get("atr_n", 14)))   # ход в ATR
    # все nb баров подряд в одну сторону
    d = c - _prev(c)
    up_all = np.ones(n, dtype=bool)
    dn_all = np.ones(n, dtype=bool)
    for k in range(nb):
        s = np.full(n, np.nan)
        s[k:] = d[:n - k]                 # разность, сдвинутая на k баров назад
        up_all &= np.isfinite(s) & (s > 0)
        dn_all &= np.isfinite(s) & (s < 0)
    m = float(p["move"])
    long_ok = dn_all & np.isfinite(mv) & (mv <= -m)
    short_ok = up_all & np.isfinite(mv) & (mv >= m)
    e = _entries(bars, p, long_ok, short_ok)
    ex = _crossed(c - ind.ema(c, ST_MEAN_N))
    return strat.finish(bars, p, Signals(n), e, ex)


# --- 6. RSI с явным фильтром режима ----------------------------------------

@strat.register("rsi_regime", FAMILY, {
    "rsi_n": [7, 14],
    "os": [25, 30],
    "adx_max": [20, 25, 30],
    "rr": [1.5],
    "stop_atr": [2.0, 3.0],
    "use_regime": [0, 1],
    "atr_n": [14],
}, "RSI-возврат, при сильном тренде вход против него запрещён")
def s_rsi_regime(bars, p):
    """Родная идея проекта, поставленная под вопрос о режиме рынка.

    Сам сигнал тот же, что у боевых ботов: RSI опустился ниже порога — покупаем
    ожидаемый отскок. Новое здесь одно — порог ADX стал перебираемым
    параметром, а не константой. Именно на этой стратегии видно, сколько стоит
    фильтр: при adx_max=20 запрещена почти половина рынка, при 30 — только
    редкие сильные тренды.

    Что мы надеемся увидеть: с ростом строгости фильтра число сделок падает, а
    средний результат сделки растёт. Если он не растёт, значит перепроданность
    на часовом графике не отличает откат от начала падения, и вся прежняя
    прибыль ботов была особенностью конкретного куска истории.

    Выход — возврат RSI к 50, то есть к середине его же шкалы. Для лонга из
    перепроданности это первое пересечение сверху вниз невозможно, поэтому
    сторона перехода снова не нужна.

    Замечание к сетке: при use_regime=0 три значения adx_max дают один и тот же
    результат. Избыточность оставлена намеренно, чтобы половины «с фильтром» и
    «без» были одинакового размера и сравнивались напрямую; при поправке на
    число попыток это надо помнить.
    """
    n = len(bars.t)
    r = ind.rsi(bars.c, int(p["rsi_n"]))
    os_ = float(p["os"])
    long_ok = _down_cross(r, os_)
    short_ok = _up_cross(r, 100.0 - os_)
    e = _entries(bars, p, long_ok, short_ok)
    ex = _crossed(r - 50.0)
    return strat.finish(bars, p, Signals(n), e, ex)


