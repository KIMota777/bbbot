@strat.register("ema_slope", "trend", {
    "ema_n": [20, 50, 100, 200],
    "slope_n": [6, 24],
    "thr": [0.3, 0.8, 1.5],
    "stop_atr": [2.0, 3.0],
    "atr_n": [14],
}, "наклон одной средней за n баров, измеренный в размахах ATR")
def s_ema_slope(bars, p):
    """Тренд без второй средней: только скорость и порог.

    Все предыдущие приборы так или иначе сравнивают две линии. Здесь нарочно
    оставлена одна: берём среднюю, смотрим, на сколько она сдвинулась за
    slope_n баров, и делим на текущий ATR. Получается ответ на прямой вопрос:
    «средняя ушла на сколько обычных размахов бара?» Порог thr отсекает
    дрейф — если средняя ползёт медленнее, чем рынок случайно колышется, это
    не тренд.

    Зачем такая проверка нужна: если пересечения из предыдущих стратегий
    работают, то работать они должны примерно так же, как простой наклон,
    потому что пересечение двух средних — это по сути и есть утверждение о
    наклоне, только в неявном виде. Если голый наклон окажется заметно хуже
    пересечений, значит польза была не в измерении инерции, а в чём-то ещё, и
    это «что-то ещё» надо назвать вслух, прежде чем ему верить.

    Деление на ATR обязательно: наклон в долларах несравним между 2023 и 2026
    годом и между BTC и DOGE, а наклон в размахах бара сравним.
    """
    n = len(bars.t)
    en = int(p["ema_n"])
    sn = int(p["slope_n"])
    if en + sn * 2 >= n:
        return Signals(n)
    m = ind.ema(bars.c, en)
    a = ind.atr(bars.h, bars.l, bars.c, int(p.get("atr_n", 14)))
    sl = (m - _shift(m, sn)) / a       # NaN в ATR сам погасит сигнал
    thr = float(p["thr"])
    e, ex = _edges(_state(sl > thr, sl < -thr))
    return strat.finish(bars, p, Signals(n), e, ex)


