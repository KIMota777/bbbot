def _self_test():
    import random
    import time

    import engine
    import metrics
    import rdata

    total = sum(strat.REG[nm].n_combos() for nm in FAMILY)
    print("МОДУЛЬ strat_trend: %d стратегий, %d сочетаний всего\n"
          % (len(FAMILY), total))

    # 1. Причинность. Портим будущее шумом и требуем, чтобы прошлое не дрогнуло.
    bt, _ = rdata.load_bars("BTCUSDT", "60").slice(*rdata.SPLITS["train"])
    print("1. ПРИЧИННОСТЬ на train BTCUSDT 1ч (%d баров)" % len(bt.t))
    bad = 0
    for nm in FAMILY:
        st = strat.REG[nm]
        combos = list(st.combos())
        pick = combos if len(combos) <= 24 \
            else random.Random(0).sample(combos, 24)
        t0 = time.time()
        errs = []
        for pp in pick:
            try:
                engine.assert_causal(lambda x, q=pp, s=st: s.build(x, q), bt)
            except AssertionError as exc:
                errs.append("%s -> %s" % (pp, str(exc)[:90]))
        bad += len(errs)
        print("   %s %-11s сетка %2d, проверено %2d, чисто %2d  (%4.1f с)"
              % ("+" if not errs else "!", nm, len(combos), len(pick),
                 len(pick) - len(errs), time.time() - t0))
        for line in errs[:3]:
            print("        %s" % line)

    # 2. Показательные прогоны. Прогрев берём слева от train, чтобы первые
    #    сделки считались по прогретому прибору, а не по недосчитанному.
    bw, off = rdata.load_bars("BTCUSDT", "60").slice(
        *rdata.SPLITS["train"], 1200)
    cfg = engine.Cfg()
    print("\n2. ПОКАЗАТЕЛЬНЫЕ ПРОГОНЫ, train BTCUSDT 1ч, риск 1%% на сделку,")
    print("   комиссия тейкера, проскальзывание и фандинг включены")
    for nm in FAMILY:
        st = strat.REG[nm]
        grid = list(st.combos())
        for label, pp in SHOW[nm]:
            if pp not in grid:
                print("   ! %s: сочетание вне сетки %s" % (label, pp))
                bad += 1
                continue
            res = engine.run(bw, st.build(bw, pp), cfg, start_i=off)
            s = metrics.summarize(res, n_trials=total, label=label)
            print("   " + metrics.brief(s))
            print("      издержки %7.0f$ фандинг %7.0f$ из капитала %.0f$ | "
                  "держим %4.0f ч | DSR %.2f"
                  % (s["fees"], s["funding"], res.start_equity,
                     s["avg_hold"], s["dsr"]))

    print("\nИТОГ: %s" % ("всё зелено, утечек будущего нет" if not bad
                          else "ПРОВАЛОВ %d" % bad))
    return bad


if __name__ == "__main__":
    import sys

    sys.exit(1 if _self_test() else 0)
