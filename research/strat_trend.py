# -*- coding: utf-8 -*-
"""Следование за трендом: семь разных способов спросить «куда идёт цена».

ОБЩАЯ ГИПОТЕЗА СЕМЕЙСТВА. Цена не перескакивает к новому справедливому уровню
одним прыжком, потому что мешают две вещи. Первая: новость доходит до
участников не одновременно — сначала до тех, кто сидит в стакане круглые сутки,
потом до всех остальных. Вторая: крупную позицию нельзя набрать за одну сделку,
её режут на части и растягивают на часы, а иногда на дни, чтобы не двигать цену
против себя. Пока такой набор идёт, движение продолжается — не потому, что
«тренд твой друг», а потому, что покупатель ещё не закончил покупать.

Если эта гипотеза верна, то знак сегодняшнего хода несёт информацию о знаке
завтрашнего. Все семь стратегий ниже измеряют один и тот же знак, только
разными приборами, и отличаются главным образом ИНЕРЦИОННОСТЬЮ прибора: как
долго он подтверждает разворот. Поэтому у каждой сетки есть ось «горизонт» —
короткий, средний, длинный. Ищем не лучшую точку, а участок, где соседние
горизонты ведут себя похоже: если прибыль держится только на одной настройке и
рассыпается у соседних, это не тренд, это совпадение.

ЧТО ЗАРАНЕЕ ИЗВЕСТНО ПРО ЧИСЛА. Круговая сделка стоит примерно 0.16% объёма
(комиссия тейкера с обеих ног плюс проскальзывание), и трендовая позиция вдобавок
платит фандинг всё время удержания. На часовых барах прибор, дающий несколько
сотен сделок за выборку, обязан отдать издержкам больше, чем обычно приносит
инерция. Поэтому чувствительные варианты (разворот гистограммы, параболик с
мелким шагом) заранее подозрительны — и они здесь оставлены НАРОЧНО, чтобы
увидеть цену чувствительности в деньгах, а не рассуждать о ней.

ПРО ПРИЧИННОСТЬ. Все приборы взяты из ind.py, где окно закрывается на текущем
баре. Ни одна строчка ниже не смотрит вперёд: сдвиг назад делается явно через
_shift, состояние тянется вперёд через _hold (только из прошлого в будущее),
исполнение сдвигает движок сам. Проверяется это не глазами, а engine.assert_causal
в конце файла.

ЧЕГО ЗДЕСЬ НЕТ. Размер позиции — не моя забота: движок считает его от риска и
расстояния до стопа. Нормировку размера по волатильности (voltarget) в сетки не
включаю намеренно — это отдельная ось, общая для всех семейств, и умножать на
неё перебор значит платить поправкой на множественную проверку за то, что к
гипотезе инерции отношения не имеет.
"""
import numpy as np

import ind
import strat
from engine import Signals

# Имена стратегий этого модуля — по нему идёт самопроверка внизу файла.
FAMILY = ["macd", "adx_dmi", "supertrend", "ichimoku", "psar", "ma_ribbon",
          "ema_slope"]


# --- мелкие общие детали ----------------------------------------------------

def _shift(x, k):
    """Значение k баров назад. Пустые места — NaN, а не ноль.

    Ноль здесь означал бы «прибор показал ноль», и сравнение с порогом дало бы
    сигнал на пустом месте. NaN в сравнении честно даёт False.
    """
    out = np.full(len(x), np.nan)
    if 0 < k < len(x):
        out[k:] = x[:len(x) - k]
    elif k == 0:
        out[:] = x
    return out


def _state(up, dn):
    """Два условия — одно состояние: +1 вверх, -1 вниз, 0 «не знаю».

    NaN в условиях сам собой превращается в False, то есть в 0: пока прибор не
    прогрелся, стратегия молчит, а не покупает.
    """
    st = np.zeros(len(up), dtype=np.int8)
    st[np.asarray(up, dtype=bool)] = 1
    st[np.asarray(dn, dtype=bool)] = -1
    return st


def _edges(st):
    """Из ряда состояний — входы и выходы.

    Вход ставим только там, где состояние СМЕНИЛОСЬ. Если ставить его на каждом
    баре подходящего состояния, то после каждого выбитого стопа стратегия тут же
    залезает обратно в тот же самый тренд, и одна неудачная идея превращается в
    десять оплаченных комиссий.

    Выход — там, где состояние погасло: прибор перестал видеть направление.
    Разворот в противоположную сторону движок обработает сам, ему достаточно
    входа с обратным знаком.
    """
    n = len(st)
    prev = np.zeros(n, dtype=np.int8)
    prev[1:] = st[:-1]
    e = np.zeros(n, dtype=np.int8)
    m = (st != prev) & (st != 0)
    e[m] = st[m]
    return e, (st == 0)


def _hold(st):
    """Тянем последнее ненулевое состояние вперёд.

    Нужно там, где фильтр силы тренда должен решать, ВХОДИТЬ ли, но не должен
    выгонять из уже открытой позиции. Смотрит строго назад: индекс последнего
    ненулевого бара накапливается максимумом слева направо.
    """
    idx = np.where(st != 0, np.arange(len(st)), 0)
    np.maximum.accumulate(idx, out=idx)
    return st[idx]


# --- 1. MACD ----------------------------------------------------------------

@strat.register("macd", "trend", {
    "fast": [6, 12, 24, 48],
    "slow_mult": [2, 3],
    "mode": ["cross", "zero", "turn"],
    "stop_atr": [2.0, 3.0],
    "atr_n": [14],
}, "разница двух средних против своей сглаженной версии: три способа читать")
def s_macd(bars, p):
    """Скорость ухода цены от собственной нормы — и момент, когда она сменилась.

    Разница быстрой и медленной средних — это, по сути, скорость: насколько
    свежая цена оторвалась от того, что рынок считал нормой недавно. Сигнальная
    линия — та же скорость, только сглаженная. Их пересечение говорит, что
    ускорение сменило знак. Гипотеза: раз крупный участник набирает позицию
    частями, ускорение держится дольше одного бара, и войти вслед за ним не
    поздно даже с задержкой на сглаживание.

    Три способа чтения, и они правда разные:
      cross — линия пересекла сигнальную. Это ТО ЖЕ САМОЕ, что «гистограмма
              сменила знак»: гистограмма по построению и есть их разность.
              Отдельного варианта под неё нет не по недосмотру — его просто не
              существует, это одна и та же величина под двумя названиями.
      zero  — линия пересекла ноль, то есть быстрая средняя обогнала медленную.
              Медленнее и грубее: подтверждения ждём дольше, зато меньше дёрганья.
      turn  — гистограмма РАЗВЕРНУЛАСЬ (сменился знак её приращения). Самый
              ранний сигнал и самый шумный: ловит замедление тренда, а не смену.
              Оставлен, чтобы измерить, сколько стоит спешка.

    Пара периодов задана как быстрый и множитель, а не двумя свободными
    числами: свободная пара половину сетки тратит на бессмысленные сочетания,
    где «быстрый» медленнее «медленного».
    """
    n = len(bars.t)
    fast = int(p["fast"])
    slow = int(fast * p["slow_mult"])
    sig_n = max(3, int(round(fast * 0.75)))     # классическая пропорция 12/26/9
    if slow + sig_n >= n:
        return Signals(n)
    line, sl, hist = ind.macd(bars.c, fast, slow, sig_n)

    mode = p["mode"]
    if mode == "cross":
        st = _state(hist > 0, hist < 0)
    elif mode == "zero":
        st = _state(line > 0, line < 0)
    else:
        d = hist - _shift(hist, 1)
        st = _state(d > 0, d < 0)
    e, ex = _edges(st)
    return strat.finish(bars, p, Signals(n), e, ex)


# --- 2. ADX + пересечение DI ------------------------------------------------

@strat.register("adx_dmi", "trend", {
    "n": [7, 14, 21, 28],
    "adx_min": [20, 25, 30],
    "exit_weak": [0, 1],
    "stop_atr": [2.0, 3.0],
    "atr_n": [14],
}, "направление по +DI/-DI, но только когда ADX подтверждает силу хода")
def s_adx_dmi(bars, p):
    """Направление отдельно, сила отдельно — и торгуем только при обеих.

    +DI и -DI сравнивают, чего за период набралось больше: приращений максимума
    или приращений минимума. Это чистое направление, и в боковике оно
    пересекается без конца, потому что там ни того ни другого не набирается
    заметно больше. ADX измеряет другое: насколько дневной ход перевешивает
    болтанку внутри. Гипотеза семейства работает не всегда, а только когда в
    рынок идёт направленный поток заявок; ADX — самая дешёвая попытка отличить
    такой рынок от пилы.

    Порог силы — главный параметр. Низкий порог пропускает пилу, высокий
    пускает в тренд так поздно, что брать уже нечего. Поэтому три порога и
    четыре периода: если инерция настоящая, между ними должно быть плато, а не
    один счастливый угол.

    exit_weak решает судьбу открытой позиции при ослаблении тренда:
      1 — гаснет ADX, выходим (тренд кончился, дальше держать нечего);
      0 — держим до противоположного пересечения DI, фильтр силы отвечает
          только за вход. Второй вариант даёт длиннее удержание и, значит,
          больше фандинга — эту цену тоже надо увидеть.
    """
    n = len(bars.t)
    per = int(p["n"])
    if per * 3 >= n:
        return Signals(n)
    a, pdi, ndi = ind.adx(bars.h, bars.l, bars.c, per)
    strong = a >= float(p["adx_min"])
    st = _state(strong & (pdi > ndi), strong & (ndi > pdi))
    if not int(p["exit_weak"]):
        st = _hold(st)                 # слабость не выгоняет, только не пускает
    e, ex = _edges(st)
    return strat.finish(bars, p, Signals(n), e, ex)


# --- 3. Supertrend ----------------------------------------------------------

@strat.register("supertrend", "trend", {
    "n": [7, 10, 14, 20],
    "k": [1.5, 2.0, 3.0, 4.0],
    "stop_atr": [2.0, 3.0],
    "atr_n": [14],
}, "смена стороны полосы, отстроенной от ATR")
def s_supertrend(bars, p):
    """Разворот признаём, только если цена прошла против больше обычного бара.

    Полоса ставится на k размахов ATR от середины бара и подтягивается за ценой,
    но никогда не отступает назад, пока сторона не сменилась. Смысл в множителе
    k: он переводит вопрос «это разворот или шум?» в измеримый вид. Если цена
    ушла против направления меньше чем на k обычных дневных размахов — это
    обычная болтанка, и мнение прибора не меняется.

    Гипотеза здесь та же, что у всего семейства, но с честной поправкой на
    масштаб: инерция живёт в единицах волатильности, а не в процентах. В
    спокойном рынке разворотом считается ход в 1%, в штормовом такой же ход —
    обычный вторник. Малые k (1.5) должны дать много сделок и, скорее всего,
    отдать всё издержкам; большие (4.0) — редкие входы, но каждый с длинным
    отступом. Где-то между ними и лежит ответ, есть ли тут вообще что ловить.
    """
    n = len(bars.t)
    per = int(p["n"])
    if per * 3 >= n:
        return Signals(n)
    _line, d = ind.supertrend(bars.h, bars.l, bars.c, per, float(p["k"]))
    e, ex = _edges(d.astype(np.int8))
    return strat.finish(bars, p, Signals(n), e, ex)


# --- 4. Ишимоку -------------------------------------------------------------

@strat.register("ichimoku", "trend", {
    "tk": [5, 9, 18, 26],
    "need_cloud": [0, 1],
    "stop_atr": [2.0, 3.0],
    "trail_atr": [0.0, 4.0],
    "atr_n": [14],
}, "цена относительно облака плюс пересечение conv/base")
def s_ichimoku(bars, p):
    """Согласие быстрой и медленной середины диапазона, подтверждённое облаком.

    conv и base — середины диапазона за короткое и длинное окно. Их взаимное
    положение говорит, куда смещается сам диапазон. Облако — память рынка о том,
    где торговали последние несколько десятков баров. Смысл условия «цена над
    облаком» простой и вполне человеческий: все, кто покупал в этом диапазоне,
    сейчас в плюсе, и им незачем продавать в ноль при первом откате. Под
    облаком зеркально: над каждым отскоком висят желающие выйти в безубыток.

    Облако здесь НЕ сдвинуто вперёд, и это не упрощение, а исправление.
    Классическое построение рисует его на 26 баров вперёд — на графике удобно,
    в бэктесте это означает сравнение цены со значением, которое будет
    посчитано позже. Такой график всегда красивый и всегда лживый.

    need_cloud проверяет, нужно ли облако вообще: 0 — торгуем по одному
    пересечению conv/base, 1 — требуем ещё и цену по нужную сторону от обеих
    границ. Если облако не улучшает результат, значит вся его польза была в
    сдвиге вперёд, то есть в подглядывании.

    Периоды заданы одним числом tk, остальные два — в классической пропорции
    9:26:52. Растягивать пропорцию отдельными параметрами значит перебирать
    формы облака, а проверяем мы не форму, а горизонт.
    """
    n = len(bars.t)
    a = int(p["tk"])
    b = int(round(a * 2.9))
    s = int(round(a * 5.8))
    if s * 2 >= n:
        return Signals(n)
    conv, base, sa, sb = ind.ichimoku(bars.h, bars.l, bars.c, a, b, s)
    up = conv > base
    dn = conv < base
    if int(p["need_cloud"]):
        top = np.maximum(sa, sb)
        bot = np.minimum(sa, sb)
        up = up & (bars.c > top)
        dn = dn & (bars.c < bot)
    e, ex = _edges(_state(up, dn))
    return strat.finish(bars, p, Signals(n), e, ex)


# --- 5. Параболик -----------------------------------------------------------

@strat.register("psar", "trend", {
    "step": [0.01, 0.02, 0.04],
    "mx": [0.1, 0.2, 0.3],
    "filt": [0, 200],
    "stop_atr": [2.0, 3.0],
    "atr_n": [14],
}, "смена стороны параболика, с фильтром длинной средней и без него")
def s_psar(bars, p):
    """Чем дольше живёт тренд, тем меньше пространства ему остаётся.

    Параболик устроен так: пока движение обновляет экстремум, коэффициент
    ускорения растёт, и точка подтягивается к цене всё быстрее. То есть молодому
    тренду прибор даёт много места, зрелому — мало. За этим стоит разумная
    мысль: чем дальше зашло движение, тем дороже стоит каждый следующий шаг и
    тем ближе момент, когда набирающий позицию закончит.

    Слабое место известно заранее — в боковике параболик переворачивается почти
    на каждом колебании, и на часовых барах это сотни сделок за выборку.
    Поэтому вторая ось сетки: filt=200 требует, чтобы переворот совпадал со
    стороной длинной средней, filt=0 берёт параболик как есть. Разница между
    ними и есть ответ на вопрос, нужен ли этому прибору взрослый присмотр.

    Когда фильтр запрещает обе стороны (цена ровно на средней или средняя ещё
    не прогрелась), состояние гаснет и позиция закрывается: сидеть в сделке,
    условия которой больше не выполняются, — это уже не стратегия, а надежда.
    """
    n = len(bars.t)
    _sar, d = ind.psar(bars.h, bars.l, float(p["step"]), float(p["mx"]))
    st = d.astype(np.int8)
    f = int(p["filt"])
    if f:
        if f >= n:
            return Signals(n)
        m = ind.ema(bars.c, f)
        st = _state((st > 0) & (bars.c > m), (st < 0) & (bars.c < m))
    e, ex = _edges(st)
    return strat.finish(bars, p, Signals(n), e, ex)


# --- 6. Веер средних --------------------------------------------------------

@strat.register("ma_ribbon", "trend", {
    "n_ma": [4, 5, 6],
    "base": [8, 13, 21],
    "mult": [1.5, 2.0],
    "stop_atr": [2.0, 3.0],
    "atr_n": [14],
}, "4-6 средних, выстроенных строго по порядку периодов")
def s_ma_ribbon(bars, p):
    """Требование согласия всех горизонтов сразу.

    Веер — это набор средних с растущими периодами. Когда они выстроены строго
    по порядку (самая короткая выше всех для роста, ниже всех для падения),
    это значит, что и вчерашний взгляд, и недельный, и месячный показывают одно.
    Гипотеза: разногласие горизонтов — признак перекладки, а не тренда; пока
    участники с разными сроками удержания видят рынок по-разному, движение
    упирается во встречный поток. Согласие всех сроков — редкое состояние, и в
    нём встречного потока нет.

    Плата за строгость известна: пока веер сложится, лучшая часть хода позади.
    Именно поэтому здесь ось «сколько средних»: 4 — мягкое требование, 6 —
    жёсткое. Если жёсткое стабильно хуже, значит согласие горизонтов приходит
    слишком поздно, чтобы на нём зарабатывать.

    Периоды растут геометрически от base с множителем mult: при base=8, mult=2
    и шести средних длиннейшая охватывает 256 часов, это чуть меньше двух
    недель. Арифметический шаг был бы неправильным — восприятие срока у рынка
    ближе к отношению, чем к разности: разница между 8 и 16 часами велика, между
    200 и 208 её нет.
    """
    n = len(bars.t)
    k = int(p["n_ma"])
    per = [max(2, int(round(p["base"] * p["mult"] ** j))) for j in range(k)]
    if len(set(per)) < k or per[-1] * 2 >= n:
        return Signals(n)              # вырожденный веер: периоды слиплись
    ma = np.vstack([ind.ema(bars.c, q) for q in per])
    d = ma[:-1] - ma[1:]               # каждая быстрее следующей — на сколько
    up = np.all(d > 0, axis=0)
    dn = np.all(d < 0, axis=0)
    e, ex = _edges(_state(up, dn))
    return strat.finish(bars, p, Signals(n), e, ex)


