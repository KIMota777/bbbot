#
# ЧЕГО ЭТО НЕ ЗНАЧИТ. Четырнадцать и девятнадцать сделок — выборка, на которой
# ничего доказать нельзя; проверка на значимость их не проходит. Гейт по своей
# природе снижает РИСК, а не добавляет доход: на пятнадцати конфигах он улучшил
# просадку у большинства и доход примерно у половины. Эти два конфига — лучшее,
# что нашлось, а не подтверждённо прибыльное.
def _with_gate(base, lev=5, gate=0.6):
    """Копия конфига с включённым гейтом и сниженным плечом."""
    out = dict(base)
    out["vol_gate"] = gate
    out["lev"] = lev
    return out


