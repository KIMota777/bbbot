# ОСЛАБЛЕННЫЙ ГЕЙТ ШОРТА
#
# ЗАЧЕМ. Гейт фандинга на шортовой стороне (fund_short_min) пускает шорт
# только при ставке ВЫШЕ порога. У LTC/final_w порог 0.0087 — и он оказался
# на КРАЮ широкого плато, причём худшей точкой на нём. Перебор порога от
# -0.006 до +0.020 (плечо x5, обе половины порознь):
#
#   порог     обучение   ХОЛДОУТ  сделок холдоута
#   -0.0030    +81.2%     +73.5%      76
#    0.0020    +94.7%     +66.8%      63
#    0.0050   +104.7%     +56.6%      51   <- максимум обучения
#    0.0060    +99.4%     +60.5%      47
#    0.0087    +99.7%     +39.3%      31   <- было
#    0.0100    +80.3%     +32.6%      28
#
# Просадка холдоута при этом не растёт: 9.4-11.2% против 9.7%. То есть гейт
# зря резал сделки — не улучшая риск, только уменьшая число наблюдений.
#
# ОТБОР ЧЕСТНЫЙ. Порог выбран по МАКСИМУМУ ДОХОДА ОБУЧАЮЩЕЙ ПОЛОВИНЫ (0.0050
# даёт +104.7%, больше всех), холдоут только измерял. За семнадцать попыток
# улучшения это первый случай, когда отбор по обучению улучшил и проверку.
#
# УСТОЙЧИВОСТЬ — ПОПОЛАМ, и первая редакция этого абзаца была неверна.
# Тогда здесь стояло «устойчивость выше» по обеим половинам. Числа были
# получены сломанной проверкой: она возмущала геном, но фильтр входа брала от
# ИСХОДНОГО конфига, а fund_short_min живёт именно в фильтре — то есть
# измеряла ровно тот ген, который правка и меняет, как неизменившийся
# (см. all_configs_honest.build_filter).
#
# Честный пересчёт 06.09.2026, медиана 40 соседей (каждый числовой ген
# сдвинут на ±10%), фильтр строится под каждого соседа:
#
#              обучение   ХОЛДОУТ
#   final_w     +24.11%    +9.37%
#   final_wf    +20.54%   +36.97%
#
# То есть на проверочной половине устойчивость вчетверо выше, а на обучающей
# НИЖЕ родительской. Одно из двух условий уровня A конфиг выполняет хуже
# родителя. Сделок на холдоуте 51 вместо 31 — на таком числе числам можно
# верить чуть больше.
#
# ЧТО ПРОВЕРКА НЕ ПОДТВЕРДИЛА. Если оставить всю машинерию бота, а случайно
# выбрать МОМЕНТЫ входа (столько же баров, та же сторона), медиана 400
# прогонов на холдоуте +35.8% против ботовских +56.6%: бот на 86-м
# процентиле, p=0.14. Значит преимущество в выборе момента входа здесь не
# показано. Что показано — управление риском: простой шорт на том же плече
# ликвидируется на обеих половинах, а шорт без плеча даёт на холдоуте +58.3%
# (ничья по доходу) при просадке $6.41 против $2.38 у бота.
#
# ЧЕГО ЭТО НЕ ЗНАЧИТ. Согласия между конфигами НЕТ: у соседнего LTC/final то
# же ослабление ухудшает обучение (+34.8% -> +17.3%), хотя холдоут улучшает
# (+1.1% -> +15.1%). Поэтому конфиг добавлен РЯДОМ с нынешним, а не вместо
# него: пусть оба стоят на витрине и разница видна.
#
# И это по-прежнему шортовая стратегия. Правка не про лонги — она вообще их
# не трогает, доля лонгов остаётся 0.0% на обучении и 1.2% на холдоуте.
def _loosen_short_gate(base, thr):
    """Копия конфига с ослабленным порогом входа в ШОРТ по фандингу."""
    out = dict(base)
    out["fund_short_min"] = thr
    return out


SYMBOL_PARAMS["LTCUSDT"]["final_wf"] = _loosen_short_gate(
    SYMBOL_PARAMS["LTCUSDT"]["final_w"], 0.0050)


SYMBOL_PARAMS["BTCUSDT"]["final_w"] = _wide(
    SYMBOL_PARAMS["BTCUSDT"]["final"], 1.25)
