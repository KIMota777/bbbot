# копеечным стопом и 239 копеечным тейком: сделка есть, издержки уплачены,
# результата нет. Ход цены между входом и выходом сопоставим со стоимостью
# круга, и стратегия торгует в масштабе, где её съедают комиссии.
#
# Отсюда правка: умножить tp и sweep на общий множитель. Ничего больше не
# трогается — ни вход, ни сетка, ни фильтры.
#
# ЭТО ПЛАТО, А НЕ ПИК. У LTC/final холдоут положителен при ВСЕХ множителях от
# 1.25 до 4.0 (семь значений подряд): +20.4, +22.0, +26.4, +26.8, +37.5, +29.6,
# +31.3. Одиночный пик так себя не ведёт.
#
# ПЕРЕНОС ЧЕСТНЫЙ. Множитель выбран ТОЛЬКО по обучающей половине (лучший доход
# на просадку среди тех, у кого просадка обучения <= 20% и итог положителен),
# холдоут только измерял. Из пятнадцати конфигов такой множитель нашёлся у
# пяти, и все пять оказались в плюсе на холдоуте — впервые за всю работу отбор
# перенёсся.
#
#   LTC final  x2.50  обучение +94.1% (DD 17.9%), холдоут +37.5% (DD 3.9%)
#   BTC normal x1.25  обучение +26.7% (DD 13.7%), холдоут +21.0% (DD 15.1%)
#   BTC bear   x1.25  обучение +57.8% (DD  4.1%), холдоут  +2.1% (DD 8.2%)
#   BTC final  x1.25  обучение +57.1% (DD  4.1%), холдоут  +2.2% (DD 8.0%)
#
# ЧЕГО ЭТО НЕ ЗНАЧИТ. Сделок мало: у BTC десять на холдоуте, у LTC двадцать
# девять. Значимости на таком числе нет и быть не может. И у расширения есть
# понятная цена: сделок становится меньше, а каждая крупнее — то есть результат
# сильнее зависит от отдельных исходов.
def _wide(base, k, lev=5):
    """Копия конфига с раздвинутыми тейком и стопом."""
    out = dict(base)
    for gene in ("tp", "sweep"):
        if gene in out:
            out[gene] = out[gene] * k
    out["lev"] = lev
    return out


SYMBOL_PARAMS["LTCUSDT"]["final_w"] = _wide(
    SYMBOL_PARAMS["LTCUSDT"]["final"], 2.50)
SYMBOL_PARAMS["BTCUSDT"]["normal_w"] = _wide(
    SYMBOL_PARAMS["BTCUSDT"]["normal"], 1.25)
