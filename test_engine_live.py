    # импульсом. Два одинаковых сценария, отличающихся только свечой-кандидатом:
    # падающая (бычий ОБ обязан появиться и сработать на возврате цены) и
    # растущая (бычьего ОБ быть не должно вовсе).
    def ob_case(cand_up):
        cs = [bar(i, 100.0, 100.1, 99.9, 100.0) for i in range(12)]
        cs.append(bar(12, 99.8, 100.3, 99.7, 100.2) if cand_up
                  else bar(12, 100.2, 100.3, 99.7, 99.8))
        start = 100.2 if cand_up else 99.8
        p = start
        for k, i in enumerate(range(13, 18)):            # импульс вверх ~3.2%
            o = p
            p = start + 3.2 * (k + 1) / 5.0
            cs.append(bar(i, o, p + 0.05, o - 0.05, p))
        top = p
        for k, i in enumerate(range(18, 24)):            # возврат цены к зоне
            o = p
            p = top - 2.9 * (k + 1) / 6.0
            cs.append(bar(i, o, o + 0.05, p - 0.05, p))
        return cs

    ob_d, _ = smc.find_order_blocks(ob_case(False), bars_per_day=5)
    ob_u, _ = smc.find_order_blocks(ob_case(True), bars_per_day=5)
    print("     OB: кандидат-падение bull[18:24]=%s | кандидат-рост bull[18:24]=%s"
          % ([int(x) for x in ob_d[18:24]], [int(x) for x in ob_u[18:24]]))
    # Ловит подмену is_down_candle на is_up_candle (smc.py:79-83): зона
    # перестанет строиться на правильной свече и построится на неправильной.
    check(ob_d[23] and not any(ob_d[13:18]),
          "smc: бычий ордер-блок ставится на падающей свече и ждёт возврата цены")
    check(not any(ob_u[13:24]),
          "smc: растущая свеча перед импульсом вверх ордер-блоком НЕ считается")

