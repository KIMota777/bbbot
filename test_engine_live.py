def test_silent_modules():
    """Четыре модуля, у чьих «тестов» не было ни одного утверждения.

    test_evolution8.py / test_patterns.py / test_signals.py / test_smc.py —
    печатающие скрипты: они зелены, пока код не падает с исключением, и не
    краснеют ни от какой ошибки внутри evolution8/patterns/signal_engine/smc.
    Здесь для каждого из четырёх модулей проверяется то, что скрипт только
    печатал: не «сколько процентов времени сигнал активен», а ЧТО ИМЕННО
    обязано быть верно на задаче с известным ответом.

    Всё считается на маленьких искусственных свечах: сети нет, доли секунды.
    """
    import random

    import all_configs_honest as ach
    import evolution8 as e8
    import patterns as pt
    import signal_engine as se
    import smc

    TS = 1600000000000

    def bar(i, o, h, l, c):
        return [TS + i * 900000, o, h, l, c]

    # ========================================================================
    # evolution8.py — ворота SMC в make_filter8 (строки ~50-88)
    # ========================================================================
    # Что печатал старый тест: «сделок N, баланс X, слив False». Число сделок
    # не падает, если ворота перепутают лонг с шортом или мягкий режим станет
    # строгим: сделок просто станет другое количество, и никто не заметит.
    # Здесь ворота проверяются по таблице истинности на четырёх барах.
    n8 = 8

    def aux8(ob_bull, ob_bear, structure):
        """aux ровно того вида, что строит e7.build_aux_full, но пустой: все
        ворота v4-v7 выключены геномом, поэтому их массивы не читаются, а
        строятся при сборке фильтра безусловно — отсюда заглушки."""
        z = [None] * n8

        def pad(a, fill):
            return list(a) + [fill] * (n8 - len(a))

        return dict(fund=z, oi_chg=z, spx5=z, dxy5=z, gold5=z,
                    closes=[100.0] * n8,
                    ema=[list(z) for _ in range(5)],
                    smaf=[list(z) for _ in range(3)],
                    smas=[list(z) for _ in range(3)],
                    aroon=[(list(z), list(z)) for _ in range(4)],
                    regime=[1] * n8, pat_bull=[False] * n8, pat_bear=[False] * n8,
                    ob_bull=pad(ob_bull, False), ob_bear=pad(ob_bear, False),
                    fvg_bull=[False] * n8, fvg_bear=[False] * n8,
                    structure=pad(structure, 0))

    #            бар 0        бар 1         бар 2        бар 3
    #        только бычий  только медв.   оба сразу   ни одного
    a_ob = aux8([True, False, True, False], [False, True, True, False], [0] * 4)
    f_off = e8.make_filter8(ach.with_defaults(dict(ob_gate=0)), a_ob)
    f_hard = e8.make_filter8(ach.with_defaults(dict(ob_gate=1)), a_ob)
    f_soft = e8.make_filter8(ach.with_defaults(dict(ob_gate=2)), a_ob)
    hard_l = [f_hard("L", i) is not None for i in range(4)]
    hard_s = [f_hard("S", i) is not None for i in range(4)]
    soft_l = [f_soft("L", i) is not None for i in range(4)]
    print("     ob_gate: строгий L=%s S=%s | мягкий L=%s" % (hard_l, hard_s, soft_l))
    # Строгий режим (=1) обязан ТРЕБОВАТЬ ордер-блок своей стороны: лонг только
    # там, где ob_bull, шорт только там, где ob_bear. Ловит перепутанные
    # стороны в evolution8.py:57-61 («L» обязан смотреть в ob_bull).
    check(hard_l == [True, False, True, False] and hard_s == [False, True, True, False],
          "evolution8: ob_gate=1 требует ордер-блок СВОЕЙ стороны")
    # Мягкий режим (=2) запрещает только прямое противоречие, то есть обязан
    # быть строго слабее строгого: пропускает всё, что пропускает строгий, плюс
    # бар без данных. Если мягкий сравняется со строгим, ген перестанет быть
    # трёхзначным, а отбор — различать два разных механизма.
    check(soft_l == [True, False, True, True] and f_soft("S", 3) is not None,
          "evolution8: ob_gate=2 мягче строгого (запрещает лишь противоречие)")
    check(all(f_off(s, i) is not None for s in ("L", "S") for i in range(4)),
          "evolution8: ob_gate=0 не режет ничего")

    # structure_mode: 1 — торгуем ПО структуре, 2 — ПРОТИВ. Это обязано быть
    # точным зеркалом, иначе два значения гена — не «по» и «против», а два
    # разных фильтра, и сравнение их результатов в отборе ничего не значит.
    a_st = aux8([], [], [1, -1, 0, 1])
    f_with = e8.make_filter8(ach.with_defaults(dict(structure_mode=1)), a_st)
    f_vs = e8.make_filter8(ach.with_defaults(dict(structure_mode=2)), a_st)
    mirror = all((f_with("L", i) is not None) == (f_vs("S", i) is not None)
                 and (f_with("S", i) is not None) == (f_vs("L", i) is not None)
                 for i in range(4))
    print("     structure: по структуре L=%s | против структуры L=%s"
          % ([f_with("L", i) is not None for i in range(4)],
             [f_vs("L", i) is not None for i in range(4)]))
    check(mirror, "evolution8: structure_mode 1 и 2 — точное зеркало")
    # bias=0 значит «структура не определена»: по неопределённой структуре
    # нельзя торговать ни в ту, ни в другую сторону (бар 2).
    check(all(f("L", 2) is None and f("S", 2) is None for f in (f_with, f_vs)),
          "evolution8: при неопределённой структуре (bias=0) вход закрыт")

    # ========================================================================
    # patterns.py — compute_pattern_signals
    # ========================================================================
    # Что печатал старый тест: доля времени, когда сигнал активен, и число
    # переключений. Эти числа не меняются от заглядывания вперёд — а именно
    # заглядывание и есть главный риск модуля (см. большой комментарий у
    # patterns.build_zigzag: готовый зигзаг перерисовывается задним числом).
    #
    # Проверка 1: ПРИЧИННОСТЬ. Расчёт по префиксу истории обязан давать в
    # точности то же, что расчёт по всей истории — на всех барах префикса.
    # Живой бот зовёт функцию на хвосте истории; если бэктест видит будущее,
    # эти два ответа разойдутся. Ловит patterns.py:172 confirm = min(pb + w,
    # n - 1): убери «+ w» — и сигнал встанет на бар, где пивот ещё не
    # подтверждён и знать о нём нельзя.
    rnd = random.Random(7)
    px, walk = 100.0, []
    for i in range(420):
        o = px
        px *= 1 + rnd.gauss(0, 0.004)
        walk.append([TS + i * 900000, o,
                     max(o, px) * (1 + abs(rnd.gauss(0, 0.002))),
                     min(o, px) * (1 - abs(rnd.gauss(0, 0.002))), px])
    bull, bear = pt.compute_pattern_signals(walk, bars_per_day=48)
    causal, first_bad = True, None
    for k in (200, 300, 380):
        b2, r2 = pt.compute_pattern_signals(walk[:k], bars_per_day=48)
        for i in range(k):
            if b2[i] != bull[i] or r2[i] != bear[i]:
                causal, first_bad = False, (k, i)
                break
    print("     patterns: на 420 барах bull %d / bear %d баров, префиксы 200/300/380 %s"
          % (sum(bull), sum(bear),
             "совпали" if causal else "разошлись на %s" % (first_bad,)))
    check(sum(bull) > 0 and sum(bear) > 0,
          "patterns: на случайном блуждании сигналы вообще срабатывают")
    check(causal,
          "patterns: расчёт по префиксу = расчёт по всей истории (нет взгляда в будущее)")

    # Проверка 2: ФЛАГ — единственный кусок модуля с чисто арифметическим
    # правилом (patterns.py:229-238): импульс >= 2.2xATR, затем консолидация
    # <= 1.0xATR. Строим ровно такую фигуру: 70 баров тишины, 20 баров хода на
    # 1.2%, 11 баров сжатия. Сигнал обязан появиться РОВНО на баре 100 (раньше
    # в окно консолидации попадает импульсный бар) и смотреть В СТОРОНУ
    # импульса. Ловит и перевёрнутое направление, и распущенный порог.
    def flag(direction, seed=3):
        r = random.Random(seed)
        out, p = [], 100.0
        for i in range(70):
            o = p
            p = 100.0 + r.uniform(-0.03, 0.03)
            out.append(bar(i, o, max(o, p) + 0.02, min(o, p) - 0.02, p))
        base = p
        for i in range(70, 90):
            o = p
            p = base + direction * 1.2 * (i - 69) / 20.0
            out.append(bar(i, o, max(o, p) + 0.02, min(o, p) - 0.02, p))
        top = p
        for i in range(90, 101):
            o = p
            p = top + r.uniform(-0.02, 0.02)
            out.append(bar(i, o, max(o, p) + 0.01, min(o, p) - 0.01, p))
        return out

    fb, fr = pt.compute_pattern_signals(flag(+1), bars_per_day=20)
    db, dr = pt.compute_pattern_signals(flag(-1), bars_per_day=20)
    print("     флаг вверх: bull[95:101]=%s bear[95:101]=%s | флаг вниз: bear[95:101]=%s"
          % ([int(x) for x in fb[95:101]], [int(x) for x in fr[95:101]],
             [int(x) for x in dr[95:101]]))
    check(fb[100] and not any(fb[95:100]) and not any(fr[95:101]),
          "patterns: бычий флаг даёт bull ровно на баре сжатия и ничего медвежьего")
    check(dr[100] and not any(dr[95:100]) and not any(db[95:101]),
          "patterns: медвежий флаг зеркален бычьему")

    # ========================================================================
    # smc.py — find_fvg и find_order_blocks
    # ========================================================================
    # Что печатал старый тест: «bull активен X% времени». Процент остаётся
    # правдоподобным и когда бык с медведем переставлены местами, и когда
    # митигация зоны сломана — то есть не проверяет ничего.
    #
    # FVG по определению: разрыв low[i] > high[i-2] даёт бычью зону
    # [high[i-2], low[i]]; зона живёт, пока цена не ушла ниже её низа.
    def fvg_case(sign):
        cs = [bar(i, 100.0, 100.1, 99.9, 100.0) for i in range(11)]
        if sign > 0:
            cs.append(bar(11, 100.0, 103.0, 100.0, 103.0))   # импульсная свеча
            cs.append(bar(12, 103.0, 103.2, 102.5, 103.0))   # low 102.5 > high[10] 100.1
            cs.append(bar(13, 103.0, 103.1, 101.0, 101.5))   # вернулись ВНУТРЬ зоны
            cs.append(bar(14, 101.5, 101.6, 99.5, 99.6))     # прошли зону насквозь
            cs.append(bar(15, 99.6, 99.8, 99.4, 99.5))
        else:
            cs.append(bar(11, 100.0, 100.0, 97.0, 97.0))
            cs.append(bar(12, 97.0, 97.5, 96.8, 97.0))       # high 97.5 < low[10] 99.9
            cs.append(bar(13, 97.0, 99.0, 96.9, 98.5))
            cs.append(bar(14, 98.5, 100.5, 98.4, 100.4))
            cs.append(bar(15, 100.4, 100.6, 100.2, 100.3))
        return cs

    ub, ur = smc.find_fvg(fvg_case(+1), bars_per_day=5)
    db2, dr2 = smc.find_fvg(fvg_case(-1), bars_per_day=5)
    print("     FVG вверх: bull[11:16]=%s bear[12]=%d | вниз: bear[11:16]=%s bull[12]=%d"
          % ([int(x) for x in ub[11:16]], int(ur[12]),
             [int(x) for x in dr2[11:16]], int(db2[12])))
    # Ловит перепутанные стороны (smc.py:49-53 — бычий разрыв обязан лечь в
    # open_bull) и сломанную митигацию (smc.py:57-58): без неё зона переживёт
    # бар 14, и bull[14] останется True, хотя цена прошла зону насквозь.
    check(not ub[11] and ub[12] and ub[13] and not ub[14] and not ub[15] and not ur[12],
          "smc: бычий FVG живёт с бара разрыва до митигации и не путается с медвежьим")
    check(not dr2[11] and dr2[12] and dr2[13] and not dr2[14] and not db2[12],
          "smc: медвежий FVG зеркален бычьему")

    # Ордер-блок по определению — ПОСЛЕДНЯЯ ПРОТИВОПОЛОЖНАЯ свеча перед
    # импульсом. Два одинаковых сценария, отличающихся только свечой-кандидатом:
    # падающая (бычий ОБ обязан появиться и сработать на возврате цены) и
    # растущая (бычьего ОБ быть не должно вовсе).
    def ob_case(cand_up):
        cs = [bar(i, 100.0, 100.1, 99.9, 100.0) for i in range(12)]
        cs.append(bar(12, 99.8, 100.3, 99.7, 100.2) if cand_up
                  else bar(12, 100.2, 100.3, 99.7, 99.8))
        start = 100.2 if cand_up else 99.8
        p = start
        for k, i in enumerate(range(13, 18)):            # импульс вверх ~3.2%
            o = p
            p = start + 3.2 * (k + 1) / 5.0
            cs.append(bar(i, o, p + 0.05, o - 0.05, p))
        top = p
        for k, i in enumerate(range(18, 24)):            # возврат цены к зоне
            o = p
            p = top - 2.9 * (k + 1) / 6.0
            cs.append(bar(i, o, o + 0.05, p - 0.05, p))
        return cs

    ob_d, _ = smc.find_order_blocks(ob_case(False), bars_per_day=5)
    ob_u, _ = smc.find_order_blocks(ob_case(True), bars_per_day=5)
    print("     OB: кандидат-падение bull[18:24]=%s | кандидат-рост bull[18:24]=%s"
          % ([int(x) for x in ob_d[18:24]], [int(x) for x in ob_u[18:24]]))
    # Ловит подмену is_down_candle на is_up_candle (smc.py:79-83): зона
    # перестанет строиться на правильной свече и построится на неправильной.
    check(ob_d[23] and not any(ob_d[13:18]),
          "smc: бычий ордер-блок ставится на падающей свече и ждёт возврата цены")
    check(not any(ob_u[13:24]),
          "smc: растущая свеча перед импульсом вверх ордер-блоком НЕ считается")

    # ========================================================================
    # signal_engine.py — модель исполнения и издержек
    # ========================================================================
    # Что печатал старый тест: по строке на сетап (сделок, WR, итог, DD).
    # Эти числа зависят от данных и меняются от любой правки — по ним нельзя
    # сказать, что именно сломалось. Здесь — задача с ответом на бумаге.
    #
    # В докстринге модуля записано обещание: номинальный тейк 3R после издержек
    # стоит ~2.9R, а номинальный стоп -1R стоит ~-1.15R. Обещание публичное
    # (по этой же формуле считает историю advisor.py), но не закреплено ничем.
    LEV, MARGIN, DIST = 15, 5.0, 0.01
    REF, STOP, TP = 100.0, 99.0, 103.0        # стоп 1%, тейк 3R
    T, M, S, F = se.TAKER, se.MAKER, se.SLIP, se.FUND_8H
    ep = REF * (1 + S)                        # вход маркетом: слиппедж против нас
    qty = MARGIN * LEV / ep

    tp_path = [bar(0, 100.0, 100.5, 99.6, 100.4),
               bar(1, 100.4, 101.5, 100.2, 101.4),
               bar(2, 101.4, 103.5, 101.2, 103.2)]
    pnl_tp, _, why_tp = se.simulate_trade(
        "L", 0, STOP, TP, tp_path, [c[0] for c in tp_path], LEV, 96)
    fund_tp = sum(qty * c[4] * F / 32 for c in tp_path)
    # тейк — лимит по своей цене: слиппеджа нет, комиссия мейкерская
    want_tp = (TP - ep) * qty - qty * ep * T - qty * TP * M - fund_tp
    r_tp = se.r_multiple(pnl_tp, MARGIN, LEV, DIST)

    st_path = [bar(0, 100.0, 100.5, 99.6, 100.0),
               bar(1, 100.0, 100.2, 98.5, 98.7)]
    pnl_st, _, why_st = se.simulate_trade(
        "L", 0, STOP, TP, st_path, [c[0] for c in st_path], LEV, 96)
    fund_st = sum(qty * c[4] * F / 32 for c in st_path)
    # стоп — маркет: слиппедж В МИНУС и комиссия тейкерская
    xp = STOP * (1 - S)
    want_st = (xp - ep) * qty - qty * ep * T - qty * xp * T - fund_st
    r_st = se.r_multiple(pnl_st, MARGIN, LEV, DIST)
    print("     сделка со стопом 1%%: тейк %s R=%+.4f (ожидание %.8f, разница %.1e) | "
          "стоп %s R=%+.4f (ожидание %.8f, разница %.1e)"
          % (why_tp, r_tp, want_tp, pnl_tp - want_tp,
             why_st, r_st, want_st, pnl_st - want_st))
    # Ловит пропажу любой издержки: снят слиппедж входа или выхода, тейкер на
    # стопе заменён мейкером, забыт фандинг (signal_engine.py:~200-240).
    check(why_tp == "tp" and why_st == "stop"
          and abs(pnl_tp - want_tp) < 1e-12 and abs(pnl_st - want_st) < 1e-12,
          "signals: итог сделки = ход цены минус слиппедж, комиссии и фандинг (до цента)")
    # То же обещание в человеческих единицах — ровно как записано в докстринге.
    check(2.85 < r_tp < 2.93 and -1.20 < r_st < -1.13,
          "signals: тейк 3R стоит ~2.9R, а стоп -1R стоит ~-1.15R")

    # Консервативность исполнения: если стоп и тейк задеты ОДНОЙ 15м-свечой,
    # засчитывается стоп. Переставь местами проверки hit_stop/hit_tp — и
    # бэктест начнёт рисовать +3R там, где живая сделка могла закрыться в
    # минус; на числах старого теста это выглядело бы как «сетап стал лучше».
    both_l = [bar(0, 100.0, 100.2, 99.9, 100.0), bar(1, 100.0, 103.5, 98.5, 101.0)]
    _, _, why_l = se.simulate_trade(
        "L", 0, STOP, TP, both_l, [c[0] for c in both_l], LEV, 96)
    both_s = [bar(0, 100.0, 100.1, 99.8, 100.0), bar(1, 100.0, 101.5, 96.5, 99.0)]
    _, _, why_s = se.simulate_trade(
        "S", 0, 101.0, 97.0, both_s, [c[0] for c in both_s], LEV, 96)
    print("     стоп и тейк в одной свече: лонг -> %s, шорт -> %s" % (why_l, why_s))
