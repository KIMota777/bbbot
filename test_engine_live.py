    fund_tp = sum(qty * c[4] * F / 32 for c in tp_path)
    # тейк — лимит по своей цене: слиппеджа нет, комиссия мейкерская
    want_tp = (TP - ep) * qty - qty * ep * T - qty * TP * M - fund_tp
    r_tp = se.r_multiple(pnl_tp, MARGIN, LEV, DIST)

    st_path = [bar(0, 100.0, 100.5, 99.6, 100.0),
               bar(1, 100.0, 100.2, 98.5, 98.7)]
    pnl_st, _, why_st = se.simulate_trade(
        "L", 0, STOP, TP, st_path, [c[0] for c in st_path], LEV, 96)
    fund_st = sum(qty * c[4] * F / 32 for c in st_path)
    # стоп — маркет: слиппедж В МИНУС и комиссия тейкерская
    xp = STOP * (1 - S)
    want_st = (xp - ep) * qty - qty * ep * T - qty * xp * T - fund_st
    r_st = se.r_multiple(pnl_st, MARGIN, LEV, DIST)
    print("     сделка со стопом 1%%: тейк %s R=%+.4f (ожидание %.8f, разница %.1e) | "
          "стоп %s R=%+.4f (ожидание %.8f, разница %.1e)"
          % (why_tp, r_tp, want_tp, pnl_tp - want_tp,
             why_st, r_st, want_st, pnl_st - want_st))
    # Ловит пропажу любой издержки: снят слиппедж входа или выхода, тейкер на
    # стопе заменён мейкером, забыт фандинг (signal_engine.py:~200-240).
    check(why_tp == "tp" and why_st == "stop"
          and abs(pnl_tp - want_tp) < 1e-12 and abs(pnl_st - want_st) < 1e-12,
          "signals: итог сделки = ход цены минус слиппедж, комиссии и фандинг (до цента)")
    # То же обещание в человеческих единицах — ровно как записано в докстринге.
    check(2.85 < r_tp < 2.93 and -1.20 < r_st < -1.13,
          "signals: тейк 3R стоит ~2.9R, а стоп -1R стоит ~-1.15R")

    # Консервативность исполнения: если стоп и тейк задеты ОДНОЙ 15м-свечой,
    # засчитывается стоп. Переставь местами проверки hit_stop/hit_tp — и
    # бэктест начнёт рисовать +3R там, где живая сделка могла закрыться в
    # минус; на числах старого теста это выглядело бы как «сетап стал лучше».
    both_l = [bar(0, 100.0, 100.2, 99.9, 100.0), bar(1, 100.0, 103.5, 98.5, 101.0)]
    _, _, why_l = se.simulate_trade(
        "L", 0, STOP, TP, both_l, [c[0] for c in both_l], LEV, 96)
    both_s = [bar(0, 100.0, 100.1, 99.8, 100.0), bar(1, 100.0, 101.5, 96.5, 99.0)]
    _, _, why_s = se.simulate_trade(
        "S", 0, 101.0, 97.0, both_s, [c[0] for c in both_s], LEV, 96)
    print("     стоп и тейк в одной свече: лонг -> %s, шорт -> %s" % (why_l, why_s))
    check(why_l == "stop" and why_s == "stop",
          "signals: стоп и тейк в одной свече — засчитывается стоп")

    # Пустое экзаменационное окно — незачёт, а не ничья (signal_engine.oos_score).
    # Именно из-за нуля вместо штрафа range_long прошёл отбор по одному
    # информативному фолду из трёх. Мало сравнить балл с самой константой
    # штрафа: сдвинь её к -0.001 — и «незачёт» снова станет ничьей, а такое
    # сравнение останется зелёным. Поэтому закреплены и величина штрафа, и
    # порог, и то, что нормальное окно получает БОЛЬШЕ штрафного.
    def window(n_trades):
        return dict(trades=[dict(pnl=1.0, hold_h=1.0) for _ in range(n_trades)],
                    monthly={0: 1.0, 1: 1.0, 2: 1.0}, months=3.0, ruined=False)

    thin, fat = window(se.OOS_MIN_TRADES - 1), window(se.OOS_MIN_TRADES + 20)
    print("     балл окна: %d сделок -> %.2f, %d сделок -> %.2f (штраф %.1f, порог %d)"
          % (se.OOS_MIN_TRADES - 1, se.oos_score(thin),
             se.OOS_MIN_TRADES + 20, se.oos_score(fat),
             se.OOS_THIN_PENALTY, se.OOS_MIN_TRADES))
    check(se.OOS_THIN_PENALTY <= -1.0 and 3 <= se.OOS_MIN_TRADES <= 20,
          "signals: штраф за прогул ощутим, а порог «окно — не экзамен» на месте")
    check(se.oos_score(thin) == se.OOS_THIN_PENALTY
          and se.oos_score(fat) > se.OOS_THIN_PENALTY,
          "signals: окно с малым числом сделок получает штраф, а не ноль")


