def build_evs(d, g, setup="dump_long"):
    """Разбор ворот на КАЖДОМ баре (считаем один раз, правила фильтруют)."""
    ext = se3.build_ext(setup, g, d["c4"], interval_min=TF)
    evs = [se3.gate_eval(setup, i, d["c4"], d["ctx"], g, ext)
           for i in range(len(d["c4"]))]
    return evs, ext


def signal_bars(evs, lo, hi):
    """Бары, на которых прошли ВСЕ ворота сетапа, в диапазоне [lo, hi)."""
    return [i for i in range(max(0, lo), min(hi, len(evs))) if evs[i]["ok"]]


