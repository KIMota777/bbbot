def run_bars(d, g, evs, ext, rng_bars, decide, lev=LEV, setup="dump_long",
             start=None, ruin=False):
    """Цикл сделок: механика движка (se3._make_trade), а бар входа выбирает
    предикат decide(i). Одна позиция за раз, кулдаун по геному.

    ruin=True воспроизводит остановку торговли при балансе < MARGIN (нужно
    для сверки с se3.run_setup и для оценки разорения); при измерении
    СИГНАЛА ruin=False, иначе выборка обрывается управлением капиталом."""
    bar_ms = se2.bar_ms_of(TF)
    a, b = rng_bars
    a = max(int(a), int(ext["warm"]))
    b = min(int(b), len(d["c4"]))
    start = se3.START if start is None else float(start)
    balance, peak, max_dd = start, start, 0.0
    trades = []
    busy_until = last_exit = 0
    ruined = False
    cool_ms = int(se3._gg(g, "cooldown")) * bar_ms
    for i in range(a, b):
        ev_ = evs[i]
        if ev_.get("stop") is None or not decide(i):
            continue
        sig_ts = d["c4"][i][0] + bar_ms
        if ruined or sig_ts < busy_until:
            continue
        if last_exit and sig_ts < last_exit + cool_ms:
            continue
        tr, why = se3._make_trade(setup, ev_, i, d["c4"], d["ctx"], g,
                                  d["c15"], d["ts15"], lev, bar_ms=bar_ms,
                                  trail15=None)
        if tr is None:
            if why == se3.REJ_NO15M:
                break
            continue
        tr["symbol"] = d["sym"]
        tr["bar_i"] = i
        balance += tr["pnl"]
        peak = max(peak, balance)
        if peak > 0:
            max_dd = max(max_dd, (peak - balance) / peak)
        trades.append(tr)
        busy_until = last_exit = tr["exit_ts"]
        if ruin and balance < se3.MARGIN:
            ruined = True
    return dict(trades=trades, balance=balance, max_dd=max_dd, ruined=ruined,
                bars=(a, b))


def run_config(d, g, evs, ext, rng_bars, lev=LEV, use_void=False):
    """Прогон итоговой конфигурации: сигналы сетапа (+ фильтр пустоты V2)."""
    if use_void:
        return run_bars(d, g, evs, ext, rng_bars,
                        lambda i: evs[i]["ok"] and void_ok(d, i, g), lev=lev)
    return run_bars(d, g, evs, ext, rng_bars, lambda i: evs[i]["ok"], lev=lev)


