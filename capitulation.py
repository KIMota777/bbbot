# --------------------------------------------------------- профиль объёма
def _bkt(p):
    """Индекс ценовой корзины в ЛОГ-шкале: одинаковая ОТНОСИТЕЛЬНАЯ ширина
    корзины на любой монете (BTC 60000 и DOGE 0.15 меряются одинаково)."""
    return int(math.floor(math.log(p) / LOG_STEP))


def volume_profile(vb, i_hi, n_bars):
    """Профиль объёма по барам (i_hi-n_bars, i_hi]. Оборот бара размазан
    равномерно по корзинам между его low и high (стандартное приближение
    при отсутствии тиковых данных)."""
    prof = {}
    a = max(0, i_hi - n_bars + 1)
    for k in range(a, i_hi + 1):
        row = vb[k]
        l, h, t = row[3], row[2], row[6]
        if t <= 0 or l <= 0:
            continue
        b0, b1 = _bkt(l), _bkt(h)
        share = t / (b1 - b0 + 1)
        for b in range(b0, b1 + 1):
            prof[b] = prof.get(b, 0.0) + share
    return prof


def density(prof, px, atr_abs):
    """Плотность объёма в полосе +-BAND_ATR*ATR вокруг px, нормированная на
    среднюю плотность профиля. 1.0 = средняя, >1 — объёмный уровень, <1 —
    пустота. Безразмерна, сравнима между монетами и окнами."""
    if not prof or px <= 0 or atr_abs <= 0:
        return None
    tot = sum(prof.values())
    if tot <= 0:
        return None
    b_min, b_max = min(prof), max(prof)
    n_span = b_max - b_min + 1
    band = BAND_ATR * atr_abs
    lo_b = _bkt(max(px - band, px * 0.5))
    hi_b = _bkt(px + band)
    v_band = sum(prof.get(b, 0.0) for b in range(lo_b, hi_b + 1))
    n_band = hi_b - lo_b + 1
    return (v_band / n_band) / (tot / n_span)


def dump_low_of(d, i, g):
    """Минимум падения: минимум low за окно drop_days включая бар i.
    Ровно то место, «за которым» ставится стоп в описании сетапа."""
    d_bars = max(1, int(g["drop_days"]) * BARS_DAY)
    a = max(0, i - d_bars)
    return min(d["lows"][a:i + 1])


def void_dens(d, i, g):
    """Плотность объёма у минимума падения по профилю за PROF_DAYS суток,
    окно которого заканчивается ПЕРЕД началом падения.

    Якорь «ДО» принципиален: если окно кончается на сигнальном баре, профиль
    увидит объём САМОГО падения (его же и наторговали) и «упёрлись в объём»
    станет частично тавтологией. Гипотеза владельца — «отскок от ЗАРАНЕЕ
    существовавшего уровня» — проверяется только якорем «ДО».
    Возвращает None, если объёмной истории ещё нет (первые ~90 суток)."""
    d_bars = max(1, int(g["drop_days"]) * BARS_DAY)
    if i - d_bars < 0:
        return None
    atr_b = d["ctx"]["atr_bar"][i]
    if not atr_b:
        return None
    px = d["c4"][i][4]
    atr_abs = atr_b * px
    # только бары объёма, ЗАКРЫТЫЕ до начала падения (заглядывания нет)
    j = bisect.bisect_right(d["vts"], d["c4"][i - d_bars][0] - MS_1H) - 1
    if j < 20:
        return None
    prof = volume_profile(d["vb"], j, PROF_DAYS * 24)
    return density(prof, dump_low_of(d, i, g), atr_abs)


def void_ok(d, i, g, thr=VOID_THR):
    """Фильтр V2: входим, только если минимум падения НЕ упёрся в объёмный
    кластер. Неизвестная плотность (нет истории объёма) сделку не запрещает —
    иначе фильтр молча вырезал бы начало выборки."""
    v = void_dens(d, i, g)
    return v is None or v < thr


